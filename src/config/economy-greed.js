// Числа мини-игры «алчность»: кусок ECONOMY.minigames, вынесенный из
// economy.js, чтобы под правку баланса одного греха не открывать весь
// конфиг. Подключается сразу после economy.js (index.html и
// tools/economy-src.js для калькуляторов).

// ---------- АЛЧНОСТЬ: АВТОМАТ ----------
// Замысел — docs/plan/16-greed-slots.md, числа проверяет
// tools/sim-slots.js ПО ЭТОМУ конфигу (правило проекта: калькулятор
// считает по живому, а не по своей копии).
//
// Единственный грех, который не платит игроку, а берёт с него.
// Крутка стоит монету, и это НЕ ставка в казино, а сток золота:
// возврат заведомо меньше сотни, иначе лучшей стратегией в игре
// становится «сидеть и крутить», и вся остальная экономика
// обесценивается (docs/plan/15-progression.md, раздел 10).
//
// Ключевое: шкалу наливает КАЖДАЯ крутка, чем бы она ни кончилась.
// Поэтому крутка небесполезна никогда, а золото — драма сверху, а не
// условие закрытия потребности.
ECONOMY.minigames.greed = {
    spinCost: 1,        // крутка стоит монету
    fillPerSpin: 10,    // и наливает столько шкалы — десять круток на полную
    // Коридор возврата. Не используется игрой: это цель, по которой
    // sim-slots.js ругается, если выплаты уехали.
    rtpMin: 0.60,
    rtpMax: 0.80,

    // ---------- БАРАБАН ----------
    // weight — ВИРТУАЛЬНЫЕ позиции, как в автоматах после патента
    // Телнеса (1984): шанс задаёт вес, а не число картинок на
    // барабане. Барабан один на все три.
    //
    // pay — сколько платит ТРОЙКА этого символа. Числа не круглые:
    // сначала выбран возврат, потом под него подогнаны выплаты, а не
    // наоборот (docs/plan/16-greed-slots.md, раздел 5).
    //
    // Веса РОВНЫЕ. «Почти выигрыши» — когда пустые позиции нарочно
    // ставят рядом с джекпотом, чтобы барабан чаще замирал в шаге от
    // него — мы не подкручиваем сознательно: это крючок для
    // зависимости, а не игровая механика.
    //
    // alt — ВТОРОЙ ПУЛ тройки: когда она выпала, с шансом chance она платит
    // не монетами, а give (docs/plan/28-greed-machine.md, разд. 5). Бросок
    // идёт ПОСЛЕ выбора тройки, а не отдельным символом на барабане: поделить
    // вес символа пополам значило бы уронить шанс его тройки вчетверо.
    // Барабаны при жетонном исходе встают на тройку altKey — игрок видит,
    // чем ему заплатили.
    reel: [
        { key: 'skull', weight: 1,  pay: 66 },
        { key: 'coin',  weight: 10, pay: 13 },
        { key: 'meat',  weight: 10, pay: 7,
          alt: { chance: 0.5, altKey: 'token', give: { greed_token: 1 } } },
        { key: 'bone',  weight: 12, pay: 3,
          alt: { chance: 0.5, altKey: 'shard', give: { greed_shard: 1 } } },
        { key: 'blank', weight: 7,  pay: 0 }
    ],
    // Мелкий выигрыш: две монеты возвращают ровно ставку, как две
    // подковы у Фея. Денег не приносит, но по ощущению это «не
    // проиграл», и случается в каждой седьмой крутке.
    pair: { key: 'coin', pay: 1 },

    // ---------- ГАРАНТИЯ ПРОТИВ ТИЛЬТА ----------
    // Больше пяти пустых круток подряд не бывает: шестая платит.
    // В настоящем автомате такого нет и быть не может — там каждая
    // крутка независима. У нас игра, а не касса.
    //
    // Гарантия не выдаёт деньги «из воздуха», а ПОДМЕНЯЕТ ИСХОД:
    // барабаны встают на тройку key, и игрок видит, за что заплатили.
    // Иначе монеты падали бы при пустых барабанах — в игре без слов
    // это читалось бы как поломка.
    pity: { spins: 6, key: 'bone' },

    // ---------- СТАВКИ ----------
    // Ставка — множитель ВСЕГО: цены крутки и каждой награды, жетонов и вещей
    // тоже. Шансы от неё не меняются, шкалу она не наливает сильнее: крутка
    // есть крутка (docs/plan/28-greed-machine.md, разд. 4). До апгрейда
    // игры доступна только первая.
    //
    // Отложено до общего баланса: на ставке 100 жетонная тройка даёт сотню
    // жетонов. Ручки — в плане, там же.
    bets: [1, 3, 10, 100],
    betsAtLevel: 2,

    // ---------- ЦЕНА ЖЕТОНОВ В МОНЕТАХ ----------
    // Только для калькулятора: возврат колеса и пачинко считается в золотом
    // эквиваленте, а для этого у жетона должна быть цена. У жетона алчности
    // она выведена из бандита (~30 монет чистой потери на жетон). У жетонов
    // остальных грехов это ЗАГЛУШКА до общего баланса: сколько стоит жетон в
    // своей игре, ещё никто не мерил.
    tokenValue: {
        greed_token: 30, greed_shard: 10,
        wrath_token: 30, wrath_shard: 10,
        glut_token: 30,  glut_shard: 10,
        sloth_token: 30, sloth_shard: 10,
        lust_token: 30,  lust_shard: 10,
        envy_token: 30,  pride_token: 30
    },

    // ---------- ИГРЫ АППАРАТА: ОТКРЫТИЕ И АПГРЕЙД ----------
    // Общий станок прокачки (Backend.buyUpgrade(key, 'greed')). Значение
    // ветки — УРОВЕНЬ игры: 0 закрыта, 1 открыта, 2 апгрейд (новый вид и
    // большие ставки). Бандит есть с начала, поэтому у него base 1 и одна
    // ступень.
    //
    // Алчность жрёт все валюты: каждая цена — жетоны алчности ПЛЮС жетоны
    // всех остальных грехов (разд. 3 плана). Ступеней всего пять, поэтому
    // они дорогие. Числа ориентировочные.
    upgrades: {
        slots: { base: 1, levels: [
            { bonus: 2, price: { greed_token: 10, wrath_token: 2, glut_token: 2, sloth_token: 2,
                                 lust_token: 2, envy_token: 2, pride_token: 2 } }
        ] },
        wheel: { base: 0, levels: [
            { bonus: 1, price: { greed_token: 7, wrath_token: 1, glut_token: 1, sloth_token: 1,
                                 lust_token: 1, envy_token: 1, pride_token: 1 } },
            { bonus: 2, price: { greed_token: 15, wrath_token: 3, glut_token: 3, sloth_token: 3,
                                 lust_token: 3, envy_token: 3, pride_token: 3 } }
        ] },
        pachinko: { base: 0, levels: [
            { bonus: 1, price: { greed_token: 12, wrath_token: 2, glut_token: 2, sloth_token: 2,
                                 lust_token: 2, envy_token: 2, pride_token: 2 } },
            { bonus: 2, price: { greed_token: 20, wrath_token: 4, glut_token: 4, sloth_token: 4,
                                 lust_token: 4, envy_token: 4, pride_token: 4 } }
        ] }
    },

    // ---------- КОЛЕСО ФОРТУНЫ ----------
    // Пул вещей: монеты, продукты в кладовую, семена в мешок, осколок
    // алчности. Крутка стоит столько же, сколько у бандита, и так же
    // наливает шкалу.
    //
    // Сектор даёт ОДНО из: give (валюта), pantry (продукт кухни) или seed
    // (семечка сада). value — монетная цена вещи: по ней калькулятор
    // считает возврат, и ЕЮ ЖЕ платится вещь, если склад полон
    // (разд. 6 плана) — тогда на возврат полный склад не влияет вовсе.
    //
    // weight — шанс, а не ширина сектора на картинке: рисовать сектора
    // можно ровными, как у настоящего колеса.
    wheel: {
        sectors: [
            { key: 'blank',  weight: 51 },
            { key: 'gold1',  weight: 25, give: { gold: 1 } },
            { key: 'gold3',  weight: 5,  give: { gold: 3 } },
            { key: 'meat',   weight: 5,  pantry: 'rib', n: 1, value: 2 },
            { key: 'seed',   weight: 12, seed: 'potato', n: 1, value: 0.5 },
            { key: 'shard',  weight: 2,  give: { greed_shard: 1 } }
        ]
    },

    // ---------- ПАЧИНКО ----------
    // Пул жетонов ВСЕХ грехов вперемешку: нужный не выбить прицельно, зато
    // игра нужна и после того, как ветка алчности закрыта (разд. 7 плана).
    //
    // Условие баланса: жетон отсюда в среднем ДОРОЖЕ, чем в своей игре, —
    // иначе гнев и похоть обесценятся. У зависти и тщеславия осколков нет,
    // поэтому их лузы платят целым жетоном, но втрое реже.
    pachinko: {
        pockets: [
            { key: 'blank',  weight: 761 },
            { key: 'gold1',  weight: 200, give: { gold: 1 } },
            { key: 'wrath',  weight: 7,   give: { wrath_shard: 1 } },
            { key: 'glut',   weight: 7,   give: { glut_shard: 1 } },
            { key: 'sloth',  weight: 7,   give: { sloth_shard: 1 } },
            { key: 'lust',   weight: 7,   give: { lust_shard: 1 } },
            { key: 'greed',  weight: 7,   give: { greed_shard: 1 } },
            { key: 'envy',   weight: 2,   give: { envy_token: 1 } },
            { key: 'pride',  weight: 2,   give: { pride_token: 1 } }
        ]
    }
};
