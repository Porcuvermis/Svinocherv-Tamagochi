    //   * keepBlank — сколько пустых остаётся всегда (доля от пустых при
    //     ставке 1): «каждый раз вещь» — скучно.
    //   * Степень своя у игры: у колеса вещи и так частые (27% круток), и при
    //     ½ пустые кончались уже к ставке 10 — ставка 100 ничего бы не
    //     прибавляла; у бандита и пачинко вещи редкие — им круче.
    // Вещь на высокой ставке ДОРОЖЕ в золоте, чем на первой (бандит: жетон
    // ~24 монеты чистой потери на ставке 1, ~280 на ставке 100): скупать
    // вещи высокой ставкой невыгодно — она про скорость и азарт, а не про
    // выгоду. Расчёт — tools/sim-slots.js, раздел «ставки».
    betItems: { slots: 0.5, wheel: 0.3, pachinko: 0.5, keepBlank: 0.1 },

    // ---------- ЦЕНА ЖЕТОНОВ В МОНЕТАХ ----------
