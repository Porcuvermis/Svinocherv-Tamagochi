    // игры доступна только первая.
    //
    // Отложено до общего баланса: на ставке 100 жетонная тройка даёт сотню
    // жетонов. Ручки — в плане, там же.
    bets: [1, 3, 10, 100],
    // 20.11 (игрок): ставки — и у гаражного аппарата, с самого начала
    // (стикер на монетоприёмнике: тап — отрывается, под ним следующий)
    betsAtLevel: 1,

    // ---------- СТАВКА И ВЕЩИ (20.11, игрок) ----------
    // Было: ставка множила ВСЁ — на ставке 100 жетонная тройка давала сотню
    // жетонов, одна удачная крутка прокачивала игру целиком, а пачинко
    // сыпало сотни осколков других грехов. Теперь ставка множит ТОЛЬКО
    // золото; вещи (жетон, осколок, продукт, семечка) выпадают по одной, а
    // растёт их ШАНС: как будто крутка на ставке b — это t = b^степень
