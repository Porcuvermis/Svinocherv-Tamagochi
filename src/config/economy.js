// ================= КОНФИГ ЭКОНОМИКИ (единственный источник чисел) =================
// Все числа баланса живут здесь и больше нигде. Мини-игра не решает, сколько
// себе начислить — она сообщает результат, а что за него дать, написано тут.
//
// Почему так. Раньше каждая мини-игра сама делала
// `GameManager.sins.<грех>.value = 100`, то есть правила начисления были
// размазаны по семи файлам. Поменять баланс означало обойти их все, а новая
// мини-игра могла молча выдать себе что угодно.
//
// Этот файл сознательно написан как ДАННЫЕ без логики: когда появится
// сервер, он переезжает туда целиком и становится серверным конфигом наград
// (см. docs/plan/01-architecture.md, раздел 3.3 — клиент не говорит
// «начисли мне N», сервер сам смотрит в свой конфиг).

const ECONOMY = {
    version: 1,

    // ---------- ГРЕХИ ----------
    // drainHours — за сколько часов полная шкала опустошается сама.
    //
    // Раньше здесь стояли decay 0.3…1.2, вычитаемые дважды в секунду, то есть
    // шкала пустела за 42–167 СЕКУНД. Пока время шло только при открытой игре,
    // это работало как темп внутри сессии. Теперь время реальное и идёт при
    // закрытом приложении (docs/plan/05-next-steps.md, п. 1.2), поэтому темп
    // задаётся в часах: вышел на обед — вернулся не к нулям.
    //
    // Разброс осмысленный: чревоугодие требует заходить дважды в день,
    // лень живёт двое суток.
    sins: {
        gluttony: { name: 'Чревоугодие', emoji: '🍖', color: '#FF9500', max: 100, drainHours: 8 },
        wrath:    { name: 'Гнев',        emoji: '🤬', color: '#FF3B30', max: 100, drainHours: 10 },
        lust:     { name: 'Похоть',      emoji: '💋', color: '#FF69B4', max: 100, drainHours: 12 },
        greed:    { name: 'Алчность',    emoji: '💰', color: '#4CAF50', max: 100, drainHours: 16 },
        pride:    { name: 'Гордыня',     emoji: '👑', color: '#FFD700', max: 100, drainHours: 24 },
        envy:     { name: 'Зависть',     emoji: '🍏', color: '#00FF7F', max: 100, drainHours: 30 },
        sloth:    { name: 'Лень',        emoji: '🦥', color: '#8E8E93', max: 100, drainHours: 48 }
    },

    // ---------- ПОРЯДОК В ИНТЕРФЕЙСЕ ----------
    // Отдельно от объекта выше: порядок обхода ключей объекта — вещь, на
    // которую полагаться нельзя, а порядок кружков в HUD менять не хочется.
    sinOrder: ['pride', 'greed', 'envy', 'wrath', 'lust', 'gluttony', 'sloth'],

    // ---------- НАГРАДЫ ЗА РЕЗУЛЬТАТ МИНИ-ИГРЫ ----------
    // Ищется rewards[грех][режим][исход], если нет — rewards.default.
    //
    //   sinFill: 'full'  — заполнить шкалу до максимума
    //   sinFill: 20      — добавить 20 единиц (не больше максимума)
    //   currencies       — что начислить в кошелёк
    //
    // Шесть мини-игр пока одноразовые: прошёл — шкала полная. Гнев уже
    // умеет три исхода, поэтому расписан подробно.
    rewards: {
        default: { sinFill: 'full' },

        // Чревоугодие не просто заполняет шкалу: червя реально покормили,
        // значит запускается пищеварение.
        gluttony: {
            feast: { win: { sinFill: 'full', feeds: true } }
        },

        wrath: {
            duel: {
                // Победа втрое выгоднее поражения — сливать бой невыгодно,
                // но и поражение даёт прогресс (docs/plan/03-wrath.md).
                win:  { sinFill: 'full', currencies: { wrath_shard: 1 } },
                draw: { sinFill: 50 },
                // Поражение оставляет след на теле. Не наказание: шрамы не
                // дают боевых штрафов, это летопись — по ней видно, что червь
                // дрался и проигрывал (docs/plan/03-wrath.md).
                lose: { sinFill: 20, mark: { kind: 'scar', chance: 0.3 } }
            }
        }
    },

    // ---------- ВАЛЮТЫ ----------
    // Порядок и подписи для будущего HUD кошелька. Золото и кристаллы
    // появятся вместе с ним (этап 1), поэтому наград в них пока нет —
    // пустых обещаний в конфиге не держим.
    currencies: {
        gold:        { name: 'Золото',      emoji: '🪙' },
        crystal:     { name: 'Кристалл',    emoji: '💎' },
        wrath_shard: { name: 'Осколок гнева', emoji: '🩸' }
    },

    // ---------- ПИЩЕВАРЕНИЕ ----------
    // Покормили — по пищеводу от головы к желудку идут несколько кусков еды,
    // потом час переваривания, потом один комок уходит к хвосту, и червь
    // какает. Всё это считается от одной метки времени (когда покормили), а
    // не тикающим таймером: цикл длиннее часа, приложение за это время сто
    // раз закроется, и «переваривание, пока смотрят» — не то, что нужно.
    digestion: {
        bites: 3,              // сколько кусков заглатывается за кормёжку
        swallowSeconds: 15,    // от головы до желудка
        stomachMinutes: 50,    // сколько лежит в желудке
        bowelMinutes: 10,      // от желудка до хвоста
        biteGapSeconds: 2.5    // задержка между соседними кусками
    },

    // ---------- ОТМЕТИНЫ НА ТЕЛЕ ----------
    marks: {
        // Сколько шрамов меняются на один жетон гнева. Порог выбран так,
        // чтобы шрамы копились неделями и червь реально зарастал, а обмен
        // был редким осознанным событием («мне надоел этот вид»), а не
        // источником дохода. Сам обмен — этап 2.
        scarsPerToken: 15
    },

    // ---------- ОФФЛАЙН ----------
    // Доход при возвращении копится не бесконечно, иначе выгодно не заходить.
    // Падение шкал потолка не имеет — только пол в нуле.
    offline: {
        incomeCapHours: 8
    }
};

// Скорость падения в единицах в секунду. Считается из drainHours, чтобы
// в конфиге стояло понятное «за сколько часов», а не 0.00347.
function sinDecayRate(sinKey) {
    const sin = ECONOMY.sins[sinKey];
    if (!sin) return 0;
    return sin.max / (sin.drainHours * 3600);
}

if (typeof window !== 'undefined') {
    window.ECONOMY = ECONOMY;
    window.sinDecayRate = sinDecayRate;
}
