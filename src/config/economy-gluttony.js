// Числа мини-игры «чревоугодие»: кусок ECONOMY.minigames, вынесенный из
// economy.js, чтобы под правку баланса одного греха не открывать весь
// конфиг. Подключается сразу после economy.js (index.html и
// tools/economy-src.js для калькуляторов).

// ---------- ЧРЕВОУГОДИЕ: КУХНЯ ----------
// Замысел — docs/plan/20-gluttony-kitchen.md. Здесь только УТВАРЬ:
// то, что покупается в приложении на телефоне (раздел 7) и остаётся
// навсегда. Расходуемые продукты живут в KITCHEN.shop.food — там же,
// где сами ингредиенты, и по той же причине: это данные кухни.
//
// ---------- ПОЧЕМУ ОБЩИЙ СТАНОК ПРОКАЧКИ ----------
// Форма levels[{price, bonus}] и база base — те же, что у гнева и
// тщеславия, поэтому покупку делает существующий Backend.buyUpgrade,
// а текущее значение отдаёт Backend.upgradeValue. Своей машинки у
// кухни нет и заводить её нельзя: три копии одного механизма — это
// ровно то, из-за чего в проекте появился docs/traps.md.
//
// ---------- ЧТО ЭТО ЧИНИТ ----------
// Стартовая готовка намеренно медленная (план, раздел 2): двенадцать
// взмахов ножом и шесть качелей ложкой. Если бы её сразу сделали
// удобной, покупать было бы нечего. Лестница ниже — это ровно та
// возня, которую игрок выкупает обратно.
//
// ---------- ПОЧЕМУ СТУПЕНЕЙ МНОГО, А ШАГ МЕЛКИЙ ----------
// Первая версия была короткой и крутой: по две ступени на ветку,
// цена вдвое за ступень. Вся кухня выкупалась за месяц — то есть на
// второй месяц игры покупать становилось нечего вовсе.
//
// Удлинять её ценой нельзя: ступеней шесть, и, чтобы растянуть их на
// полгода, последняя должна стоить месяц накоплений. Это и есть та
// тишина, в которой игрок уходит.
//
// Поэтому растянуто КОЛИЧЕСТВОМ: двадцать одна ступень вместо шести,
// шаг величины мельче (нож теряет по одному взмаху, а не по четыре),
// цена растёт примерно в 1.35 раза за ступень вместо двойки. Кухня
// занимает те же полгода-год, но покупка случается раз в неделю-две,
// а не раз в месяц. Правило и его проверка —
// docs/plan/15-progression.md, раздел 4а и tools/sim-progression.js.
//
// Потолок ступени тоже не на глаз: она не должна копиться дольше
// трёх недель даже у среднего игрока, иначе ветка читается тупиком.
