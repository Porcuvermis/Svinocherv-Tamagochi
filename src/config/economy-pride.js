// economy.js, чтобы под правку баланса одного греха не открывать весь
// конфиг. Подключается сразу после economy.js (index.html и
// tools/economy-src.js для калькуляторов).

// ---------- ТЩЕСЛАВИЕ: КОВРОВАЯ ДОРОЖКА ----------
// Замысел — docs/plan/17-pride.md. Числа считает tools/sim-pride.js,
// и считает ПО ЭТОМУ конфигу, а не по своей копии.
//
// Правило игры в одну строку: множитель растят ТОЛЬКО белые зоны
// (вспышки в толпе), платят ТОЛЬКО розовые (поцелуи на черве), и
// розовые вообще не появляются, пока не закрыта хотя бы одна белая.
// Отсюда порядок: сначала заводишь толпу, потом собираешь урожай.
ECONOMY.minigames.pride = {
    runMs: 20000,          // сколько длится выход — дорожка ровно на столько

    // ---------- ЧАСТОТА ЗОН: СКРЫТАЯ РУЧКА ----------
    // Отдельной покупки «зоны чаще» больше нет. Частоту двигает ЛЮБАЯ
    // купленная ступень любой линии: каждая отнимает от интервала
    // spawnStep миллисекунд. Смысл в том, что прокачка ощущается
    // сильнее, чем обещает ценник: игрок покупает ширину зоны, а
    // выход в целом становится гуще и живее.
    //
    // Пол интервала — ФИЗИЧЕСКИЙ ПРЕДЕЛ ПАЛЬЦА: человек устойчиво
    // закрывает около двух с половиной зон в секунду, и всё, что
    // сыплется сверх, гаснет само (docs/traps.md, п. 53). Ниже
    // spawnFloor поэтому не опускаемся ни при какой прокачке.
    spawnBase: 620,        // мс между зонами без единой покупки
    spawnStep: 8,          // на столько короче за КАЖДУЮ купленную ступень
    spawnFloor: 430,       // короче не бывает: дальше палец не успевает
    // ---------- КОМУ ДОСТАЁТСЯ СЛЕДУЮЩАЯ ЗОНА ----------
    // Не «бросок монетки на каждую зону», а МЕШОК: из `of` зон ровно
    // `kisses` поцелуйных, порядок случайный, тянем без возврата,
    // кончился — набираем заново. Разница с монеткой не в среднем, а
    // в хвостах: монетка регулярно выдаёт выход, где поцелуев почти
    // не было, и игрок винит в этом себя, хотя не виноват. Мешок
    // такого не умеет — за каждые четыре зоны своё придёт.
    //
    // Доля ФИКСИРОВАННАЯ. Раньше она зависела от ажиотажа (разогретая
    // толпа целовалась вдвое чаще), но теперь тем же занят стрик, и
    // занят жёстче: при нулевом стрике поцелуйных зон нет ВООБЩЕ.
    // Две ручки на одно и то же — это не баланс, а шум.
    kissBag: {
        of: 4,             // сколько зон в мешке
        kisses: 1          // сколько из них поцелуйных
    },
    maxTargets: 8,         // предохранитель: больше стольких зон не держим.
                           // Не ручка сложности, а страховка от пачки:
                           // сложность задаёт интервал, а этот потолок
                           // просто не должен резать верхнюю ступень
                           // массовки (при 430 мс на экране их ~4–6)

    // ---------- СТРИК ----------
    // Ажиотажа больше нет. Есть СТРИК — сколько белых зон закрыто
    // подряд, и он же множитель: закрыл три вспышки подряд — поцелуй
    // стоит три, но не больше, чем разрешает машина.
    //
    // Три правила, и каждое поставлено нарочно:
    //
    //   • растят стрик ТОЛЬКО белые зоны. Поцелуй его УДЕРЖИВАЕТ (это
    //     не промах), но не растит: иначе деньги сами себя дорожают и
    //     вспышки становятся не нужны;
    //   • пока стрик нулевой, ПОЦЕЛУЙНЫХ ЗОН НЕТ. Червя никто не
    //     целует, пока толпа не завелась. Это и есть вся связка между
    //     двумя типами зон: белые открывают кран, розовые из него
    //     льют;
    //   • рвёт стрик ЛЮБАЯ незакрытая зона — и тап в пустоту, и та,
    //     что погасла сама.
    //
    // Последнее правило раньше было мягче (погасшая зона только
    // проседала), и мягче оно было не от доброты: зон бывает больше,
    // чем успевает палец, и рвать за это значит наказывать за
    // купленную прокачку. Теперь этот тормоз держит не разница
    // наказаний, а spawnFloor — интервал не опускается ниже того, что
    // палец физически закрывает.
    streak: {
        perHit: 1,         // на сколько растёт стрик за белую зону
        needForKiss: 1,    // с какого стрика червя начинают целовать
        breakOnMiss: true, // погасшая зона рвёт серию
        breakOnMissclick: true  // тап в пустоту тоже
    },

    // ---------- ТРИ ПОКУПКИ ----------
    // Толпа даёт ОБЪЁМ, машина — ПОТОЛОК, дорожка — ПОЛ. Ни одна не
    // заменяет другую и ни одна не делает игру скучной: купленная
    // массовка поднимает и доход, и риск разом (зон становится
    // больше, чем успеваешь ловить, а не пойманная роняет ажиотаж).
    //
    // Уровень 0 — то, с чего игрок начинает; levels — что покупается
    // поверх. Цены по лестнице ×1.8 (docs/plan/15-progression.md).
    upgrades: {
        order: ['crowd', 'car', 'carpet'],

        // ---------- ШИРИНА ЗОНЫ ----------
        // Толпа гуще — рук, тянущихся к звезде, больше, и место, куда
        // можно попасть, шире. Радиус зоны в единицах холста.
        //
        // Зона попадания ВСЕГДА равна видимому пятну, на всех
        // ступенях: расхождение между тем, что видно, и тем, что
        // засчитывается, здесь уже стоило одной переделки
        // (docs/plan/17-pride.md, раздел 1).
        crowd: {
            name: 'Массовка', emoji: '👥',
            hint: 'зона попадания шире',
            base: 44,          // радиус зоны без прокачки
            levels: [
                { price: { pride_kiss: 60 },   bonus: 47 },
                { price: { pride_kiss: 140 },  bonus: 50 },
                { price: { pride_kiss: 230 },  bonus: 53 },
                { price: { pride_kiss: 450 },  bonus: 56 },
                { price: { pride_kiss: 820 },  bonus: 59 },
                { price: { pride_kiss: 1450 }, bonus: 62 }
            ]
        },

        // ---------- ГЛАВНАЯ ЛИНИЯ ГРЕХА ----------
        // Машина — единственное, что УМНОЖАЕТ доход, а не прибавляет
        // к нему. Массовка даёт больше зон, дорожка — больше
        // попаданий, и обе прибавляют линейно; машина умножает всё,
        // что дали первые две. Поэтому и стоит она особняком: своя
        // лестница, вдвое круче соседской (×2.2 против ×2), и к
        // верхним множителям игрок идёт дольше всего в игре.
        //
        // БЕЗ ПРОКАЧКИ ПОТОЛОК ×1. Не ×3, как было: на старте один
        // поцелуй должен стоить один поцелуй, и никакой ажиотаж этого
        // не меняет. Весь множитель — купленный, в этом и смысл
        // линии.
        //
        // Первая ступень при этом нарочно дешёвая: до неё ажиотаж не
        // умножает ничего, а механику, которой игрок ни разу не
        // видел, невозможно захотеть. Шестьдесят поцелуев — это
        // несколько выходов, то есть первый же день.
        car: {
            name: 'Машина', emoji: '🚘',
            hint: 'выше потолок множителя',
            base: 1,           // потолок множителя без прокачки
            levels: [
                { price: { pride_kiss: 30 },   bonus: 2 },
                { price: { pride_kiss: 92 },   bonus: 3 },
                { price: { pride_kiss: 250 },  bonus: 4 },
                { price: { pride_kiss: 570 },  bonus: 5 },
                { price: { pride_kiss: 1200 }, bonus: 6 },
                { price: { pride_kiss: 2450 }, bonus: 7 }
            ]
        },

        // ---------- ВРЕМЯ ЗОНЫ ----------
        // Дорожка длиннее и наряднее — публика тянется к звезде
        // дольше, и зона висит дольше. Единственная покупка «чтобы
        // было легче»: она не добавляет ни зон, ни денег, она даёт
        // время подумать.
        //
        // Растёт время ТОЛЬКО вверх. Ускорения тайминга не будет ни в
        // каком виде: один раз уже сделали (каждый удачный тап
        // отнимал 0.1 сек), и игра стала непроходимой
        // (docs/plan/17-pride.md, раздел 12).
        carpet: {
            name: 'Дорожка', emoji: '🟥',
            hint: 'зона висит дольше',
            base: 1500,        // мс жизни зоны без прокачки
            levels: [
                { price: { pride_kiss: 60 },   bonus: 1650 },
                { price: { pride_kiss: 140 },  bonus: 1800 },
                { price: { pride_kiss: 230 },  bonus: 1950 },
                { price: { pride_kiss: 450 },  bonus: 2100 },
                { price: { pride_kiss: 820 },  bonus: 2250 },
                { price: { pride_kiss: 1450 }, bonus: 2400 }
            ]
        }
    }
};
