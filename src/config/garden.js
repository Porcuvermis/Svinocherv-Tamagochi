    startingSeeds: ['potato', 'herb'],

    // ---------- НАХОДКИ ПРИ КОПАНИИ ----------
    // Лопата не трогает время вовсе — она даёт находки, и потому работает при
    // любом расписании игрока. Засохшая кучка здесь не для красоты: она
    // снимает ворота «нет чревоугодия — нет валюты — нет магазина лени»
