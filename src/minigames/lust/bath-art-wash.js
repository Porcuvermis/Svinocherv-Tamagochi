// ================= ВАННАЯ: ПЕНА, ХВОСТ, ПОТЁКИ, СТРУЯ, ШКАЛА =================
// Продолжение BATH_ART (bath-art.js): свойства добавляются на тот же
// объект, `this` в методах — он же. Подключается сразу после bath-art.js.
Object.assign(BATH_ART, {

    // ---------- МЫЛЬНАЯ МУТЬ И ПЕНА ----------
    // Мазок мылом — широкое мягкое пятно, тёрка мочалкой — мелкое и плотное.
    // Разные движения обязаны оставлять разный след, иначе второй этап
    // читается повтором первого (docs/plan/21-lust-bath.md).
    //
    // Рисуется НЕ в svg, а на холсте (см. lust.js). Причина в двух вещах
    // сразу, и обе смертельные:
    //
    // 1. Пятно в svg — это фигура, а фигура не умеет обрезаться по силуэту
    //    червя: мыло ложилось и на воду вокруг него.
    // 2. За проход мочалкой пятен набиралось под полторы сотни, и каждое —
    //    полупрозрачный узел поверх остальных. Браузер пересчитывает всю
    //    эту стопку на каждом кадре анимации червя, и кадры умирали.
    //
    // Холст решает оба: маска по силуэту — одна операция композиции, а вся
    // накопленная пена — один узел в дереве.
    //
    // Прозрачность НИЗКАЯ нарочно: мазки ложатся сотнями внахлёст, и та, что
    // выглядит правильной на одном, за проход собирается в сплошное белое
    // поле — червя под ним не видно вовсе.
    // Три состояния клетки, и они различаются НАЗНАЧЕНИЕМ, а не оттенком
    // одного и того же: муть от мыла — мягкая и приглушённая, пена от
    // мочалки — плотная и яркая, тремя ступенями по числу тёрок. Одна
    // яркость на все ступени означала «непонятно, засчиталось или нет».
    WASH: {
        soap:  { key: 'soapFilm', a: [0.62] },
        cloth: { key: 'foam',     a: [0.45, 0.72, 1.0] }
    },

    // Заливка одной клетки. t — доля от нужного числа проходов.
    // Пена на теле — ТЕ ЖЕ ПУЗЫРИ, что налипли на хвост, только нарисованные
    // на холсте. Радиальное пятно с мягким краем читалось запотевшим стеклом:
    // мыло есть, а пены нет. У пузыря есть КРАЙ, блик и сосед — из этого он и
    // читается пеной.
    //
    // Размеры идут ГРАДАЦИЕЙ: доля возводится в степень, поэтому мелких
    // много, крупных единицы — так пена и выглядит. Одинаковые кружки
    // складываются в сетку, а не в пену.
    //
    // Раскладка выводится из СИДА клетки: пена перерисовывается на каждый
    // мазок, и случайные числа заставили бы её мигать.
    // part: 'base' — только подложка (её обрезают силуэтом),
    //       'foam' — только пузыри (их НЕ обрезают),
    //       не задан — и то и другое разом.
    // inside(x, y) — необязательная проверка «точка на теле»: пузырь, чей
    // ЦЕНТР за силуэтом, не рисуется вовсе. Край при этом торчать наружу
    // может и должен — пузырь выпуклый, у кромки тела половина его снаружи.
    washCell(ctx, kind, x, y, cell, t, seed, part, inside) {
        const cloth = kind === 'cloth';
        const c = btPal()[cloth ? 'foam' : 'soapFilm'];
        const rng = btRng(seed);
        const k = t == null ? 1 : Math.max(0, Math.min(1, t));
        // Мыло — плёнка: пузырьков много и они мелкие. Мочалка взбивает:
        // пузыри крупнее, ярче и с краем, и тем гуще, чем больше тёрок.
        const n = cloth ? 4 + Math.round(k * 4) : 6;
        const big = cell * (cloth ? 0.66 : 0.46);
        const small = cell * (cloth ? 0.16 : 0.11);
        const A = cloth ? 0.34 + k * 0.3 : 0.3;
        // Недотёртая клетка обязана быть ВИДНО недотёртой. Раньше разница
        // между одной тёркой и тремя была в числе пузырей и в яркости —
        // на глаз это одна и та же пена, и игрок водил мочалкой по уже
        // «готовому» червю, ища невидимые клетки. Теперь у неполной клетки
        // пена занимает МЕНЬШЕ МЕСТА: между такими клетками остаются тёмные
        // прогалы мыльной плёнки, и недотёртое читается прямо на картинке.
        const spread = cloth ? 0.5 + 0.5 * k : 1;
        // Подложка под пузырями. Одни пузыри оставляют между собой голую
        // кожу, и намыленный червь читается обсыпанным, а не намыленным.
        // Слабая заливка по клетке закрывает эти просветы, не съедая
        // пузыри: они всё равно ярче и с краем.
        if (part !== 'foam') {
            ctx.globalAlpha = cloth ? 0.14 + k * 0.16 : 0.16;
            ctx.fillStyle = c[500];
            ctx.beginPath();
            ctx.arc(x, y, cell * 0.95 * spread, 0, Math.PI * 2); ctx.fill();
        }
        if (part === 'base') { ctx.globalAlpha = 1; return; }
        for (let i = 0; i < n; i++) {
            const r = (small + Math.pow(rng(), 2.1) * (big - small)) * spread;
            const a = rng() * Math.PI * 2;
            const d = Math.pow(rng(), 0.6) * cell * 0.72 * spread;
            const bx = x + Math.cos(a) * d, by = y + Math.sin(a) * d;
            // Пузырь садится на тело, а не цепляется за него краем: мало
            // того, что центр на силуэте, — половина пузыря обязана лежать
            // на нём же. Без второго условия крупный пузырь, чей центр попал
            // на кончик уха, висел в воздухе отдельным кольцом.
            if (inside) {
                if (!inside(bx, by)) continue;
                const q = r * 0.7;
                let n2 = 0;
                if (inside(bx - q, by)) n2++;
                if (inside(bx + q, by)) n2++;
                if (inside(bx, by - q)) n2++;
                if (inside(bx, by + q)) n2++;
                if (n2 < 2) continue;
            }
            ctx.globalAlpha = A;
            ctx.fillStyle = c[500];
            ctx.beginPath(); ctx.arc(bx, by, r, 0, Math.PI * 2); ctx.fill();
            ctx.globalAlpha = A * (cloth ? 1.5 : 1.1);
            ctx.lineWidth = Math.max(1, r * 0.16);
            ctx.strokeStyle = c.hi;
            ctx.beginPath(); ctx.arc(bx, by, r * 0.94, 0, Math.PI * 2); ctx.stroke();
            // Блик — только у крупных: на мелком он превращается в шум.
            if (r > cell * 0.3) {
                ctx.globalAlpha = A * 1.7;
                ctx.fillStyle = c.hi;
                ctx.beginPath();
                ctx.arc(bx - r * 0.32, by - r * 0.34, r * 0.26, 0, Math.PI * 2);
                ctx.fill();
            }
        }
        ctx.globalAlpha = 1;
    },

    // ---------- ХВОСТ ФИНАЛА ----------
    // Отдельная сущность, не привязанная к скелету (docs/plan/21-lust-bath.md,
    // раздел 2). Так не от лени: в финале червь выныривает у дальнего борта, а
    // хвост всплывает у ближнего — привязанный к телу хвост в такую раскладку
    // не встаёт, он растёт из конца туловища.
    //
    // От модели наследуется ТОЛЬКО оттенок: цвет хвоста обязан меняться
    // вместе с червём.
    //
    // ---------- ОН ГНЁТСЯ, А НЕ ПОВОРАЧИВАЕТСЯ ----------
    // Первая версия просто крутила готовую фигуру вокруг основания. На
    // экране это читалось предметом, лежащим поверх ванны и вращающимся на
    // месте: основание уезжало из воды, связи с чашей не было.
    //
    // Теперь хвост — ПРУТ. Основание всегда стоит вертикально и остаётся под
    // водой, кривизна набирается к кончику. Отсюда и форма изгиба: угол
    // растёт как t², то есть у корня прут почти прямой, а гнётся верхняя
    // треть — ровно так ведёт себя ветка, которую отгибают за макушку.
    // side: в какую сторону гнётся. −1 — влево: хвост стоит правее головы,
    // и тянуть его надо к ней.
    // Хвост НАЧИНАЕТ маленьким и растёт В ДЛИНУ: в этом весь этап.
    //
    // Потолок длины задан не на глаз, а ЦЕЛЬЮ: налившийся хвост своим
    // кончиком обязан остаться НИЖЕ рта — примерно по нижний край головы.
    // Корень стоит на y=748, рот на y≈595, значит вся длина с ростом не
    // больше ~130. Стоило кончику задраться выше рта, как струя переставала
    // лететь ВВЕРХ, дуги не оставалось и попадание вырождалось.
    //
    // 145×40 с ростом до 225×86 были размером с голову червя: два предмета
    // спорили за кадр, а прицел стал почти невозможен — длинное плечо
    // множит любую ошибку по углу.
    // side: 1 — хвост гнётся ВПРАВО, к морде. Хвост стоит левее головы,
    // и тянуть его надо к ней.
    TAIL: { len: 92, base: 34, seg: 22, side: 1 },

    // Осевая линия при заданном изгибе. bend — на сколько радиан уведён
    // КОНЧИК от вертикали; у основания отклонение всегда ноль.
    // grow — во сколько раз хвост длиннее исходного. Растёт он на этапе
    // поглаживания, и растёт ВСЯ фигура: и осевая, и толщина. Держать рост
    // масштабом группы нельзя — вместе с хвостом поехал бы и его корень,
    // а тот обязан оставаться на месте, под бортом.
    tailSpine(bend, grow) {
        const T = this.TAIL, n = T.seg, ds = T.len * (grow || 1) / n;
        const k = T.side || 1;
        const pts = [{ x: 0, y: 0, a: 0 }];
        let x = 0, y = 0;
        for (let i = 1; i <= n; i++) {
            const t = i / n;
            // ЛУК, а не удочка. Наибольший изгиб — В СЕРЕДИНЕ, а не на самом
            // кончике: держат снизу, гнут сверху, и выгибается середина.
            // Профиль t²(3−2t) — та же плавная ступенька: угол растёт быстрее
            // всего на половине длины, значит там же и максимум кривизны.
            // Было t²: кривизна копилась к концу, и хвост вилял кончиком, как
            // хлыстом, — упругости в нём не читалось.
            const a = bend * t * t * (3 - 2 * t);
            x += k * Math.sin(a) * ds;
            y -= Math.cos(a) * ds;
            pts.push({ x, y, a });
        }
        return pts;
    },

    // Контур прута: осевая линия, разведённая на полутолщину по нормали.
    tailCurve(bend, grow) {
        const T = this.TAIL, g = grow || 1;
        const pts = this.tailSpine(bend, g), n = pts.length - 1;
        // Сужение с лёгкой выпуклостью в середине и ОСТРЫМ кончиком.
        // Линейное давало ровный треугольник — плавник, а не хвост; степень
        // без множителя оставляла кончик тупым, и изгиб на нём не читался.
        // Толщина растёт МЕДЛЕННЕЕ длины (степень меньше единицы): налив —
        // это прежде всего длина, а толщина идёт следом, чтобы хвост
        // набухал, а не масштабировался целиком. Было наоборот, степенью
        // 1.7, и выросший хвост оказывался с голову шириной.
        const half = (t) => (T.base / 2) * Math.pow(g, 0.7) * Math.pow(1 - t, 0.72)
                          * (1 + 0.28 * Math.sin(Math.PI * t));
        const left = [], right = [];
        for (let i = 0; i <= n; i++) {
            const p = pts[i], w = half(i / n);
            const nx = (T.side || 1) * Math.cos(p.a), ny = Math.sin(p.a);
            left.push(`${(p.x - nx * w).toFixed(1)} ${(p.y - ny * w).toFixed(1)}`);
            right.push(`${(p.x + nx * w).toFixed(1)} ${(p.y + ny * w).toFixed(1)}`);
        }
        // Низ уходит под воду, поэтому основание закрывается прямой: закруглять
        // то, чего не видно, незачем.
        const d = `M${left.join('L')}L${right.reverse().join('L')}Z`;
        const tip = pts[n];
        return { d, spine: pts, tip,
                 // Направление кончика в координатах сцены: фигура смотрит
                 // ВВЕРХ, то есть в −y.
                 dir: Math.atan2(-Math.cos(tip.a), (T.side || 1) * Math.sin(tip.a)) };
    },

    // Две линии хвоста при заданном изгибе: сам прут и блик по нему. Блик
    // идёт ПО ОСИ, а не отдельной дугой: при изгибе он обязан гнуться вместе
    // с телом, иначе съезжает с формы.
    // Полуширина хвоста в доле t вдоль оси. Пузыри садятся ПО НЕЙ, а не по
    // постоянной: у основания хвост вдвое толще, чем у кончика, и общая
    // ширина сажала половину пены мимо, на плитку.
    tailHalf(t, grow) {
        const g = grow || 1;
        return (this.TAIL.base / 2) * Math.pow(g, 0.7)
             * Math.pow(1 - t, 0.72) * (1 + 0.28 * Math.sin(Math.PI * t));
    },

    tailD(bend, grow) {
        const c = this.tailCurve(bend || 0, grow);
        const shine = c.spine.filter((p, i) => i > 1 && i < c.spine.length - 3)
            .map(p => `${(p.x - (this.TAIL.side || 1) * Math.cos(p.a) * this.TAIL.base * 0.17 * (grow || 1)).toFixed(1)} `
                    + `${(p.y - Math.sin(p.a) * this.TAIL.base * 0.17 * (grow || 1)).toFixed(1)}`);
        return { body: c.d, shine: 'M' + shine.join('L'), curve: c };
    },

    // Разметка хвоста собирается ОДИН РАЗ, дальше меняются только атрибуты d.
    // Пересобирать её каждый кадр значит парсить строку шестьдесят раз в
    // секунду ради двух чисел — на телефоне это заметно.
    tail(model) {
        const m = (model && model.tail) || {};
        // Оттенок берётся у предхвостового сегмента тела, а не у собственного
        // хвоста модели: тот покрашен в самую тёмную ступень мяса, и хвост
        // такого размера читался тёмным клинком, а не частью червя.
        const seg = (model && model.growingSegments && model.growingSegments[0])
                 || (model && model.belly) || null;
        const fill = (seg && seg.fill) || m.fill || PALETTE.flesh[700];
        const ink = (seg && seg.stroke) || m.stroke || PALETTE.ink;
        return `
        <path id="bt-tail-body" d="" fill="${fill}" stroke="${ink}"
              stroke-width="3" stroke-linejoin="round"/>
        <path id="bt-tail-shine" d="" fill="none" stroke="${PALETTE.flesh[100]}"
              stroke-width="7" stroke-linecap="round" opacity="0.38"/>
        <!-- Потёки на хвосте — ВНУТРИ его группы: гнутся и опадают вместе с
             ним (lust-goo.js). -->
        ${this.gooLive('bt-tail-goo')}`;
    },

    // ---------- ПУЗЫРИ ПЕНЫ ----------
    // Пузырь читается пузырём по БЛИКУ, а не по кружку: без блика это пятно
    // той же пены, и лопать его незачем.
    bubble(x, y, r, seed) {
        const f = btPal().foam;
        const rng = btRng(seed);
        const ox = (rng() - 0.5) * r * 0.5, oy = -r * (0.28 + rng() * 0.14);
        return `<g class="bt-bubble" data-r="${r.toFixed(1)}"
                   data-x="${x.toFixed(1)}" data-y="${y.toFixed(1)}">
            <circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"
                    fill="${f[500]}" fill-opacity="0.52"
                    stroke="${f.rim}" stroke-width="2"/>
            <circle cx="${(x + ox).toFixed(1)}" cy="${(y + oy).toFixed(1)}"
                    r="${(r * 0.3).toFixed(1)}" fill="${f.hi}" opacity="0.85"/>
        </g>`;
    },

    // ---------- ГОРКА ПЕНЫ НАД ХВОСТОМ ----------
    // Не украшение, а ШИРМА: под ней всплывает хвост, и всплытие не должно
    // быть заметно. Отсюда и требование — горка непроницаема, пока цела.
    //
    // Собирается из перекрывающихся комков: один эллипс читается яйцом, а
    // десяток разнокалиберных кругов — комом пены. Растёт снизу вверх по
    // доле k: пока червя трут мочалкой, k — это доля вытертого тела, а когда
    // пузыри лопают — доля оставшихся.
    foamMound(x, y, w, h, k, seed) {
        const f = btPal().foam;
        const g = Math.max(0, Math.min(1, k));
        if (g <= 0.01) return '';
        const rng = btRng(seed || 7);
        const H = h * (0.35 + 0.65 * g);      // высота растёт с наливом
        const W = w * (0.6 + 0.4 * g);
        const out = [];
        // Комки идут снизу вверх и сужаются к макушке: у кучи пены широкое
        // основание, иначе она читается облаком в воздухе.
        for (let i = 0; i < 22; i++) {
            const t = Math.pow(i / 21, 0.85);
            const half = (W / 2) * (1 - 0.62 * t);
            const bx = x + (rng() - 0.5) * 2 * half;
            const by = y - t * H - 2;
            const r = (W * 0.30) * (1 - 0.42 * t) * (0.7 + rng() * 0.6);
            out.push(`<circle cx="${bx.toFixed(1)}" cy="${by.toFixed(1)}"`
                   + ` r="${r.toFixed(1)}" fill="${f[500]}"/>`);
        }
        // Заливка НЕПРОЗРАЧНАЯ — иначе сквозь ширму видно хвост, — а
        // прозрачность у всей группы: так комки не просвечивают друг сквозь
        // друга и горка остаётся одним телом, а не кучей кружков.
        return `<g opacity="${(0.35 + 0.65 * g).toFixed(2)}">${out.join('')}</g>`;
    },

    // Лужицы во рту здесь НЕТ и быть не может: она — часть самого рта
    // (worm-renderer, mouthFill), а не пятно поверх морды. Пока её рисовали
    // тут, её приходилось наводить на рот числами после каждого переезда
    // камеры, она не размывалась вместе с червём и при малейшем расхождении
    // оказывалась на щеке.

    // ---------- ПОТЁКИ И КОМЕТА ----------
    // ЖИДКОСТЬ, А НЕ ЗНАЧОК. Первая версия рисовала пятно правильным кругом,
    // нитку трапецией и каплю кружком, всё с толстой обводкой, — и читалось
    // это набором пиктограмм, а не тем, что шлёпнулось и течёт. Жидкость
    // выдают три вещи, и все три здесь:
    //   * НЕРОВНЫЙ край — клякса вытянута по ходу удара, радиус гуляет от
    //     точки к точке, вокруг разлетаются мелкие брызги;
    //   * ОДНА гладкая кривая на всё — пятно, нитка и капля на конце не
    //     склеены из фигур, а обведены одним контуром через сплайн;
    //   * объём СВЕТОМ, а не обводкой: мягкая тень чуть ниже и блик сверху.
    //     Контур у жидкости не нарисован — его видно по тени.
    //
    // Все куски пятна (клякса, брызги, нитка) обходятся В ОДНУ СТОРОНУ и
    // лежат в одном пути: при правиле nonzero перекрытия сливаются, и
    // полупрозрачная заливка не темнеет там, где нитка входит в кляксу.

    // Расфокус дальнего плана, в единицах сцены. Одно число на стену
    // (svg-фильтр душа, см. blurFar в lust.js) и на потёки по ней.
    FAR_BLUR: 2.6,

    // Замкнутый сплайн Катмулла — Рома через точки, кубическими кривыми.
    //
    // Команды ОТНОСИТЕЛЬНЫЕ, и переход к следующему куску — тоже (m от
    // начала прошлого: после z перо стоит именно там). Тогда во всём пути
    // абсолютна одна первая точка, и пятно переносится заменой ЕЁ одной
    // (gooMove). Пятна на хвосте едут за ним каждый кадр изгиба, и
    // пересчитывать ради этого все сплайны стоило четырёх кадров из
    // шестидесяти.
    gooCurve(pts, from) {
        const n = pts.length, f = (v) => v.toFixed(2);
        let d = from ? `m${f(pts[0].x - from.x)} ${f(pts[0].y - from.y)}`
                     : `M${pts[0].x.toFixed(1)} ${pts[0].y.toFixed(1)}`;
        for (let i = 0; i < n; i++) {
            const p0 = pts[(i - 1 + n) % n], p1 = pts[i],
                  p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
            d += `c${f((p2.x - p0.x) / 6)} ${f((p2.y - p0.y) / 6)} `
               + `${f(p2.x - (p3.x - p1.x) / 6 - p1.x)} ${f(p2.y - (p3.y - p1.y) / 6 - p1.y)} `
               + `${f(p2.x - p1.x)} ${f(p2.y - p1.y)}`;
        }
        return d + 'z';
    },

    // Несколько замкнутых кусков одним путём: первый от абсолютной точки,
    // остальные — относительным переходом от начала предыдущего.
    gooCurves(list) {
        if (!list) return '';
        let d = '', prev = null;
        for (const pts of list) { d += this.gooCurve(pts, prev); prev = pts[0]; }
        return d;
    },

    // Пятно, нарисованное в (0, 0), переносится в (x, y) заменой первой
    // точки: всё остальное в пути относительное.
    gooMove(d, x, y) {
        if (!d) return '';
        const m = /^M(-?[\d.]+) (-?[\d.]+)/.exec(d);
        if (!m) return d;
        return `M${(+m[1] + x).toFixed(1)} ${(+m[2] + y).toFixed(1)}` + d.slice(m[0].length);
    },

    // Овал точками по часовой стрелке (ось y вниз), повёрнутый на rot.
    gooOval(x, y, rx, ry, rot, n) {
        const c = Math.cos(rot || 0), s = Math.sin(rot || 0), out = [];
        for (let i = 0; i < (n || 8); i++) {
            const a = 2 * Math.PI * i / (n || 8);
            const u = Math.cos(a) * rx, v = Math.sin(a) * ry;
            out.push({ x: x + u * c - v * s, y: y + u * s + v * c });
        }
        return out;
    },

    // ---------- ТОЛЩИНА: МУТНОЕ ЯДРО И ПРОЗРАЧНЫЙ КРАЙ ----------
    // Жижа не краска: она мутная там, где её МНОГО, и просвечивает там, где
    // её тонкий слой. Пятно поэтому рисуется двумя тонами:
    //   край (thin) — вся форма, холодный и полупрозрачный: сквозь него
    //                 видно кожу, плитку, эмаль;
    //   ядро (core) — та же клякса, ужатая к середине и СПУЩЕННАЯ ВНИЗ:
    //                 на отвесной поверхности жидкость стекает и копится
    //                 у нижнего края; тёплое и почти непрозрачное.
    // Нитка в ядре тоньше, а капля на конце — почти вся ядро: там толще
    // всего.
    //
    // Каждый тон — ОДИН путь на все пятна слоя, и прозрачность у пути, а не
    // у группы: внутри одного пути перекрытия по правилу nonzero сливаются
    // и не темнеют стопкой, а отдельного буфера, как у группы с
    // прозрачностью, путь не требует (docs/traps.md, п. 73).
    //
    // Края не прозрачнее 0.7: на 0.55 пятно на черве (он сам полупрозрачен
    // в финале) читалось каплей ВОДЫ — прозрачной и с бликом, — а не
    // мутной жижей.
    GOO_TONE: { thin: 0.7, core: 0.95 },

    // Путь пятна. x, y — куда шлёпнулось; r — размер; len — насколько
    // стекло; seed — своё у каждого пятна, из него вся неровность, чтобы
    // форма не дрожала от кадра к кадру; ang — направление удара.
    // g — раздуть все края на g единиц.
    // Отдаёт три пути: body (край, вся форма), core (ядро), hi (блики).
    //
    // fit — необязательная «поверхность»: функция точка → точка, через
    // которую проходит КАЖДАЯ точка контура до того, как по ним ляжет
    // кривая. Ею пятно поджимается к своему предмету (lust-goo.js, fitter):
    // у края борта, хвоста, части тела оно не обрезается, а мягко
    // закругляется с отступом — как капля, которую держит натяжение.
    // Поджать точки, а не обрезать готовую фигуру, — вся разница: сплайн
    // по поджатым точкам сам даёт скруглённый край.
    goo(x, y, r, len, seed, ang, g, fit) {
        const p = this.gooPts(x, y, r, len, seed, ang, g, fit);
        return { body: this.gooCurves(p.body), core: this.gooCurves(p.core),
                 hi: this.gooCurves(p.hi) };
    },

    // То же пятно ТОЧКАМИ, до кривой: кому надо двигать пятно за
    // поверхностью (хвост гнётся и опадает), тот держит точки и гонит их
    // через своё преобразование, а кривую строит уже по результату.
    gooPts(x, y, r, len, seed, ang, g, fit) {
        g = g || 0;
        const rnd = btRng(1 + Math.floor(seed * 1e6));
        const parts = [], core = [];
        // Клякса: вытянута по удару, край гуляет. Ядро — те же лепестки
        // (тот же случай), ужатые и спущенные вниз.
        const n = 11, c = Math.cos(ang || 0), s = Math.sin(ang || 0);
        const blob = [], kern = [];
        const cy = y + r * 0.16;
        for (let i = 0; i < n; i++) {
            const a = 2 * Math.PI * i / n, k = 0.78 + 0.4 * rnd();
            const u = Math.cos(a) * (r * k * 1.25 + g), v = Math.sin(a) * (r * k * 0.8 + g);
            blob.push({ x: x + u * c - v * s, y: y + u * s + v * c });
            const uc = Math.cos(a) * r * k * 0.72, vc = Math.sin(a) * r * k * 0.5;
            kern.push({ x: x + uc * c - vc * s, y: cy + uc * s + vc * c });
        }
        parts.push(blob);
        core.push(kern);
        // Брызги: мелкие капли, разлетевшиеся по ходу удара. Мелкая капля —
        // вся ядро: тонкого края у неё нет, она целиком толстая.
        const sat = r > 4.5 ? 1 + Math.floor(rnd() * 3) : (rnd() < 0.35 ? 1 : 0);
        for (let i = 0; i < sat; i++) {
            const a = (ang || 0) + (rnd() - 0.5) * 1.6, dd = r * (1.45 + rnd() * 0.8);
            const rr = r * (0.1 + rnd() * 0.13) + g * 0.7;
            const px = x + Math.cos(a) * dd, py = y + Math.sin(a) * dd;
            parts.push(this.gooOval(px, py, rr, rr * 0.85, a, 7));
            core.push(this.gooOval(px, py + rr * 0.1, rr * 0.7, rr * 0.6, a, 6));
        }
        // Нитка с каплей на конце: одним контуром — правый край вниз, капля,
        // левый край вверх. Нитка чуть виляет и сужается, капля на конце
        // растёт вместе с длиной: тяжелеет.
        const cxOf = (t) => x + r * 0.14 * Math.sin(seed * 9 + t * 2.6) * t;
        const rbOf = r * (0.24 + 0.2 * Math.min(1, len / (3 * r)));
        const y0 = y - r * 0.15, L = len + r * 0.15;
        const drip = (wk, bk) => {
            const m = 7, pts = [];
            const hw = (t) => Math.max(0.3, r * 0.42 * wk * (1 - 0.72 * Math.pow(t, 0.8)) + g);
            const rb = Math.max(0.4, rbOf * bk + g);
            for (let i = 0; i < m; i++) { const t = i / m; pts.push({ x: cxOf(t) + hw(t), y: y0 + t * L }); }
            const bx = cxOf(1), by = y0 + L + (1 - bk) * rbOf * 0.3;
            for (let i = 0; i <= 6; i++) {
                const a = -0.35 + (Math.PI + 0.7) * i / 6;
                pts.push({ x: bx + Math.cos(a) * rb, y: by + Math.sin(a) * rb });
            }
            for (let i = m - 1; i >= 0; i--) { const t = i / m; pts.push({ x: cxOf(t) - hw(t), y: y0 + t * L }); }
            return pts;
        };
        if (len > r * 0.25) {
            parts.push(drip(1, 1));
            core.push(drip(0.45, 0.72));
        }
        const F = fit ? (list) => list.map(pts => pts.map(fit)) : (list) => list;
        const out = { body: F(parts), core: F(core), hi: [] };
        if (g) return out;
        // Блики. Жидкость глянцевая: резкая искра на верхней кромке кляксы,
        // вторая, мельче, рядом — отражение окна дробится на выпуклости, —
        // и точка на капле. Отсвета снизу (свет насквозь) здесь нет: мутная
        // жижа света насквозь не пропускает, и с ним пятно читалось водой.
        const his = [this.gooOval(x - r * 0.3, y - r * 0.32, r * 0.3, r * 0.12, -0.45, 7),
                     this.gooOval(x + r * 0.08, y - r * 0.44, r * 0.09, r * 0.06, -0.3, 5)];
        if (len > r * 0.6) {
            const bx = cxOf(1), by = y0 + L;
            his.push(this.gooOval(bx - rbOf * 0.35, by - rbOf * 0.35, rbOf * 0.26, rbOf * 0.18, -0.6, 6));
        }
        out.hi = F(his);
        return out;
    },

    // ---------- ПОТЁКИ СЛИВАЮТСЯ В ОДНУ МАССУ ----------
    // Приём тот же, что у слизи в комнате (worm-slime.js): пятна одного слоя
    // лежат в ОДНОМ пути на тон, и перекрытия сливаются в одну лужу, а не
    // копятся стопкой. Тень тоже одна на слой.
    //
    // Первая версия давала каждому пятну свою полупрозрачную тень со
    // сдвигом в две единицы: там, куда падало много капель, тени
    // складывались в тёмное пятно с резкой светотенью, а каждое пятно
    // читалось отдельной наклейкой.
    GOO_SHADE: { alpha: 0.14, dx: 0.5, dy: 0.9 },

    // Разметка слоя потёков: по тону — застывшие (один путь, переписывается
    // при застывании) и живые (один путь на все ползущие).
    gooLive(id) {
        const m = btPal().milk, S = this.GOO_SHADE, T = this.GOO_TONE;
        const pair = (suf, attrs) =>
            `<path id="${id}-done${suf}" d="" ${attrs}/><path id="${id}${suf}" d="" ${attrs}/>`;
        return `<g transform="translate(${S.dx} ${S.dy})">${pair('-sh',
                    `fill="${m.shade}" fill-opacity="${S.alpha}"`)}</g>
                ${pair('', `fill="${m.thin}" fill-opacity="${T.thin}"`)}
                ${pair('-core', `fill="${m.core}" fill-opacity="${T.core}"`)}
                ${pair('-hi', `fill="${m.hi}"`)}`;
    },

    // Капля в полёте — КОМЕТА: густая голова и сужающийся хвост по следу
    // полёта, одним контуром. Обводки нет: объём — ядром, тенью и бликом.
    flyLive() {
        const m = btPal().milk, S = this.GOO_SHADE, T = this.GOO_TONE;
        return `<path id="bt-fly-sh" d="" fill="${m.shade}" fill-opacity="${S.alpha}"
                      transform="translate(${S.dx} ${S.dy})"/>
                <path id="bt-fly" d="" fill="${m.thin}" fill-opacity="${T.thin + 0.15}"/>
                <path id="bt-fly-core" d="" fill="${m.core}" fill-opacity="${T.core}"/>
                <path id="bt-fly-hi" d="" fill="${m.hi}"/>`;
    },

    // ---------- СТРУЯ: ОДНА ЛЕНТА ----------
    // Толчок — это не цепочка капель, а одна длинная лента жижи: толстая
    // голова, сужающееся тело, скруглённый хвост. Вторая версия рисовала
    // хвост кометы бусами — перетяжка, бусина, перетяжка, — и струя
    // читалась нанизанными шариками, а не жидкостью. Капли от струи
    // отрываются, но оторвавшаяся — это уже отдельная капля (lust.js,
    // shedStream); пока капля в струе, её не видно: лента цельная.
    //
    // pts — точки оси от головы к хвосту, ws — полуширина в каждой,
    // dir — направление полёта на случай, когда ось ещё не вытянулась
    // (первые мгновения: вся струя стоит у кончика).
    streamD(pts, ws, dir) {
        const n = pts.length, L = [], R = [];
        let tx0 = Math.cos(dir || 0), ty0 = Math.sin(dir || 0);
        for (let i = 0; i < n; i++) {
            const a = pts[Math.max(0, i - 1)], b = pts[Math.min(n - 1, i + 1)];
            let tx = a.x - b.x, ty = a.y - b.y;
            const l = Math.hypot(tx, ty);
            if (l > 1e-3) { tx /= l; ty /= l; tx0 = tx; ty0 = ty; } else { tx = tx0; ty = ty0; }
            L.push({ x: pts[i].x - ty * ws[i], y: pts[i].y + tx * ws[i], tx, ty });
            R.push({ x: pts[i].x + ty * ws[i], y: pts[i].y - tx * ws[i], tx, ty });
        }
        // Скругления на концах: голова — полукруг вперёд, хвост — назад.
        const cap = (p, w, tx, ty, back) => {
            const a0 = Math.atan2(ty, tx) + (back ? Math.PI : 0), out = [];
            for (let i = 1; i < 5; i++) {
                const a = a0 + Math.PI / 2 - Math.PI * i / 5;
                out.push({ x: p.x + Math.cos(a) * w, y: p.y + Math.sin(a) * w });
            }
            return out;
        };
        const head = cap(pts[0], ws[0], L[0].tx, L[0].ty, false);
        const tail = cap(pts[n - 1], ws[n - 1], L[n - 1].tx, L[n - 1].ty, true);
        return this.gooCurve(L.slice().reverse().concat(head, R, tail));
    },

    cometHi(x, y, r) {
        return this.gooCurve(this.gooOval(x - r * 0.3, y - r * 0.35, r * 0.34, r * 0.2, -0.5, 6));
    },

    // Заготовка узла вспышки попадания: создаётся один раз, дальше ей
    // правятся только координаты (см. renderShots в lust.js).
    flashNode() {
        const m = btPal().milk;
        return `<circle r="1" fill="none" stroke="${m.hi}" stroke-width="5"/>`;
    },

    // ---------- ШКАЛА НАД ГОЛОВОЙ: ЖЕТОН ИЗ ТРЁХ ЧАСТЕЙ ----------
    // Жетон — кольцо из трёх равных третей, и каждая треть поделена на
    // СТОЛЬКО долек, сколько попаданий она стоит (2, 5, 8). Цена части видна
    // без единого слова: крупные дольки набираются быстро, мелкие — долго
    // (инвариант 9). Части закрываются по порядку, от верха по часовой
    // стрелке, — так же, как заполняется жетон в кошельке (docs/token-art.md).
    //
    // Вид временный: форма та же, что у жетона в кошельке, но без его
    // перемычек и объёма. Красивая шкала — отдельная работа.
    //
    // x, y — точка ПОД жетоном: он стоит над головой, и снизу у него опора.
    // steps — цены частей, hits — сколько попаданий за забег.
    gauge(x, y, steps, hits) {
        const R = 44, r = 19, cy = y - R;
        const color = (typeof TokenArt !== 'undefined')
            ? TokenArt.color('lust_token') : btPal().milk.hi;
        const ink = btBake().ink;
        const GROUP = 12, PIECE = 3;          // просветы, градусы
        const n = steps.length, third = 360 / n;
        const st = LustShot.gaugeState(hits, steps);
        const pt = (deg, rad) => {
            const a = (deg - 90) * Math.PI / 180;
            return `${(x + Math.cos(a) * rad).toFixed(1)},${(cy + Math.sin(a) * rad).toFixed(1)}`;
        };
        const wedge = (a0, a1) => {
            const big = (a1 - a0) > 180 ? 1 : 0;
            return `M ${pt(a0, R)} A ${R} ${R} 0 ${big} 1 ${pt(a1, R)} `
                 + `L ${pt(a1, r)} A ${r} ${r} 0 ${big} 0 ${pt(a0, r)} Z`;
        };
        const out = [`<circle cx="${x}" cy="${cy.toFixed(1)}" r="${R + 5}"
                              fill="${btPal().shadow}" fill-opacity="0.28"/>`];
        steps.forEach((cost, part) => {
            const from = part * third + GROUP / 2, to = (part + 1) * third - GROUP / 2;
            const slice = (to - from) / cost;
            // Сколько долек этой части уже закрашено: прошлые части целиком,
            // текущая — сколько набрано, будущие — ноль.
            const lit = part < st.done ? cost : (part === st.done ? st.inPart : 0);
            for (let i = 0; i < cost; i++) {
                const a0 = from + i * slice + PIECE / 2, a1 = from + (i + 1) * slice - PIECE / 2;
                const on = i < lit;
                out.push(on
                    ? `<path d="${wedge(a0, a1)}" fill="${color}" stroke="${ink}"
                             stroke-width="2" stroke-linejoin="round"/>`
                    // Незакрашенная долька ВИДНА: иначе не понять, сколько
                    // осталось. Но бледная — чтобы не спорить с набранным.
                    : `<path d="${wedge(a0, a1)}" fill="${color}" fill-opacity="0.12"
                             stroke="${color}" stroke-opacity="0.55" stroke-width="1.6"
                             stroke-linejoin="round"/>`);
            }
        });
        return out.join('');
    },

    // ---------- УКАЗАТЕЛЬ НЕПОКРЫТОГО ----------
    // Порог 92% без подсказки превращается в поиск пикселя: игрок водит и не
    // понимает, почему этап не кончается (план, §1).
    spot(x, y, r) {
        return `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"
                        fill="none" stroke="${btPal().foam.hi}" stroke-width="4"
                        opacity="0.9"/>`;
    },
});
