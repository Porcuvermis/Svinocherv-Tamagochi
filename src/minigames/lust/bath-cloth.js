// ================= МОЧАЛКА: ЛЕСТНИЦА ВИДА =================
// Мочалка прокачивает время трения и таймер награды, и с каждой покупкой
// меняется сам ПРЕДМЕТ (docs/plan/21-lust-bath.md, разд. 5д): застиранная
// тряпка-ветошь → кухонная губка → банная губка → пуф → морская губка → люфа →
// рукавица → губка конняку → волшебное облачко. Все вещи — в одном формате
// (овал или прямоугольник одного габарита): узкое и длинное выбивалось бы
// на полке и в руке.
//
// Одна вещь в трёх местах: на полке, в руке и на иконке магазина. Поэтому
// предмет рисуется в координатах СЦЕНЫ вокруг гнезда мочалки, как рисовалась
// запечённая губка: рука (BATH_ART.held) и иконка сдвигают его на гнездо
// сами и ничего не знают о ступенях. Гнездо и зона захвата не двигаются от
// ступени — меняется только картинка. Так же устроено мыло (bath-soap.js).
const BATH_CLOTH = {
    // Вид на каждой ступени. Ещё не нарисованные ступени берут запечённую
    // губку — пока лестница не закончена.
    TIERS: ['rag', 'kitchen', 'brick', 'puff', 'sea', 'luffa', 'mitt', 'konjac', 'cloud'],
    uid: 0,

    level() {
        if (typeof GameState === 'undefined' || !GameState.upgradeLevel || typeof Backend === 'undefined') return 0;
        return GameState.upgradeLevel(Backend.upgradeKey('lust', 'cloth')) || 0;
    },
    tier(level) {
        const L = level == null ? this.level() : level;
        return Math.max(0, Math.min(this.TIERS.length - 1, L | 0));
    },

    // Вещь ступени — из двух частей: основная (лежит в корзине, за передней
    // сеткой) и передняя (свисает через край корзины наружу, поверх сетки).
    // На полке они в разных слоях сцены (bt-cloth-art и bt-cloth-front), в
    // руке и на иконке — вместе: это одна и та же вещь. Функция ступени
    // возвращает строку (всё — основная часть) или { main, front }.
    parts(level, where) {
        const r = this.tierArt(level, where);
        return typeof r === 'string' ? { main: r, front: '' } : r;
    },
    drawFront(level) { return this.parts(level, 'shelf').front; },

    // where === 'shelf' — предмет на полке: там основная часть без передней
    // (передняя — своим слоем поверх сетки), и ступень может показать там
    // то, чего нет в руке и на иконке. Иначе — обе части вместе.
    draw(level, where) {
        const p = this.parts(level, where);
        return where === 'shelf' ? p.main : p.main + p.front;
    },
    tierArt(level, where) {
        const kind = this.TIERS[this.tier(level)];
        if (kind === 'rag') return this.rag(where);
        return BATH_BAKED.draw('cloth');
    },

    // Габарит на сцене — по нему захват, упор в край экрана и иконка.
    box(level) {
        const kind = this.TIERS[this.tier(level)];
        // Ветошь — по нарисованному: getBBox кома и лоскута вместе (x 537–642,
        // y 472–570, низ — махры подола), округлено наружу.
        if (kind === 'rag') return { x: 537, y: 472, w: 105, h: 98 };
        return BATH_BAKED.box('cloth');
    },

    // Полка перерисовывается после покупки и после debug-панели.
    refresh() {
        if (typeof document === 'undefined') return;
        const p = this.parts(null, 'shelf'), el = document.getElementById('bt-cloth-art');
        const fr = document.getElementById('bt-cloth-front');
        if (el) el.innerHTML = p.main;
        if (fr) fr.innerHTML = p.front;
    },

    // ---------- 0. ВЕТОШЬ ----------
    // Застиранная клетчатая кухонная тряпка брошена в нижнюю корзину: низкий
    // смятый ком лежит ВДОЛЬ корзины, а угол полотна перевалился через
    // переднюю перекладину (y≈513) и висит вяло поверх сетки, с махрами на
    // подоле. Первой попыткой была старая жёлто-зелёная губка — та же вещь,
    // что ступень 1, только грязнее. Второй — ком, нарисованный «сам по
    // себе», без места: мелко (в руке, на иконке) он читался просто комом.
    // Мягкое лучше всего показывает себя свисающим краем, поэтому вещь
    // спроектирована под корзину (docs/bench/art-pair.md).
    //
    // Тряпку узнают по четырём вещам ПОЛОТНА, а не по фактуре:
    // 1. висящий лоскут с углом полотна внизу: на полке — через перекладину,
    //    в руке — вниз из-под пальцев (хват у гнезда приходится на верх кома);
    // 2. клетка-гингем, обрывающаяся на складках;
    // 3. два бледных изнаночных угла по диагонали — левый верх кома, низ
    //    лоскута;
    // 4. махры на кромке: подол лоскута и низ кома (на полке он за сеткой,
    //    в руке виден).
    // Силуэт кома — одна кривая, низкая и длинная. Два равных бугра читались
    // сердцем, два острых пика — кошачьей головой, овал-валик над лоскутом —
    // шляпой, прямой низ в руке — коробкой. Острый только бледный угол.
    //
    // Две части: main — ком (на полке за передней сеткой), front — лоскут
    // (поверх сетки). Верх лоскута лежит на коме швом БЕЗ контура: обведены
    // только бока и подол.
    //
    // Геометрия считается ОДИН раз и кешируется шаблоном; на вызов меняется
    // только префикс id.
    rag(where) {
        const A = BATH_ART.slots().cloth;
        if (!this._rag) this._rag = this.ragArt();
        const id = 'bcl' + (this.uid++);
        const wrap = (s, cls) => `<g class="bt-cloth ${cls}" transform="translate(${A.x} ${A.y})">`
            + s.split('§').join(id) + `</g>`;
        return { main: wrap(this._rag.main, 'bt-cloth-rag'), front: wrap(this._rag.front, 'bt-cloth-rag-flap') };
    },

    // Шаблон ветоши: { main, front } в координатах гнезда; «§» — место
    // префикса id. Чертёж — в координатах СЦЕНЫ (перекладина, стойки и дно
    // корзины там заданы числами), в шаблон он уходит сдвинутым на гнездо,
    // под которое рисовался: если гнездо переедет, вещь переедет с ним.
    ragArt() {
        const P = btPal(), R = P.rag, ink = PALETTE.ink, CK = P.ragCheck;
        const O = [573, 492];
        const f = (n) => String(Math.round(n * 10) / 10);
        // Все пути пишутся парами «x,y» в абсолютных командах (махры — тоже
        // M…L, не l): сдвиг на гнездо переписывает каждую пару.
        const S = (d) => d.replace(/(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g, (_, x, y) => f(+x - O[0]) + ',' + f(+y - O[1]));
        // Изнанка бледнее лица: застиранная ткань с обратной стороны не
        // прокрашена. Как у прошлой ветоши (back0).
        const back = mixColor(R[3], R[4], 0.35);
        const W2 = 2 * STROKE.contour;
        // Клетка полупрозрачная на КАЖДОЙ полосе, и полосы двух направлений —
        // РАЗНЫЕ элементы: на пересечении прозрачности складываются, клетка
        // там темнее полос — это и есть гингем. Одним путём со stroke-opacity
        // пересечение не темнеет, выходила «вафля»: светлые квадраты в тёмной
        // решётке. Прозрачность на самой полосе, не на группе — вещь в руке
        // живой слой (docs/traps.md, п. 73).
        const OP = 0.42;
        // Шаг 9, полоса 4: шаг 8 в руке рябил.
        const PER = 9, BAR = 4;

        // ================= КОМ =================
        const heap = 'M539,514 C537,506 539,498 542,491 L547,481 L560,488 '
            + 'C563,482 568,476 574,474 C578,472 582,473 584,476 C587,473 591,474 594,479 '
            + 'C596,482 597,484 598,486 C603,482 609,480 616,481 C621,479 626,480 630,483 '
            + 'C636,487 640,495 641,503 C642,511 641,518 638,523 '
            + 'C634,528 626,531 616,531 C606,532 596,531 588,528 '
            + 'C584,530 579,531 572,531 C561,531 551,528 545,524 C541,520 540,518 539,514 Z';
        // Изнаночный угол слева вверху: частично под ухом червя, правее x≈540
        // виден.
        const heapBack = 'M547,481 L560,488 C556,494 549,498 541,499 C543,492 545,486 547,481 Z';

        // Участки клетки со своим углом: граница участка — складка, на ней
        // клетка обрывается. Левая масса, правая (дополнение по долине) и низ
        // левой массы между двумя складками от хвата — третий угол.
        const lowLeft = 'M575,493 L552,505 L537,509 L537,533 L570,533 L570,516 C574,509 576,502 576,495 Z';
        const clipL = 'M537,467 L600,467 L598,484 C597,493 596,503 592,512 L588,533 L537,533 Z';
        const clipR = 'M598,484 L643,467 L643,533 L588,533 L592,512 C596,503 597,493 598,484 Z';
        // Честный габарит: getBBox не знает о клипах, а по габариту захват и
        // иконка магазина. Полосы — отрезки, заранее обрезанные по рамке
        // кома; повёрнутые целиком решётки раздули бы габарит вдвое, и
        // иконка схлопнулась бы.
        const FR = [537, 472, 642, 532];
        const clipSeg = (x0, y0, x1, y1) => {
            let t0 = 0, t1 = 1;
            const dx = x1 - x0, dy = y1 - y0;
            for (const [p, q] of [[-dx, x0 - FR[0]], [dx, FR[2] - x0], [-dy, y0 - FR[1]], [dy, FR[3] - y0]]) {
                if (p === 0) { if (q < 0) return null; continue; }
                const r = q / p;
                if (p < 0) { if (r > t1) return null; if (r > t0) t0 = r; }
                else { if (r < t0) return null; if (r < t1) t1 = r; }
            }
            return [x0 + dx * t0, y0 + dy * t0, x0 + dx * t1, y0 + dy * t1];
        };
        // Решётка под углом ang вокруг (cx, cy): два пути — два направления.
        const grid = (cx, cy, ang) => {
            const a = ang * Math.PI / 180, c = Math.cos(a), s = Math.sin(a), E = 80;
            const rot = (p) => [cx + p[0] * c - p[1] * s, cy + p[0] * s + p[1] * c];
            const dd = ['', ''];
            for (let k = -8; k <= 8; k++) for (const dir of [0, 1]) {
                const o = k * PER;
                const q0 = rot(dir ? [-E, o] : [o, -E]), q1 = rot(dir ? [E, o] : [o, E]);
                const g = clipSeg(q0[0], q0[1], q1[0], q1[1]);
                if (g) dd[dir] += `M${f(g[0])},${f(g[1])} L${f(g[2])},${f(g[3])} `;
            }
            return dd;
        };
        const bars = (dd, clip) => dd.map(d => `<path d="${S(d)}" clip-path="url(#§-${clip})" fill="none" stroke="${CK}" stroke-opacity="${OP}" stroke-width="${BAR}"/>`).join('');

        // ================= ЛОСКУТ =================
        // Трапеция, расширяется книзу; подол скошен, самый нижний угол полотна —
        // слева и почти прямой: острый клин читался языком, а не углом ткани.
        const flap = 'M588,507 C598,501 616,501 628,506 C630,512 628,518 627,524 C627,534 630,542 633,548 '
            + 'C624,551 613,556 604,559 L596,563 C593,550 590,535 590,522 C589,515 587,510 588,507 Z';
        // Контур — открытым путём: верхняя кромка лежит на коме швом.
        const flapEdge = 'M628,506 C630,512 628,518 627,524 C627,534 630,542 633,548 '
            + 'C624,551 613,556 604,559 L596,563 C593,550 590,535 590,522 C589,515 587,510 588,507';
        const flapBack = 'M596,563 L607,558 C604,554 600,551 596,551 Z';
        // Клетка лоскута — в координатах полотна (u поперёк, v вдоль):
        // левый и правый края, лёгкая волна поперёк, провис к середине.
        const L = (v) => [589 + 7 * v, 505 + 58 * v], Rt = (v) => [628 + 5 * v, 505 + 43 * v];
        const fp = (u, v) => {
            const a = L(v), b = Rt(v);
            return [a[0] + (b[0] - a[0]) * u + 1.6 * Math.sin(u * Math.PI * 3) * v,
                    a[1] + (b[1] - a[1]) * u + 2.5 * v * Math.sin(u * Math.PI)];
        };
        const quad = (u0, u1, v0, v1) => {
            const N = 6, pts = [];
            for (let i = 0; i <= N; i++) pts.push(fp(u0 + (u1 - u0) * i / N, v0));
            for (let i = 0; i <= N; i++) pts.push(fp(u1, v0 + (v1 - v0) * i / N));
            for (let i = N; i >= 0; i--) pts.push(fp(u0 + (u1 - u0) * i / N, v1));
            for (let i = N; i >= 0; i--) pts.push(fp(u0, v0 + (v1 - v0) * i / N));
            return 'M' + pts.map(p => f(p[0]) + ',' + f(p[1])).join(' L') + ' Z ';
        };
        let flapV = '', flapH = '';
        for (let k = 0; k < 5; k++) flapV += quad(k / 5 + 0.03, k / 5 + 0.12, -0.05, 1.05);
        // Ряды СЖАТЫ к перекладине: так ткань заворачивает через неё без
        // овала-валика (валик-«крышка» читался шляпой или банкой).
        [[0, 0.035], [0.075, 0.125], [0.19, 0.255], [0.33, 0.405], [0.49, 0.57], [0.66, 0.74], [0.83, 0.91]]
            .forEach(([a, b]) => { flapH += quad(-0.05, 1.05, a, b); });

        // Махры: короткие нити веером, не строго вертикально. Толще hairline:
        // тоньше они пропадали в руке. Поверх контура — иначе чернила съедают
        // их основания.
        const fringeHeap = 'M549,527 L548,532 M555,530 L555,535 M561,531 L562,536 M567,532 L567,536';
        const fringeFlap = 'M599,565 L597,570 M605,562 L605,568 M611,559 L612,565 M617,557 L617,562 M623,554 L625,559 M629,551 L631,555';
        const FRINGE = 1.4;

        // ================= СВЕТОТЕНЬ =================
        // Свет сверху-слева, сплошными заливками рампы (заливки под клипом
        // всё равно прижаты к рамке кома — габарит считается без клипов); клетка ляжет ПОВЕРХ и
        // сама потемнеет в тени и посветлеет на свету. Между rag[3] и
        // rag[0/1] всегда полоса базы: светлое вплотную к тёмному по одной
        // линии читается ребром камня, а не тканью.
        const heapShade = 'M537,514 C552,522 566,524 580,521 C586,524 596,526 606,524 C620,524 632,518 642,508 L642,533 L537,533 Z '
            + 'M631,485 C637,493 638,503 634,512 C630,506 628,497 626,490 Z';
        const valley = 'M594,477 L598,484 C597,493 596,503 592,512 C589,504 590,492 588,486 Z';
        const heapLit = 'M562,485 C566,479 571,476 576,476 C580,475 583,477 585,479 C588,477 590,478 591,481 C583,480 575,482 569,487 C566,489 563,489 562,485 Z '
            + 'M604,487 C609,483 615,483 620,483 C625,482 629,484 632,487 C624,486 616,488 610,491 C607,492 604,490 604,487 Z';
        // Складки сжатия — ТРИ клина лучами от хвата (≈575, 492). Клинья, а не
        // черты: тонкие прямые черты читались шрамом или птичьей лапкой, а
        // светлые «губы» у складок — палочками.
        const folds = 'M574,491 C566,495 559,500 552,505 C560,503 567,499 575,494 Z '
            + 'M576,495 C576,502 574,509 570,516 C574,509 577,502 580,495 Z '
            + 'M580,492 C585,495 589,500 590,507 C588,501 584,497 579,494 Z';
        // Подрубленный край у низа кома.
        const hem = 'M547,522 C554,527 562,529 571,529';
        // Лоскут: узкий свет у левого края и две тени-складки, сужающиеся к
        // перекладине, — лучами от перевала. Параллельные вертикали дали бы
        // занавеску.
        const flapLit = 'M592,523 C593,535 595,546 597,556 L600,555 C599,543 598,532 597,523 Z';
        const flapFolds = 'M604,523 C607,535 609,546 610,557 L615,555 C613,543 611,532 608,523 Z '
            + 'M617,522 C620,532 623,542 626,550 L629,548 C626,539 624,530 621,522 Z';
        // Перевал через перекладину: короткий блик слева и короткая тень под
        // перекладиной у ПРАВОГО края. Ровная дуга на всю ширину крупно
        // читалась ртом, сдвинутая вправо дуга — всё ещё улыбкой; поэтому тень
        // не дуга, а загиб, уходящий вниз в правую складку лоскута.
        const bendLit = 'M592,507 C597,504 603,503 609,504';
        const bendShade = 'M610,514.5 C614,515.8 616.8,517.2 618.3,520.8';

        const main = `
            <defs>
                <clipPath id="§-heap"><path d="${S(heap)}"/></clipPath>
                <clipPath id="§-ckL"><path d="${S(clipL)} ${S(lowLeft)}" clip-rule="evenodd"/></clipPath>
                <clipPath id="§-ckB"><path d="${S(lowLeft)}"/></clipPath>
                <clipPath id="§-ckR"><path d="${S(clipR)}"/></clipPath>
            </defs>
            <path d="${S(heap)}" fill="${R[2]}"/>
            <g clip-path="url(#§-heap)">
                <path d="${S(heapShade)}" fill="${R[1]}"/>
                <path d="${S(valley)}" fill="${R[0]}"/>
                <path d="${S(heapLit)}" fill="${R[3]}"/>
                <!-- Клетка трёх участков: левая масса, её низ между складками, правая. -->
                ${bars(grid(570, 495, -18), 'ckL')}${bars(grid(556, 516, 6), 'ckB')}${bars(grid(620, 500, 14), 'ckR')}
            </g>
            <path d="${S(heapBack)}" fill="${back}" stroke="${ink}" stroke-width="${STROKE.structure}" stroke-linejoin="round"/>
            <path d="${S(folds)}" fill="${R[1]}"/>
            <path d="${S(hem)}" fill="none" stroke="${R[3]}" stroke-width="1.4" stroke-linecap="round"/>
            <path d="${S(heap)}" fill="none" stroke="${ink}" stroke-width="${W2}" stroke-linejoin="round"/>
            <path d="${S(fringeHeap)}" fill="none" stroke="${ink}" stroke-width="${FRINGE}" stroke-linecap="round"/>`;

        const front = `
            <defs><clipPath id="§-flap"><path d="${S(flap)}"/></clipPath></defs>
            <path d="${S(flap)}" fill="${R[2]}"/>
            <g clip-path="url(#§-flap)">
                <path d="${S(bendLit)}" fill="none" stroke="${R[3]}" stroke-width="2.4" stroke-linecap="round"/>
                <path d="${S(bendShade)}" fill="none" stroke="${R[1]}" stroke-width="1.6" stroke-linecap="round"/>
                <path d="${S(flapLit)}" fill="${R[3]}"/>
                <path d="${S(flapFolds)}" fill="${R[1]}"/>
                <path d="${S(flapV)}" fill="${CK}" fill-opacity="${OP}"/>
                <path d="${S(flapH)}" fill="${CK}" fill-opacity="${OP}"/>
            </g>
            <path d="${S(flapBack)}" fill="${back}" stroke="${ink}" stroke-width="${STROKE.structure}" stroke-linejoin="round"/>
            <path d="${S(flapEdge)}" fill="none" stroke="${ink}" stroke-width="${W2}" stroke-linejoin="round" stroke-linecap="round"/>
            <path d="${S(fringeFlap)}" fill="none" stroke="${ink}" stroke-width="${FRINGE}" stroke-linecap="round"/>`;

        return { main, front };
    }
};

if (typeof window !== 'undefined') window.BATH_CLOTH = BATH_CLOTH;
