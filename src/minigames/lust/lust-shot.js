// ============ ПОЛЁТ КАПЛИ: ОДНА ФИЗИКА НА ИГРУ И НА КАЛЬКУЛЯТОР ============
//
// Раньше попадание решала формула («долетело, если сила ≥ порога; попало,
// если угол в допуске»), а на экране рисовалась картинка про то же самое, но
// отдельно. Игрок видел, что струя идёт в рот, и не попадал: считалось одно,
// показывалось другое.
//
// Теперь капля — снаряд. Она летит по баллистике, и попадание — это
// СТОЛКНОВЕНИЕ с открытым ртом. Что видно, то и засчитано.
//
// Файл нарочно без единого обращения к DOM: его читает и запускает
// tools/sim-lust.js — тем же шагом, теми же числами. Считать баланс по копии
// физики нельзя ровно по той же причине, по какой нельзя по копии конфига.
const LustShot = {

    // Один толчок. Направление — касательная кончика хвоста; к нему
    // прибавляется разброс струи. Сила решает начальную скорость, то есть
    // насколько далеко капля летит.
    //
    // Сила — ПРОМЕЖУТОК minPower…maxPower, и прокачка двигает оба конца. Низ
    // лестницы хвоста режет и верхний конец: самый сильный толчок новичка
    // слабее полного, и часть струй не долетает даже при идеальном прицеле.
    // Так прокачка чувствуется с первой ступени, а не только после того, как
    // нижняя граница поднялась.
    //
    // Увода хвоста (`slop`) здесь больше НЕТ: раньше он был случайной
    // добавкой к углу, то есть изображал неточность руки числом. Теперь рука
    // настоящая — хвост держится свайпами, а насколько он послушен, решают
    // `pushBend` и `relaxBend` ниже. Поле читается только ради старых
    // лестниц, у которых оно ещё есть.
    launch(cfg, tier, dir, rnd) {
        const r = rnd || Math.random;
        const u = (a, b) => a + r() * (b - a);
        const power = u(tier.minPower || 0, tier.maxPower == null ? 1 : tier.maxPower);
        const err = (u(-tier.spread, tier.spread) + (tier.slop ? u(-tier.slop, tier.slop) : 0))
                  * Math.PI / 180;
        const a = dir + err;
        const v = cfg.speedMin + power * (cfg.speedMax - cfg.speedMin);
        return { vx: Math.cos(a) * v, vy: Math.sin(a) * v, power, err, angle: a };
    },

    // ================= ХВОСТ ПОД ПАЛЬЦЕМ =================
    // Две половины одного управления, и обе покупаются прокачкой хвоста:
    //
    //   pushBend  — сколько наклона даёт свайп. `gain` — наклон на радиан
    //               хода пальца по дуге вокруг корня. Работает В ОБЕ
    //               стороны: ход назад разгибает хвост с той же отдачей и
    //               складывается с его собственным выпрямлением;
    //   relaxBend — как быстро хвост выпрямляется сам. `relax` — доля изгиба
    //               в секунду, и тем быстрее, чем сильнее согнут (`hard`).
    //
    // На низкой прокачке свайп даёт мало, а хвост выпрямляется быстро: точно
    // держать угол можно, но только частыми размашистыми свайпами. Угол НЕ
    // ограничивается, ограничивается отдача — так навык по-прежнему решает,
    // просто работать руками приходится больше.
    //
    // Живут здесь, а не в lust.js, по той же причине, что и полёт капли:
    // баланс считает tools/sim-lust.js, и копия этих двух строк в нём однажды
    // разошлась бы с игрой.
    // Первая версия считала только ход ВПЕРЁД, а ход назад просто заново
    // заводил руку. Разогнуть хвост можно было одним способом — отпустить и
    // ждать, и направление струи игроку не принадлежало: он мог только
    // догонять прицел. Теперь палец ведёт угол в обе стороны, а куда лить —
    // в рот или мимо, — решает он сам. Разгибается хвост до прямого, не
    // дальше.
    pushBend(bend, arc, tier, max) {
        const b = bend + arc * tier.gain;
        return Math.max(0, Math.min(max == null ? 1 : max, b));
    },

    relaxBend(bend, dt, tier, max) {
        const m = max == null ? 1 : max;
        const u = Math.max(0, bend) / m;
        const hard = tier.hard == null ? 1.3 : tier.hard;
        let b = bend - bend * tier.relax * (1 + hard * u * u) * dt;
        if (b < 0) b = 0;
        if (b > m) b = m;
        return b;
    },

    // ================= ШКАЛА НАД ГОЛОВОЙ =================
    // Деления РАЗНОЙ цены и набираются ПО ПОРЯДКУ, каждое с нуля. Первое
    // дешёвое — новичок почти никогда не уходит пустым; последнее дорогое —
    // целый жетон берут только прокачка и руки. Возвращает, сколько делений
    // закрыто и сколько попаданий лежит в текущем незакрытом.
    gaugeState(hits, steps) {
        let left = hits, done = 0;
        for (const c of steps) {
            if (left < c) return { done, inPart: left };
            left -= c; done++;
        }
        return { done, inPart: 0 };
    },

    // Шаг интегрирования. Возвращает состояние капли; игра рисует его, а
    // калькулятор просто крутит в цикле.
    step(d, cfg) {
        d.vy += cfg.gravity * cfg.dt;
        d.x += d.vx * cfg.dt;
        d.y += d.vy * cfg.dt;
        d.t += cfg.dt;
        return d;
    },

    // Попала ли капля в рот. Рот — КОРЗИНА: круг заданного радиуса вокруг
    // точки рта, а не угловой допуск. Угловой допуск и был причиной, по
    // которой видимое расходилось с засчитанным.
    inMouth(d, mouth, r) {
        const dx = d.x - mouth.x, dy = d.y - mouth.y;
        return dx * dx + dy * dy <= r * r;
    },

    // Долетела, упала или улетела за кадр.
    spent(d, cfg) {
        return d.t >= cfg.maxT || d.y > cfg.floorY
            || d.x < -100 || d.x > 820;
    },

    // Весь полёт разом — для калькулятора и для поиска прицела.
    fly(cfg, from, vel, mouth, r) {
        const d = { x: from.x, y: from.y, vx: vel.vx, vy: vel.vy, t: 0 };
        let near = Infinity;
        while (!this.spent(d, cfg)) {
            this.step(d, cfg);
            const dx = d.x - mouth.x, dy = d.y - mouth.y;
            const dist = Math.hypot(dx, dy);
            if (dist < near) near = dist;
            if (dist <= r) return { hit: true, near: dist, t: d.t };
        }
        return { hit: false, near, t: d.t };
    }
};

if (typeof module !== 'undefined') module.exports = LustShot;
