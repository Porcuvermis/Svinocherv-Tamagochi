// ================= ВАННАЯ: ИГРОВОЙ СЛОЙ ПОВЕРХ ЗАПЕЧЁННОГО =================
// Запечённое (bath-baked.js) знает, КАК выглядит комната. Этот файл знает,
// ЧТО в кадре, что интерактивно и где у чего гнездо. Разделение то же, что на
// кухне, и по той же причине: пока картинка и раскладка жили в одном файле,
// любая правка вида тянула за собой правку геометрии игры.
//
// ---------- ГЛАВНОЕ ОТЛИЧИЕ ОТ КУХНИ ----------
// Здесь НЕТ собственных чисел раскладки. Гнёзда берутся из ЯКОРЕЙ запекания —
// точек мира, спроецированных той же камерой, что и предметы. Разъехаться с
// картинкой они не могут по построению.
//
// Что осталось двумерным и живёт здесь: мыльная муть, пена, пузыри, струя.
// Это не предметы, а следы на теле, и лепить их из геометрии незачем.

const btPal = () => PALETTE.bathScene;
const btBake = () => BATH_BAKED;

// Невидимая зона захвата: `fill="none"` событий не ловит, нужна прозрачная
// заливка (docs/traps.md, п. 1).
function btGrab(rx, ry, cx, cy) {
    return `<ellipse cx="${cx || 0}" cy="${cy || 0}" rx="${rx}" ry="${ry}"
                     fill="#000" fill-opacity="0" pointer-events="all"/>`;
}

// Детерминированный шум: раскладка пены и пузырей выводится из сида, а не
// берётся из Math.random — иначе она меняется на каждой перерисовке и
// картинка мигает.
function btRng(seed) {
    let s = (seed || 1) >>> 0;
    return () => {
        s = (s * 1664525 + 1013904223) >>> 0;
        return s / 4294967296;
    };
}

const BATH_ART = {

    W: 720,
    H: 1440,

    // Порядок предметов в кадре. Между предметами он задан СПИСКОМ — то же
    // решение, что и при запекании: соприкасающиеся поверхности алгоритм
    // художника не разводит, и порядок здесь решение художника.
    ORDER: ['wall', 'floor', 'shower', 'faucet', 'shelf', 'soap', 'cloth',
            'shelfRail', 'tub'],

    // Куда наезжает камера. Прямоугольники вписываются ЦЕЛИКОМ (contain),
    // поэтому вокруг предмета всегда виден кусок комнаты.
    // Прямоугольники берутся С ЗАПАСОМ по краям. Кадр вписывается целиком,
    // то есть ширина кадра ложится ровно в ширину холста, — и предмет,
    // стоящий у самого края прямоугольника, упирается в рамку окна. Мочалку
    // так срезало пополам на обоих планах, а у душа срезало верх.
    FOCUS: {
        // Общий вид: ванна, душ и полка целиком. С него начинается забег, и
        // по нему игрок понимает устройство комнаты.
        overview: { x: 125, y: 190, w: 545, h: 810 },
        // Мытьё: червь и полка. Лейка из кадра УХОДИТ — воду больше не
        // выключают, и смотреть на неё незачем; вся работа теперь между
        // червём и двумя ярусами полки.
        body:     { x: 205, y: 270, w: 460, h: 600 },
        // ОДИН кадр на пузыри, поглаживание и финал: это один и тот же
        // эпизод, и переезд камеры посреди него читается сменой сцены.
        //
        // Он ТЕСНЕЕ, чем кадр мытья, и это главное: мыло, мочалка и полка
        // здесь уже не участвуют, а значит им незачем занимать экран.
        // В кадре остаются ровно двое — морда и хвост, — и композиция
        // сводится к ним. Заодно кадр держит ДУГУ, по которой полетит струя:
        // от кончика хвоста до рта.
        tail:     { x: 145, y: 304, w: 310, h: 420 },
        finish:   { x: 145, y: 304, w: 310, h: 420 }
    },

    // ---------- ГНЁЗДА ----------
    // Ни одного своего числа: всё приходит из якорей запекания.
    slots() { return btBake().anchors; },

    // Габарит предмета в сцене — тоже из запекания.
    box(name) { return btBake().box(name); },

    // Во сколько раз предмет в руке крупнее, чем на полке. Немного, а не
    // вдвое: предмет живёт в координатах ХОЛСТА, поэтому наезд камеры его не
    // уменьшает, и множитель 1.7 давал мыло в половину экрана.
    DRAG_SCALE: 1.15,

    // ---------- СЦЕНА ----------
    // Комната разложена на ДВА холста, между которыми лежит червь. Причина
    // не в красоте: рендерер персонажа монтирует свой собственный svg в
    // html-контейнер, вложить его в группу сцены нельзя. Значит либо червь
    // поверх всей комнаты, либо комната разрезана там, где он должен быть.
    // Разрез — по поверхности воды: червь ЛЕЖИТ В НЕЙ, и вода обязана
    // накрывать его снизу.
    sceneBack() {
        const B = btBake(), A = B.anchors;
        return `
        <!-- ГЛУБИНА КАДРА. Стена с плиткой дальше всех, значит и размыта она
             сильнее всех; червь посередине — размыт заметно, но слабее;
             чаша и хвост на переднем плане резкие. Пока размыт был один
             червь, глубины не читалось: резкая плитка спорила с ним и
             тянула взгляд на себя.

             Размытие фона — РОДНОЙ svg-фильтр, а не css. WebKit не применяет
             css filter к внутренним элементам svg (docs/traps.md, история
             фильтра истощения в worm-renderer): на айфоне размытия просто не
             было бы. У червя css работает — он живёт в html-контейнере. -->
        <defs>
            <filter id="bt-far-blur" x="-20%" y="-20%" width="140%" height="140%"
                    color-interpolation-filters="sRGB">
                <feGaussianBlur id="bt-far-blur-amount" stdDeviation="0"/>
            </filter>
        </defs>
        <g id="bt-back-blur" filter="url(#bt-far-blur)">
        ${B.draw('wall')}
        ${B.drawTiles()}
        ${B.draw('floor')}
        ${B.drawSeams()}

        <g id="bt-shower">
            ${B.draw('shower')}
            ${btGrab(64, 78, A.showerHead.x, A.showerHead.y - 20)}
        </g>

        <!-- Дождь ИЗ ЛЕЙКИ, дальний слой: он за червём. Живёт отдельной
             группой, а не внутри запечённого душа, потому что включается
             по ходу забега. -->
        <g id="bt-rain-back" opacity="0"></g>

        ${B.draw('faucet')}

        ${B.draw('shelf')}
        <g id="bt-soap-home">${B.draw('soap')}
            ${btGrab(46, 34, A.soap.x, A.soap.y)}</g>
        <g id="bt-cloth-home">${B.draw('cloth')}
            ${btGrab(42, 40, A.cloth.x, A.cloth.y)}</g>

        <!-- Бортик доски ПОВЕРХ предметов: перекрытый низ — единственное,
             чем в лоб «на полке» отличается от «перед полкой». -->
        ${B.draw('shelfRail')}
        </g>
        `;
    },

    sceneFront() {
        const B = btBake();
        return `
        <!-- Ближние струи дождя: их немного и они бледные. Дождь только
             сзади читается стоящим ЗА червём, а не льющимся на него. -->
        <g id="bt-rain-front" opacity="0"></g>

        <!-- Хвост, пена и пузыри — ПОД ЧАШЕЙ, ровно как червь. Хвост торчит
             ИЗ ванны, а не стоит перед ней: борт обязан резать его снизу,
             иначе он висит перед чашей отдельным предметом. По той же
             причине под чашей и пена — её низ должен уходить за борт, как
             у воды.

             На ввод порядок не влияет: пузыри ловятся по координатам сцены,
             а не попаданием в узел. -->
        <g id="bt-tail" opacity="0"></g>

        <!-- Горка пены НАД хвостом и ПОД пузырями. Она копится, пока червя
             трут мочалкой, и к моменту, когда хвост всплывает, закрывает его
             целиком: появление хвоста не должно быть видно. Дальше игрок
             разбирает горку пузырь за пузырём — и хвост проявляется. -->
        <g id="bt-foam"></g>
        <g id="bt-bubbles"></g>

        <!-- Чаша ЦЕЛИКОМ и ПОВЕРХ червя. Камера смотрит в лоб, дальнего борта
             не видно вовсе, и всё ниже ближнего борта закрыто им — червь
             режется ровной линией и оказывается «в ванне» даром. Пила по
             глубине была нужна только косой камере (docs/bake-3d.md). -->
        ${B.draw('tub')}

        <!-- Струи и шкала — поверх всего: они не в комнате, они про игру. -->
        <g id="bt-shots"></g>
        <g id="bt-gauge"></g>
        <g id="bt-spot"></g>
        `;
    },

    // ---------- ДОЖДЬ ИЗ ЛЕЙКИ ----------
    // Не «поверхность воды», а падающие струйки. Уровня в ванне больше нет:
    // камера смотрит в лоб, нутра чаши не видно, и наливать туда нечего.
    // Вода в кадре нужна ровно для одного — показать, что душ включён.
    //
    // Струйки идут КОЛОНКАМИ, и внутри колонки повторяются через один и тот
    // же шаг. Колонка целиком едет вниз ровно на этот шаг и начинает круг
    // заново — стык не виден, а вся анимация стоит одного css-правила на
    // группу. Ни одного таймера в js (CLAUDE.md, инвариант 1).
    //
    // near — ближний слой: реже, бледнее и тоньше. Ему падать перед червём.
    rain(near) {
        const w = btPal().water, A = btBake().anchors;
        const S = A.showerHead, rng = btRng(near ? 31 : 7);
        const TOP = S.y + 16, BOT = 806;     // ниже борта: конец струи прячет ванна
        const cols = near ? 6 : 15;
        const HALF_TOP = 30, HALF_BOT = 152; // раструб лейки → пятно на червя
        // Пятно уведено ВПРАВО: лейка повёрнута к червю (bath-models.js), а
        // его голова стоит правее посадочного якоря почти на два корпуса.
        // Отвесная струя лила рядом с ним, а не на него.
        const LEAN = 104;
        const out = [];
        for (let i = 0; i < cols; i++) {
            const k = (i + 0.5) / cols;
            const x0 = S.x + (k - 0.5) * 2 * HALF_TOP;
            const x1 = S.x + LEAN + (k - 0.5) * 2 * HALF_BOT + (rng() - 0.5) * 26;
            const step = 96 + rng() * 54;          // шаг повтора внутри колонки
            const len = near ? 16 + rng() * 12 : 22 + rng() * 20;
            const dur = (near ? 0.62 : 0.5) + rng() * 0.3;
            const segs = [];
            // От TOP - step, чтобы в начале круга колонка не была пустой сверху.
            for (let y = TOP - step; y < BOT + step; y += step) {
                const t0 = (y - TOP) / (BOT - TOP);
                const x = x0 + (x1 - x0) * Math.max(0, Math.min(1, t0));
                segs.push(`<line x1="${x.toFixed(1)}" y1="${y.toFixed(1)}"
                                 x2="${(x + (x1 - x0) * len / (BOT - TOP)).toFixed(1)}"
                                 y2="${(y + len).toFixed(1)}"/>`);
            }
            out.push(`<g class="bt-drip" style="--p:${step.toFixed(0)}px;
                         --d:${dur.toFixed(2)}s;
                         animation-delay:-${(rng() * 2).toFixed(2)}s">${segs.join('')}</g>`);
        }
        // Вуаль: еле заметный конус от лейки. Без неё колонки читаются
        // палочками, а не водой; с полной непрозрачностью — мутным стеклом
        // поверх червя.
        const veil = near ? '' : `<path d="M${S.x - HALF_TOP} ${TOP}
                 L${S.x + HALF_TOP} ${TOP} L${S.x + LEAN + HALF_BOT} ${BOT}
                 L${S.x + LEAN - HALF_BOT} ${BOT} Z"
              fill="${w.surfHi}" opacity="0.13"/>`;
        // Обрезка снизу. Колонка повторяется с шагом и потому всегда чуть
        // длиннее заявленного — без обрезки хвост струй вылезал ИЗ-ПОД ванны
        // на пол: чаша закрывает их только на своей высоте.
        const id = near ? 'bt-rain-clip-n' : 'bt-rain-clip-f';
        return `<defs><clipPath id="${id}">
                  <rect x="0" y="${TOP - 40}" width="720" height="${BOT - TOP + 40}"/>
                </clipPath></defs>
                <g clip-path="url(#${id})">${veil}
                <g fill="none" stroke="${w.surfHi}"
                   stroke-linecap="round"
                   stroke-width="${near ? 1.7 : 2.6}"
                   opacity="${near ? 0.44 : 0.72}">${out.join('')}</g></g>`;
    },

    // ---------- ШКАЛА НАЛИВА ----------
    // Вертикальный столбик рядом с хвостом: видно, сколько ещё тереть.
    // Рядом, а не над головой: работа идёт по хвосту, и смотреть игрок
    // должен туда же (инвариант 9 — ни одной подписи, только столбик).
    rubGauge(x, y, h, k) {
        const p = btPal(), w = 15, r = w / 2;
        const fill = Math.max(0, Math.min(1, k));
        return `<g id="bt-rubgauge">
            <rect x="${(x - r).toFixed(1)}" y="${y.toFixed(1)}"
                  width="${w}" height="${h.toFixed(1)}" rx="${r}"
                  fill="${p.shadow}" fill-opacity="0.3"
                  stroke="${PALETTE.ink}" stroke-width="2.4"/>
            <rect x="${(x - r + 3).toFixed(1)}"
                  y="${(y + 3 + (h - 6) * (1 - fill)).toFixed(1)}"
                  width="${w - 6}" height="${((h - 6) * fill).toFixed(1)}"
                  rx="${r - 3}" fill="${p.foam.hi}" opacity="0.9"/>
        </g>`;
    },

    // ---------- ПРЕДМЕТ В РУКЕ ----------
    // Мыло и мочалка в руке — те же запечённые предметы, только крупнее:
    // одна и та же вещь не может быть в кадре из двух разных наборов.
    // camScale — во сколько раз сцена уменьшена текущим наездом. Без него
    // предмет в руке был бы нарисован в единицах сцены поверх экрана и
    // оказывался бы во столько же раз крупнее, во сколько камера отъехала.
    held(kind, camScale) {
        const B = btBake(), a = B.anchors[kind];
        const k = (camScale || 1) * this.DRAG_SCALE;
        // Запечённый предмет нарисован на своём месте на полке; в руке он
        // должен сидеть в НУЛЕ группы, поэтому сдвигается на своё же гнездо.
        return `<g transform="scale(${k.toFixed(4)}) translate(${-a.x} ${-a.y})">`
             + B.draw(kind) + `</g>`;
    },

    // ---------- МЫЛЬНАЯ МУТЬ И ПЕНА ----------
    // Мазок мылом — широкое мягкое пятно, тёрка мочалкой — мелкое и плотное.
    // Разные движения обязаны оставлять разный след, иначе второй этап
    // читается повтором первого (docs/plan/21-lust-bath.md).
    //
    // Рисуется НЕ в svg, а на холсте (см. lust.js). Причина в двух вещах
    // сразу, и обе смертельные:
    //
    // 1. Пятно в svg — это фигура, а фигура не умеет обрезаться по силуэту
    //    червя: мыло ложилось и на воду вокруг него.
    // 2. За проход мочалкой пятен набиралось под полторы сотни, и каждое —
    //    полупрозрачный узел поверх остальных. Браузер пересчитывает всю
    //    эту стопку на каждом кадре анимации червя, и кадры умирали.
    //
    // Холст решает оба: маска по силуэту — одна операция композиции, а вся
    // накопленная пена — один узел в дереве.
    //
    // Прозрачность НИЗКАЯ нарочно: мазки ложатся сотнями внахлёст, и та, что
    // выглядит правильной на одном, за проход собирается в сплошное белое
    // поле — червя под ним не видно вовсе.
    // Три состояния клетки, и они различаются НАЗНАЧЕНИЕМ, а не оттенком
    // одного и того же: муть от мыла — мягкая и приглушённая, пена от
    // мочалки — плотная и яркая, тремя ступенями по числу тёрок. Одна
    // яркость на все ступени означала «непонятно, засчиталось или нет».
    WASH: {
        soap:  { key: 'soapFilm', a: [0.62] },
        cloth: { key: 'foam',     a: [0.45, 0.72, 1.0] }
    },

    // Заливка одной клетки. t — доля от нужного числа проходов.
    // Пена на теле — ТЕ ЖЕ ПУЗЫРИ, что налипли на хвост, только нарисованные
    // на холсте. Радиальное пятно с мягким краем читалось запотевшим стеклом:
    // мыло есть, а пены нет. У пузыря есть КРАЙ, блик и сосед — из этого он и
    // читается пеной.
    //
    // Размеры идут ГРАДАЦИЕЙ: доля возводится в степень, поэтому мелких
    // много, крупных единицы — так пена и выглядит. Одинаковые кружки
    // складываются в сетку, а не в пену.
    //
    // Раскладка выводится из СИДА клетки: пена перерисовывается на каждый
    // мазок, и случайные числа заставили бы её мигать.
    // part: 'base' — только подложка (её обрезают силуэтом),
    //       'foam' — только пузыри (их НЕ обрезают),
    //       не задан — и то и другое разом.
    // inside(x, y) — необязательная проверка «точка на теле»: пузырь, чей
    // ЦЕНТР за силуэтом, не рисуется вовсе. Край при этом торчать наружу
    // может и должен — пузырь выпуклый, у кромки тела половина его снаружи.
    washCell(ctx, kind, x, y, cell, t, seed, part, inside) {
        const cloth = kind === 'cloth';
        const c = btPal()[cloth ? 'foam' : 'soapFilm'];
        const rng = btRng(seed);
        const k = t == null ? 1 : Math.max(0, Math.min(1, t));
        // Мыло — плёнка: пузырьков много и они мелкие. Мочалка взбивает:
        // пузыри крупнее, ярче и с краем, и тем гуще, чем больше тёрок.
        const n = cloth ? 4 + Math.round(k * 4) : 6;
        const big = cell * (cloth ? 0.66 : 0.46);
        const small = cell * (cloth ? 0.16 : 0.11);
        const A = cloth ? 0.34 + k * 0.3 : 0.3;
        // Недотёртая клетка обязана быть ВИДНО недотёртой. Раньше разница
        // между одной тёркой и тремя была в числе пузырей и в яркости —
        // на глаз это одна и та же пена, и игрок водил мочалкой по уже
        // «готовому» червю, ища невидимые клетки. Теперь у неполной клетки
        // пена занимает МЕНЬШЕ МЕСТА: между такими клетками остаются тёмные
        // прогалы мыльной плёнки, и недотёртое читается прямо на картинке.
        const spread = cloth ? 0.5 + 0.5 * k : 1;
        // Подложка под пузырями. Одни пузыри оставляют между собой голую
        // кожу, и намыленный червь читается обсыпанным, а не намыленным.
        // Слабая заливка по клетке закрывает эти просветы, не съедая
        // пузыри: они всё равно ярче и с краем.
        if (part !== 'foam') {
            ctx.globalAlpha = cloth ? 0.14 + k * 0.16 : 0.16;
            ctx.fillStyle = c[500];
            ctx.beginPath();
            ctx.arc(x, y, cell * 0.95 * spread, 0, Math.PI * 2); ctx.fill();
        }
        if (part === 'base') { ctx.globalAlpha = 1; return; }
        for (let i = 0; i < n; i++) {
            const r = (small + Math.pow(rng(), 2.1) * (big - small)) * spread;
            const a = rng() * Math.PI * 2;
            const d = Math.pow(rng(), 0.6) * cell * 0.72 * spread;
            const bx = x + Math.cos(a) * d, by = y + Math.sin(a) * d;
            // Пузырь садится на тело, а не цепляется за него краем: мало
            // того, что центр на силуэте, — половина пузыря обязана лежать
            // на нём же. Без второго условия крупный пузырь, чей центр попал
            // на кончик уха, висел в воздухе отдельным кольцом.
            if (inside) {
                if (!inside(bx, by)) continue;
                const q = r * 0.7;
                let n2 = 0;
                if (inside(bx - q, by)) n2++;
                if (inside(bx + q, by)) n2++;
                if (inside(bx, by - q)) n2++;
                if (inside(bx, by + q)) n2++;
                if (n2 < 2) continue;
            }
            ctx.globalAlpha = A;
            ctx.fillStyle = c[500];
            ctx.beginPath(); ctx.arc(bx, by, r, 0, Math.PI * 2); ctx.fill();
            ctx.globalAlpha = A * (cloth ? 1.5 : 1.1);
            ctx.lineWidth = Math.max(1, r * 0.16);
            ctx.strokeStyle = c.hi;
            ctx.beginPath(); ctx.arc(bx, by, r * 0.94, 0, Math.PI * 2); ctx.stroke();
            // Блик — только у крупных: на мелком он превращается в шум.
            if (r > cell * 0.3) {
                ctx.globalAlpha = A * 1.7;
                ctx.fillStyle = c.hi;
                ctx.beginPath();
                ctx.arc(bx - r * 0.32, by - r * 0.34, r * 0.26, 0, Math.PI * 2);
                ctx.fill();
            }
        }
        ctx.globalAlpha = 1;
    },

    // ---------- ХВОСТ ФИНАЛА ----------
    // Отдельная сущность, не привязанная к скелету (docs/plan/21-lust-bath.md,
    // раздел 2). Так не от лени: в финале червь выныривает у дальнего борта, а
    // хвост всплывает у ближнего — привязанный к телу хвост в такую раскладку
    // не встаёт, он растёт из конца туловища.
    //
    // От модели наследуется ТОЛЬКО оттенок: цвет хвоста обязан меняться
    // вместе с червём.
    //
    // ---------- ОН ГНЁТСЯ, А НЕ ПОВОРАЧИВАЕТСЯ ----------
    // Первая версия просто крутила готовую фигуру вокруг основания. На
    // экране это читалось предметом, лежащим поверх ванны и вращающимся на
    // месте: основание уезжало из воды, связи с чашей не было.
    //
    // Теперь хвост — ПРУТ. Основание всегда стоит вертикально и остаётся под
    // водой, кривизна набирается к кончику. Отсюда и форма изгиба: угол
    // растёт как t², то есть у корня прут почти прямой, а гнётся верхняя
    // треть — ровно так ведёт себя ветка, которую отгибают за макушку.
    // side: в какую сторону гнётся. −1 — влево: хвост стоит правее головы,
    // и тянуть его надо к ней.
    // Хвост НАЧИНАЕТ маленьким и растёт В ДЛИНУ: в этом весь этап.
    //
    // Потолок длины задан не на глаз, а ЦЕЛЬЮ: налившийся хвост своим
    // кончиком обязан остаться НИЖЕ рта — примерно по нижний край головы.
    // Корень стоит на y=748, рот на y≈595, значит вся длина с ростом не
    // больше ~130. Стоило кончику задраться выше рта, как струя переставала
    // лететь ВВЕРХ, дуги не оставалось и попадание вырождалось.
    //
    // 145×40 с ростом до 225×86 были размером с голову червя: два предмета
    // спорили за кадр, а прицел стал почти невозможен — длинное плечо
    // множит любую ошибку по углу.
    // side: 1 — хвост гнётся ВПРАВО, к морде. Хвост стоит левее головы,
    // и тянуть его надо к ней.
    TAIL: { len: 92, base: 34, seg: 22, side: 1 },

    // Осевая линия при заданном изгибе. bend — на сколько радиан уведён
    // КОНЧИК от вертикали; у основания отклонение всегда ноль.
    // grow — во сколько раз хвост длиннее исходного. Растёт он на этапе
    // поглаживания, и растёт ВСЯ фигура: и осевая, и толщина. Держать рост
    // масштабом группы нельзя — вместе с хвостом поехал бы и его корень,
    // а тот обязан оставаться на месте, под бортом.
    tailSpine(bend, grow) {
        const T = this.TAIL, n = T.seg, ds = T.len * (grow || 1) / n;
        const k = T.side || 1;
        const pts = [{ x: 0, y: 0, a: 0 }];
        let x = 0, y = 0;
        for (let i = 1; i <= n; i++) {
            const t = i / n;
            // ЛУК, а не удочка. Наибольший изгиб — В СЕРЕДИНЕ, а не на самом
            // кончике: держат снизу, гнут сверху, и выгибается середина.
            // Профиль t²(3−2t) — та же плавная ступенька: угол растёт быстрее
            // всего на половине длины, значит там же и максимум кривизны.
            // Было t²: кривизна копилась к концу, и хвост вилял кончиком, как
            // хлыстом, — упругости в нём не читалось.
            const a = bend * t * t * (3 - 2 * t);
            x += k * Math.sin(a) * ds;
            y -= Math.cos(a) * ds;
            pts.push({ x, y, a });
        }
        return pts;
    },

    // Контур прута: осевая линия, разведённая на полутолщину по нормали.
    tailCurve(bend, grow) {
        const T = this.TAIL, g = grow || 1;
        const pts = this.tailSpine(bend, g), n = pts.length - 1;
        // Сужение с лёгкой выпуклостью в середине и ОСТРЫМ кончиком.
        // Линейное давало ровный треугольник — плавник, а не хвост; степень
        // без множителя оставляла кончик тупым, и изгиб на нём не читался.
        // Толщина растёт МЕДЛЕННЕЕ длины (степень меньше единицы): налив —
        // это прежде всего длина, а толщина идёт следом, чтобы хвост
        // набухал, а не масштабировался целиком. Было наоборот, степенью
        // 1.7, и выросший хвост оказывался с голову шириной.
        const half = (t) => (T.base / 2) * Math.pow(g, 0.7) * Math.pow(1 - t, 0.72)
                          * (1 + 0.28 * Math.sin(Math.PI * t));
        const left = [], right = [];
        for (let i = 0; i <= n; i++) {
            const p = pts[i], w = half(i / n);
            const nx = (T.side || 1) * Math.cos(p.a), ny = Math.sin(p.a);
            left.push(`${(p.x - nx * w).toFixed(1)} ${(p.y - ny * w).toFixed(1)}`);
            right.push(`${(p.x + nx * w).toFixed(1)} ${(p.y + ny * w).toFixed(1)}`);
        }
        // Низ уходит под воду, поэтому основание закрывается прямой: закруглять
        // то, чего не видно, незачем.
        const d = `M${left.join('L')}L${right.reverse().join('L')}Z`;
        const tip = pts[n];
        return { d, spine: pts, tip,
                 // Направление кончика в координатах сцены: фигура смотрит
                 // ВВЕРХ, то есть в −y.
                 dir: Math.atan2(-Math.cos(tip.a), (T.side || 1) * Math.sin(tip.a)) };
    },

    // Две линии хвоста при заданном изгибе: сам прут и блик по нему. Блик
    // идёт ПО ОСИ, а не отдельной дугой: при изгибе он обязан гнуться вместе
    // с телом, иначе съезжает с формы.
    // Полуширина хвоста в доле t вдоль оси. Пузыри садятся ПО НЕЙ, а не по
    // постоянной: у основания хвост вдвое толще, чем у кончика, и общая
    // ширина сажала половину пены мимо, на плитку.
    tailHalf(t, grow) {
        const g = grow || 1;
        return (this.TAIL.base / 2) * Math.pow(g, 0.7)
             * Math.pow(1 - t, 0.72) * (1 + 0.28 * Math.sin(Math.PI * t));
    },

    tailD(bend, grow) {
        const c = this.tailCurve(bend || 0, grow);
        const shine = c.spine.filter((p, i) => i > 1 && i < c.spine.length - 3)
            .map(p => `${(p.x - (this.TAIL.side || 1) * Math.cos(p.a) * this.TAIL.base * 0.17 * (grow || 1)).toFixed(1)} `
                    + `${(p.y - Math.sin(p.a) * this.TAIL.base * 0.17 * (grow || 1)).toFixed(1)}`);
        return { body: c.d, shine: 'M' + shine.join('L'), curve: c };
    },

    // Разметка хвоста собирается ОДИН РАЗ, дальше меняются только атрибуты d.
    // Пересобирать её каждый кадр значит парсить строку шестьдесят раз в
    // секунду ради двух чисел — на телефоне это заметно.
    tail(model) {
        const m = (model && model.tail) || {};
        // Оттенок берётся у предхвостового сегмента тела, а не у собственного
        // хвоста модели: тот покрашен в самую тёмную ступень мяса, и хвост
        // такого размера читался тёмным клинком, а не частью червя.
        const seg = (model && model.growingSegments && model.growingSegments[0])
                 || (model && model.belly) || null;
        const fill = (seg && seg.fill) || m.fill || PALETTE.flesh[700];
        const ink = (seg && seg.stroke) || m.stroke || PALETTE.ink;
        return `
        <path id="bt-tail-body" d="" fill="${fill}" stroke="${ink}"
              stroke-width="3" stroke-linejoin="round"/>
        <path id="bt-tail-shine" d="" fill="none" stroke="${PALETTE.flesh[100]}"
              stroke-width="7" stroke-linecap="round" opacity="0.38"/>`;
    },

    // ---------- ПУЗЫРИ ПЕНЫ ----------
    // Пузырь читается пузырём по БЛИКУ, а не по кружку: без блика это пятно
    // той же пены, и лопать его незачем.
    bubble(x, y, r, seed) {
        const f = btPal().foam;
        const rng = btRng(seed);
        const ox = (rng() - 0.5) * r * 0.5, oy = -r * (0.28 + rng() * 0.14);
        return `<g class="bt-bubble" data-r="${r.toFixed(1)}"
                   data-x="${x.toFixed(1)}" data-y="${y.toFixed(1)}">
            <circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"
                    fill="${f[500]}" fill-opacity="0.52"
                    stroke="${f.rim}" stroke-width="2"/>
            <circle cx="${(x + ox).toFixed(1)}" cy="${(y + oy).toFixed(1)}"
                    r="${(r * 0.3).toFixed(1)}" fill="${f.hi}" opacity="0.85"/>
        </g>`;
    },

    // ---------- ГОРКА ПЕНЫ НАД ХВОСТОМ ----------
    // Не украшение, а ШИРМА: под ней всплывает хвост, и всплытие не должно
    // быть заметно. Отсюда и требование — горка непроницаема, пока цела.
    //
    // Собирается из перекрывающихся комков: один эллипс читается яйцом, а
    // десяток разнокалиберных кругов — комом пены. Растёт снизу вверх по
    // доле k: пока червя трут мочалкой, k — это доля вытертого тела, а когда
    // пузыри лопают — доля оставшихся.
    foamMound(x, y, w, h, k, seed) {
        const f = btPal().foam;
        const g = Math.max(0, Math.min(1, k));
        if (g <= 0.01) return '';
        const rng = btRng(seed || 7);
        const H = h * (0.35 + 0.65 * g);      // высота растёт с наливом
        const W = w * (0.6 + 0.4 * g);
        const out = [];
        // Комки идут снизу вверх и сужаются к макушке: у кучи пены широкое
        // основание, иначе она читается облаком в воздухе.
        for (let i = 0; i < 22; i++) {
            const t = Math.pow(i / 21, 0.85);
            const half = (W / 2) * (1 - 0.62 * t);
            const bx = x + (rng() - 0.5) * 2 * half;
            const by = y - t * H - 2;
            const r = (W * 0.30) * (1 - 0.42 * t) * (0.7 + rng() * 0.6);
            out.push(`<circle cx="${bx.toFixed(1)}" cy="${by.toFixed(1)}"`
                   + ` r="${r.toFixed(1)}" fill="${f[500]}"/>`);
        }
        // Заливка НЕПРОЗРАЧНАЯ — иначе сквозь ширму видно хвост, — а
        // прозрачность у всей группы: так комки не просвечивают друг сквозь
        // друга и горка остаётся одним телом, а не кучей кружков.
        return `<g opacity="${(0.35 + 0.65 * g).toFixed(2)}">${out.join('')}</g>`;
    },

    // ---------- КАПЛИ И ПОТЁКИ ----------
    // Капля в полёте — густая, с вытянутым по скорости телом: по форме видно,
    // куда она летит. Потёк — то, что не попало: прилипло к поверхности и
    // ползёт вниз, оставляя хвост.
    //
    // Рисуется одной строкой на кадр: капель единицы, и держать их узлами
    // ради этого незачем.
    // Лужицы во рту здесь НЕТ и быть не может: она — часть самого рта
    // (worm-renderer, mouthFill), а не пятно поверх морды. Пока её рисовали
    // тут, её приходилось наводить на рот числами после каждого переезда
    // камеры, она не размывалась вместе с червём и при малейшем расхождении
    // оказывалась на щеке.
    drops(flying, splats) {
        const m = btPal().milk, out = [];
        for (const s of (splats || [])) {
            if (s.gulp) {
                // Попадание: короткая вспышка в самой корзине рта.
                const k = 1 - s.t / 0.45;
                out.push(`<circle cx="${s.x.toFixed(1)}" cy="${s.y.toFixed(1)}"
                                  r="${(s.r * (1.6 - k)).toFixed(1)}" fill="none"
                                  stroke="${m.hi}" stroke-width="5"
                                  opacity="${(k * 0.9).toFixed(2)}"/>`);
                continue;
            }
            // Промах ОСТАЁТСЯ там, куда попал. Сначала стекает, потом
            // застывает — и к концу забега по стене видно всю историю
            // промахов. Таяли — и стрелять было будто в пустоту.
            out.push(`<path d="M${(s.x - s.r).toFixed(1)} ${s.y.toFixed(1)}
                             a${s.r.toFixed(1)} ${s.r.toFixed(1)} 0 1 0 ${(s.r * 2).toFixed(1)} 0
                             l${(-s.r).toFixed(1)} ${(s.r * 2.2).toFixed(1)} Z"
                            fill="${m[500]}" stroke="${m.edge}" stroke-width="1.6"
                            opacity="0.88"/>`);
        }
        for (const d of (flying || [])) {
            const sp = Math.hypot(d.vx, d.vy) || 1;
            const ex = d.vx / sp, ey = d.vy / sp, L = d.r * 1.7;
            out.push(`<ellipse cx="${d.x.toFixed(1)}" cy="${d.y.toFixed(1)}"
                               rx="${(d.r + L).toFixed(1)}" ry="${d.r.toFixed(1)}"
                               fill="${m.hi}" stroke="${m.edge}" stroke-width="1.4"
                               transform="rotate(${(Math.atan2(ey, ex) * 180 / Math.PI).toFixed(1)}
                                          ${d.x.toFixed(1)} ${d.y.toFixed(1)})"/>`);
        }
        return out.join('');
    },

    // ---------- ШКАЛА ФИНАЛА ----------
    // Три секции, и ни одной буквы: сколько налито — столько и горит
    // (инвариант 9). Наполняется снизу вверх, как всё, что наливают.
    gauge(x, y, sections, filled) {
        const p = btPal(), h = 34, gap = 7, w = 26;
        const out = [];
        for (let i = 0; i < sections; i++) {
            const cy = y - i * (h + gap);
            const on = i < filled;
            out.push(`<rect x="${(x - w / 2).toFixed(1)}" y="${(cy - h).toFixed(1)}"
                            width="${w}" height="${h}" rx="7"
                            fill="${on ? p.water.surfHi : p.shadow}"
                            fill-opacity="${on ? 0.95 : 0.35}"
                            stroke="${p.foam.rim}" stroke-width="2"/>`);
        }
        return out.join('');
    },

    // ---------- УКАЗАТЕЛЬ НЕПОКРЫТОГО ----------
    // Порог 92% без подсказки превращается в поиск пикселя: игрок водит и не
    // понимает, почему этап не кончается (план, §1).
    spot(x, y, r) {
        return `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"
                        fill="none" stroke="${btPal().foam.hi}" stroke-width="4"
                        opacity="0.9"/>`;
    }
};
