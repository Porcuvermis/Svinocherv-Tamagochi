// ================= ВАННАЯ: ИГРОВОЙ СЛОЙ ПОВЕРХ СКЛАДА =================
// Склад (bath-objects.js) знает, КАК нарисован предмет. Этот файл знает, ЧТО
// стоит в кадре, что интерактивно и где у чего гнездо. Разделение то же, что
// на кухне, и по той же причине: пока картинка и раскладка жили в одном
// файле, любая правка вида тянула за собой правку геометрии игры.
//
// Ни одного числа отсюда НЕ повторять в lust.js: логика спрашивает координаты
// здесь. Кухня наступила на это дважды (docs/traps.md).

const btPal = () => PALETTE.bathScene;
const btObj = () => BATH_OBJECTS;

// Невидимая зона захвата в координатах игрового слоя.
function btGrab(rx, ry, cx, cy) {
    return `<ellipse cx="${cx || 0}" cy="${cy || 0}" rx="${rx}" ry="${ry}"
                     fill="#000" fill-opacity="0" pointer-events="all"/>`;
}

// Детерминированный шум: раскладка пены и пузырей выводится из сида, а не
// хранится и не берётся из Math.random — иначе она меняется на каждой
// перерисовке и картинка мигает.
function btRng(seed) {
    let s = (seed || 1) >>> 0;
    return () => {
        s = (s * 1664525 + 1013904223) >>> 0;
        return s / 4294967296;
    };
}

const BATH_ART = {

    // Сцена = комната плюс поля сверху и снизу: камера вписывает в стейдж
    // прямоугольник из FOCUS, и без полей по краям виден фон страницы.
    W: 720,
    H: 1440,

    // Куда наезжает камера. Прямоугольники вписываются ЦЕЛИКОМ (contain),
    // поэтому вокруг предмета всегда виден кусок комнаты.
    FOCUS: {
        // Общий вид: видно всё сразу — душ, полку, ванну. С него начинается
        // забег, и по нему игрок понимает устройство комнаты.
        overview: { x: 0,   y: 150, w: 720, h: 1080 },
        // Мытьё: червь в чаше крупно. Полка с мылом и мочалкой обязана
        // остаться в кадре — их отсюда и берут.
        body:     { x: 60,  y: 420, w: 660, h: 620 },
        // Хвост всплывает у ближнего борта.
        tail:     { x: 150, y: 560, w: 470, h: 520 },
        // Финал: голова червя и хвост одновременно.
        finish:   { x: 90,  y: 520, w: 600, h: 560 }
    },

    // ---------- ГНЁЗДА ----------
    // Всё, что игра ищет пальцем или чем целится, стоит здесь одним списком.
    SLOTS: {
        // Кран: тап по нему включает воду и начинает забег.
        faucet: { x: 150, y: 640 },
        // Лейка душа: из неё льётся, пока идёт мытьё.
        showerHead: { x: 232, y: 402 },
        // Полка: мыло и мочалка. Их ТАЩАТ на червя.
        soap:  { x: 484, y: 484 },
        cloth: { x: 610, y: 476 },
        // Куда кладётся червь: центр чаши между бортами.
        worm:  { x: 380, y: 790 },
        // Хвост в финале всплывает у ближнего борта, ближе к правому краю:
        // слева душ, и струя перекрывала бы его.
        tail:  { x: 430, y: 880 }
    },

    // Во сколько раз предмет в руке крупнее, чем на полке. Предмет под
    // пальцем обязан быть крупнее пальца, иначе не видно, что держишь. То же
    // число и по той же причине, что в саду.
    DRAG_SCALE: 1.6,

    // ---------- СЦЕНА ----------
    scene() {
        const O = btObj();
        return `
        ${O.wall.draw()}
        ${O.tileWall.draw()}
        ${O.floor.draw()}

        <!-- Душ и смеситель. Труба идёт по стене, поэтому рисуется ДО ванны:
             ванна ближе к камере и обязана её перекрывать. -->
        ${O.shower.draw()}
        <g id="bt-jet" opacity="0"></g>
        <g id="bt-faucet">
            ${O.faucet.draw()}
            ${btGrab(70, 60, 150, 640)}
        </g>

        <!-- Полка с мылом и мочалкой. -->
        ${O.shelf.draw()}
        <g id="bt-soap-home">${O.soap.draw()}${btGrab(58, 44, 484, 484)}</g>
        <g id="bt-cloth-home">${O.cloth.draw()}${btGrab(60, 46, 610, 476)}</g>

        <!-- Червь лежит в чаше: слой между ванной и водой, поэтому вода
             накрывает его снизу и он читается лежащим В воде, а не НА ней. -->
        <g id="bt-worm-layer"></g>

        <!-- Ванна с водой. Вода рисуется ПОСЛЕ червя — см. выше. -->
        ${O.bathTub.draw()}
        <g id="bt-water" opacity="0">${O.water.draw({ level: 1 })}</g>

        <!-- Мыльная муть и пена: их наносят пальцем, поэтому слои свои. -->
        <g id="bt-film"></g>
        <g id="bt-foam"></g>
        <g id="bt-bubbles"></g>
        `;
    },

    // ---------- СТРУЯ ИЗ ЛЕЙКИ ----------
    // Отдельной функцией, потому что её включают и выключают: пока вода не
    // включена, струи в кадре нет вовсе.
    jet() {
        const w = btPal().water;
        const S = this.SLOTS.showerHead, T = this.SLOTS.worm;
        const g = 'bt-jet-grad';
        const drops = [];
        const rng = btRng(7);
        for (let i = 0; i < 9; i++) {
            const t = rng();
            drops.push(`<ellipse cx="${(S.x + (t - 0.5) * 74).toFixed(0)}"
                                 cy="${(S.y + 40 + rng() * 300).toFixed(0)}"
                                 rx="2.6" ry="${(9 + rng() * 12).toFixed(1)}"
                                 fill="${w.surfHi}" opacity="0.55"/>`);
        }
        return `<defs>
            <linearGradient id="${g}" gradientUnits="userSpaceOnUse"
                            x1="0" y1="${S.y}" x2="0" y2="${T.y}">
                <stop offset="0" stop-color="${w.surfHi}" stop-opacity="0.55"/>
                <stop offset="1" stop-color="${w.surf}" stop-opacity="0.18"/>
            </linearGradient>
        </defs>
        <path d="M${S.x - 34} ${S.y + 6} L${S.x + 34} ${S.y + 6}
                 L${S.x + 62} ${T.y + 40} L${S.x - 58} ${T.y + 40} Z"
              fill="url(#${g})"/>
        ${drops.join('')}`;
    },

    // ---------- ПРЕДМЕТ В РУКЕ ----------
    // Мыло и мочалка в руке — те же предметы склада, только крупнее: одна и
    // та же вещь не может быть в кадре из двух разных наборов.
    held(kind) {
        const O = btObj();
        const o = kind === 'cloth' ? O.cloth : O.soap;
        const s = this.SLOTS[kind === 'cloth' ? 'cloth' : 'soap'];
        // Предмет склада нарисован на своём месте на полке; в руке он должен
        // сидеть в НУЛЕ группы, поэтому сдвигается на своё же гнездо.
        return `<g transform="scale(${this.DRAG_SCALE}) translate(${-s.x} ${-s.y})">`
             + o.draw() + `</g>`;
    }
};
