// ================= ВАННАЯ: ИГРОВОЙ СЛОЙ ПОВЕРХ ЗАПЕЧЁННОГО =================
// Запечённое (bath-baked.js) знает, КАК выглядит комната. Этот файл знает,
// ЧТО в кадре, что интерактивно и где у чего гнездо. Разделение то же, что на
// кухне, и по той же причине: пока картинка и раскладка жили в одном файле,
// любая правка вида тянула за собой правку геометрии игры.
//
// ---------- ГЛАВНОЕ ОТЛИЧИЕ ОТ КУХНИ ----------
// Здесь НЕТ собственных чисел раскладки. Гнёзда берутся из ЯКОРЕЙ запекания —
// точек мира, спроецированных той же камерой, что и предметы. Разъехаться с
// картинкой они не могут по построению.
//
// Что осталось двумерным и живёт здесь: мыльная муть, пена, пузыри, струя.
// Это не предметы, а следы на теле, и лепить их из геометрии незачем.

const btPal = () => PALETTE.bathScene;
const btBake = () => BATH_BAKED;

// Невидимая зона захвата: `fill="none"` событий не ловит, нужна прозрачная
// заливка (docs/traps.md, п. 1).
function btGrab(rx, ry, cx, cy) {
    return `<ellipse cx="${cx || 0}" cy="${cy || 0}" rx="${rx}" ry="${ry}"
                     fill="#000" fill-opacity="0" pointer-events="all"/>`;
}

// Детерминированный шум: раскладка пены и пузырей выводится из сида, а не
// берётся из Math.random — иначе она меняется на каждой перерисовке и
// картинка мигает.
function btRng(seed) {
    let s = (seed || 1) >>> 0;
    return () => {
        s = (s * 1664525 + 1013904223) >>> 0;
        return s / 4294967296;
    };
}

const BATH_ART = {

    W: 720,
    H: 1440,

    // Порядок предметов в кадре. Между предметами он задан СПИСКОМ — то же
    // решение, что и при запекании: соприкасающиеся поверхности алгоритм
    // художника не разводит, и порядок здесь решение художника.
    ORDER: ['wall', 'floor', 'shower', 'faucet', 'shelf', 'soap', 'cloth',
            'tub', 'water'],

    // Куда наезжает камера. Прямоугольники вписываются ЦЕЛИКОМ (contain),
    // поэтому вокруг предмета всегда виден кусок комнаты.
    FOCUS: {
        // Общий вид: видно всё сразу — душ, полку, ванну. С него начинается
        // забег, и по нему игрок понимает устройство комнаты.
        overview: { x: 20, y: 150, w: 690, h: 830 },
        // Мытьё: червь в чаше крупно. Полка обязана остаться в кадре — мыло
        // и мочалку берут оттуда.
        body:     { x: 170, y: 180, w: 545, h: 500 },
        // Хвост всплывает у ближнего борта.
        tail:     { x: 150, y: 140, w: 520, h: 530 },
        // Финал: голова червя и хвост одновременно.
        finish:   { x: 150, y: 140, w: 520, h: 530 }
    },

    // ---------- ГНЁЗДА ----------
    // Ни одного своего числа: всё приходит из якорей запекания.
    slots() { return btBake().anchors; },

    // Габарит предмета в сцене — тоже из запекания.
    box(name) { return btBake().box(name); },

    // Во сколько раз предмет в руке крупнее, чем на полке. Немного, а не
    // вдвое: предмет живёт в координатах ХОЛСТА, поэтому наезд камеры его не
    // уменьшает, и множитель 1.7 давал мыло в половину экрана.
    DRAG_SCALE: 1.15,

    // ---------- СЦЕНА ----------
    // Комната разложена на ДВА холста, между которыми лежит червь. Причина
    // не в красоте: рендерер персонажа монтирует свой собственный svg в
    // html-контейнер, вложить его в группу сцены нельзя. Значит либо червь
    // поверх всей комнаты, либо комната разрезана там, где он должен быть.
    // Разрез — по поверхности воды: червь ЛЕЖИТ В НЕЙ, и вода обязана
    // накрывать его снизу.
    sceneBack() {
        const B = btBake(), A = B.anchors;
        return `
        ${B.draw('wall')}
        ${B.drawTiles()}
        ${B.draw('floor')}
        ${B.draw('shower')}

        <!-- Струя из лейки. Появляется, когда открывают кран, и потому живёт
             отдельной группой, а не внутри запечённого душа. -->
        <g id="bt-jet" opacity="0"></g>

        <g id="bt-faucet">
            ${B.draw('faucet')}
            ${btGrab(52, 56, A.faucet.x, A.faucet.y)}
        </g>

        ${B.draw('shelf')}
        <g id="bt-soap-home">${B.draw('soap')}
            ${btGrab(50, 40, A.soap.x, A.soap.y)}</g>
        <g id="bt-cloth-home">${B.draw('cloth')}
            ${btGrab(50, 42, A.cloth.x, A.cloth.y)}</g>

        <!-- ДАЛЬНЯЯ половина чаши: она за червём, он стоит в ней. -->
        ${B.draw('tubFar')}
        `;
    },

    sceneFront() {
        const B = btBake();
        return `
        <!-- БЛИЖНЯЯ половина чаши: она перед червём и прячет его низ. Раньше
             он обрезался прямой линией по уровню воды — это и читалось
             «персонаж обрезан», — а целая чаша в переднем холсте убирала его
             за ванну целиком. Распил по глубине делает запекание
             (docs/bake-3d.md), здесь только порядок. -->
        ${B.draw('tubNear')}

        <!-- Хвост финала лежит ПОД водой. Он гнётся, а не поворачивается,
             поэтому корень всегда стоит вертикально и всегда остаётся ниже
             поверхности: вода сама прячет основание, и хвост читается
             торчащим ИЗ ванны, а не лежащим поверх неё. -->
        <g id="bt-tail" opacity="0"></g>

        <!-- Вода наливается: уровень задаётся высотой обрезки. -->
        <g id="bt-water" opacity="0">
            <clipPath id="bt-water-clip">
                <rect id="bt-water-rect" x="0" y="0" width="720" height="0"/>
            </clipPath>
            <g clip-path="url(#bt-water-clip)">${B.draw('water')}</g>
        </g>

        <!-- Пузыри, струи и шкала — поверх всего: их трогают пальцем. -->
        <g id="bt-bubbles"></g>
        <g id="bt-shots"></g>
        <g id="bt-gauge"></g>
        <g id="bt-spot"></g>
        `;
    },

    // ---------- СТРУЯ ИЗ ЛЕЙКИ ----------
    jet() {
        const w = btPal().water, A = btBake().anchors;
        const S = A.showerHead, T = A.worm;
        const g = 'bt-jet-grad';
        const drops = [];
        const rng = btRng(7);
        for (let i = 0; i < 11; i++) {
            drops.push(`<ellipse cx="${(S.x + (rng() - 0.5) * 52).toFixed(0)}"
                                 cy="${(S.y + 24 + rng() * (T.y - S.y)).toFixed(0)}"
                                 rx="2.4" ry="${(8 + rng() * 12).toFixed(1)}"
                                 fill="${w.surfHi}" opacity="0.5"/>`);
        }
        return `<defs>
            <linearGradient id="${g}" gradientUnits="userSpaceOnUse"
                            x1="0" y1="${S.y}" x2="0" y2="${T.y}">
                <stop offset="0" stop-color="${w.surfHi}" stop-opacity="0.5"/>
                <stop offset="1" stop-color="${w.surf}" stop-opacity="0.14"/>
            </linearGradient>
        </defs>
        <path d="M${S.x - 26} ${S.y + 4} L${S.x + 26} ${S.y + 4}
                 L${S.x + 52} ${T.y + 30} L${S.x - 46} ${T.y + 30} Z"
              fill="url(#${g})"/>
        ${drops.join('')}`;
    },

    // ---------- ПРЕДМЕТ В РУКЕ ----------
    // Мыло и мочалка в руке — те же запечённые предметы, только крупнее:
    // одна и та же вещь не может быть в кадре из двух разных наборов.
    // camScale — во сколько раз сцена уменьшена текущим наездом. Без него
    // предмет в руке был бы нарисован в единицах сцены поверх экрана и
    // оказывался бы во столько же раз крупнее, во сколько камера отъехала.
    held(kind, camScale) {
        const B = btBake(), a = B.anchors[kind];
        const k = (camScale || 1) * this.DRAG_SCALE;
        // Запечённый предмет нарисован на своём месте на полке; в руке он
        // должен сидеть в НУЛЕ группы, поэтому сдвигается на своё же гнездо.
        return `<g transform="scale(${k.toFixed(4)}) translate(${-a.x} ${-a.y})">`
             + B.draw(kind) + `</g>`;
    },

    // ---------- МЫЛЬНАЯ МУТЬ И ПЕНА ----------
    // Мазок мылом — широкое мягкое пятно, тёрка мочалкой — мелкое и плотное.
    // Разные движения обязаны оставлять разный след, иначе второй этап
    // читается повтором первого (docs/plan/21-lust-bath.md).
    //
    // Рисуется НЕ в svg, а на холсте (см. lust.js). Причина в двух вещах
    // сразу, и обе смертельные:
    //
    // 1. Пятно в svg — это фигура, а фигура не умеет обрезаться по силуэту
    //    червя: мыло ложилось и на воду вокруг него.
    // 2. За проход мочалкой пятен набиралось под полторы сотни, и каждое —
    //    полупрозрачный узел поверх остальных. Браузер пересчитывает всю
    //    эту стопку на каждом кадре анимации червя, и кадры умирали.
    //
    // Холст решает оба: маска по силуэту — одна операция композиции, а вся
    // накопленная пена — один узел в дереве.
    //
    // Прозрачность НИЗКАЯ нарочно: мазки ложатся сотнями внахлёст, и та, что
    // выглядит правильной на одном, за проход собирается в сплошное белое
    // поле — червя под ним не видно вовсе.
    // Три состояния клетки, и они различаются НАЗНАЧЕНИЕМ, а не оттенком
    // одного и того же: муть от мыла — мягкая и приглушённая, пена от
    // мочалки — плотная и яркая, тремя ступенями по числу тёрок. Одна
    // яркость на все ступени означала «непонятно, засчиталось или нет».
    WASH: {
        soap:  { key: 'soapFilm', a: [0.62] },
        cloth: { key: 'foam',     a: [0.45, 0.72, 1.0] }
    },

    // Заливка одной клетки. t — доля от нужного числа проходов.
    washPaint(ctx, kind, x, y, r, t) {
        const W = this.WASH[kind === 'cloth' ? 'cloth' : 'soap'];
        const c = btPal()[W.key];
        const step = Math.max(1, Math.min(W.a.length,
            Math.ceil((t == null ? 1 : t) * W.a.length)));
        const A = W.a[step - 1];
        const g = ctx.createRadialGradient(x, y, 0, x, y, r);
        const rgba = (hex, a) => {
            const n = parseInt(hex.slice(1), 16);
            return `rgba(${(n >> 16) & 255},${(n >> 8) & 255},${n & 255},${a})`;
        };
        // Ядро плотное, край мягкий: соседние клетки сливаются, а пропущенная
        // остаётся дырой — и её видно.
        g.addColorStop(0, rgba(c.hi, A));
        g.addColorStop(0.6, rgba(c[500], A * 0.8));
        g.addColorStop(1, rgba(c[500], 0));
        return g;
    },

    // ---------- ХВОСТ ФИНАЛА ----------
    // Отдельная сущность, не привязанная к скелету (docs/plan/21-lust-bath.md,
    // раздел 2). Так не от лени: в финале червь выныривает у дальнего борта, а
    // хвост всплывает у ближнего — привязанный к телу хвост в такую раскладку
    // не встаёт, он растёт из конца туловища.
    //
    // От модели наследуется ТОЛЬКО оттенок: цвет хвоста обязан меняться
    // вместе с червём.
    //
    // ---------- ОН ГНЁТСЯ, А НЕ ПОВОРАЧИВАЕТСЯ ----------
    // Первая версия просто крутила готовую фигуру вокруг основания. На
    // экране это читалось предметом, лежащим поверх ванны и вращающимся на
    // месте: основание уезжало из воды, связи с чашей не было.
    //
    // Теперь хвост — ПРУТ. Основание всегда стоит вертикально и остаётся под
    // водой, кривизна набирается к кончику. Отсюда и форма изгиба: угол
    // растёт как t², то есть у корня прут почти прямой, а гнётся верхняя
    // треть — ровно так ведёт себя ветка, которую отгибают за макушку.
    // side: в какую сторону гнётся. −1 — влево: хвост стоит правее головы,
    // и тянуть его надо к ней.
    TAIL: { len: 200, base: 74, seg: 22, side: -1 },

    // Осевая линия при заданном изгибе. bend — на сколько радиан уведён
    // КОНЧИК от вертикали; у основания отклонение всегда ноль.
    tailSpine(bend) {
        const T = this.TAIL, n = T.seg, ds = T.len / n;
        const k = T.side || 1;
        const pts = [{ x: 0, y: 0, a: 0 }];
        let x = 0, y = 0;
        for (let i = 1; i <= n; i++) {
            const t = i / n;
            const a = bend * t * t;           // прут: кривизна набирается к концу
            x += k * Math.sin(a) * ds;
            y -= Math.cos(a) * ds;
            pts.push({ x, y, a });
        }
        return pts;
    },

    // Контур прута: осевая линия, разведённая на полутолщину по нормали.
    tailCurve(bend) {
        const T = this.TAIL, pts = this.tailSpine(bend), n = pts.length - 1;
        // Сужение с лёгкой выпуклостью в середине и ОСТРЫМ кончиком.
        // Линейное давало ровный треугольник — плавник, а не хвост; степень
        // без множителя оставляла кончик тупым, и изгиб на нём не читался.
        const half = (t) => (T.base / 2) * Math.pow(1 - t, 0.72)
                          * (1 + 0.28 * Math.sin(Math.PI * t));
        const left = [], right = [];
        for (let i = 0; i <= n; i++) {
            const p = pts[i], w = half(i / n);
            const nx = (T.side || 1) * Math.cos(p.a), ny = Math.sin(p.a);
            left.push(`${(p.x - nx * w).toFixed(1)} ${(p.y - ny * w).toFixed(1)}`);
            right.push(`${(p.x + nx * w).toFixed(1)} ${(p.y + ny * w).toFixed(1)}`);
        }
        // Низ уходит под воду, поэтому основание закрывается прямой: закруглять
        // то, чего не видно, незачем.
        const d = `M${left.join('L')}L${right.reverse().join('L')}Z`;
        const tip = pts[n];
        return { d, spine: pts, tip,
                 // Направление кончика в координатах сцены: фигура смотрит
                 // ВВЕРХ, то есть в −y.
                 dir: Math.atan2(-Math.cos(tip.a), (T.side || 1) * Math.sin(tip.a)) };
    },

    // Две линии хвоста при заданном изгибе: сам прут и блик по нему. Блик
    // идёт ПО ОСИ, а не отдельной дугой: при изгибе он обязан гнуться вместе
    // с телом, иначе съезжает с формы.
    tailD(bend) {
        const c = this.tailCurve(bend || 0);
        const shine = c.spine.filter((p, i) => i > 1 && i < c.spine.length - 3)
            .map(p => `${(p.x - (this.TAIL.side || 1) * Math.cos(p.a) * this.TAIL.base * 0.17).toFixed(1)} `
                    + `${(p.y - Math.sin(p.a) * this.TAIL.base * 0.17).toFixed(1)}`);
        return { body: c.d, shine: 'M' + shine.join('L'), curve: c };
    },

    // Разметка хвоста собирается ОДИН РАЗ, дальше меняются только атрибуты d.
    // Пересобирать её каждый кадр значит парсить строку шестьдесят раз в
    // секунду ради двух чисел — на телефоне это заметно.
    tail(model) {
        const m = (model && model.tail) || {};
        // Оттенок берётся у предхвостового сегмента тела, а не у собственного
        // хвоста модели: тот покрашен в самую тёмную ступень мяса, и хвост
        // такого размера читался тёмным клинком, а не частью червя.
        const seg = (model && model.growingSegments && model.growingSegments[0])
                 || (model && model.belly) || null;
        const fill = (seg && seg.fill) || m.fill || PALETTE.flesh[700];
        const ink = (seg && seg.stroke) || m.stroke || PALETTE.ink;
        return `
        <path id="bt-tail-body" d="" fill="${fill}" stroke="${ink}"
              stroke-width="3" stroke-linejoin="round"/>
        <path id="bt-tail-shine" d="" fill="none" stroke="${PALETTE.flesh[100]}"
              stroke-width="7" stroke-linecap="round" opacity="0.38"/>`;
    },

    // ---------- ПУЗЫРИ ПЕНЫ ----------
    // Пузырь читается пузырём по БЛИКУ, а не по кружку: без блика это пятно
    // той же пены, и лопать его незачем.
    bubble(x, y, r, seed) {
        const f = btPal().foam;
        const rng = btRng(seed);
        const ox = (rng() - 0.5) * r * 0.5, oy = -r * (0.28 + rng() * 0.14);
        return `<g class="bt-bubble" data-r="${r.toFixed(1)}"
                   data-x="${x.toFixed(1)}" data-y="${y.toFixed(1)}">
            <circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"
                    fill="${f[500]}" fill-opacity="0.52"
                    stroke="${f.rim}" stroke-width="2"/>
            <circle cx="${(x + ox).toFixed(1)}" cy="${(y + oy).toFixed(1)}"
                    r="${(r * 0.3).toFixed(1)}" fill="${f.hi}" opacity="0.85"/>
        </g>`;
    },

    // ---------- КАПЛИ И ПОТЁКИ ----------
    // Капля в полёте — густая, с вытянутым по скорости телом: по форме видно,
    // куда она летит. Потёк — то, что не попало: прилипло к поверхности и
    // ползёт вниз, оставляя хвост.
    //
    // Рисуется одной строкой на кадр: капель единицы, и держать их узлами
    // ради этого незачем.
    drops(flying, splats) {
        const w = btPal().water, out = [];
        for (const s of (splats || [])) {
            if (s.gulp) {
                // Попадание: короткая вспышка в самой корзине рта.
                const k = 1 - s.t / 0.45;
                out.push(`<circle cx="${s.x.toFixed(1)}" cy="${s.y.toFixed(1)}"
                                  r="${(s.r * (1.6 - k)).toFixed(1)}" fill="none"
                                  stroke="${w.surfHi}" stroke-width="5"
                                  opacity="${(k * 0.9).toFixed(2)}"/>`);
                continue;
            }
            const k = Math.max(0, 1 - s.t / 2.6);
            out.push(`<path d="M${(s.x - s.r).toFixed(1)} ${s.y.toFixed(1)}
                             a${s.r.toFixed(1)} ${s.r.toFixed(1)} 0 1 0 ${(s.r * 2).toFixed(1)} 0
                             l${(-s.r).toFixed(1)} ${(s.r * 2.2).toFixed(1)} Z"
                            fill="${w.surfHi}" opacity="${(k * 0.72).toFixed(2)}"/>`);
        }
        for (const d of (flying || [])) {
            const sp = Math.hypot(d.vx, d.vy) || 1;
            const ex = d.vx / sp, ey = d.vy / sp, L = d.r * 1.7;
            out.push(`<ellipse cx="${d.x.toFixed(1)}" cy="${d.y.toFixed(1)}"
                               rx="${(d.r + L).toFixed(1)}" ry="${d.r.toFixed(1)}"
                               fill="${w.surfHi}" opacity="0.95"
                               transform="rotate(${(Math.atan2(ey, ex) * 180 / Math.PI).toFixed(1)}
                                          ${d.x.toFixed(1)} ${d.y.toFixed(1)})"/>`);
        }
        return out.join('');
    },

    // ---------- ШКАЛА ФИНАЛА ----------
    // Три секции, и ни одной буквы: сколько налито — столько и горит
    // (инвариант 9). Наполняется снизу вверх, как всё, что наливают.
    gauge(x, y, sections, filled) {
        const p = btPal(), h = 34, gap = 7, w = 26;
        const out = [];
        for (let i = 0; i < sections; i++) {
            const cy = y - i * (h + gap);
            const on = i < filled;
            out.push(`<rect x="${(x - w / 2).toFixed(1)}" y="${(cy - h).toFixed(1)}"
                            width="${w}" height="${h}" rx="7"
                            fill="${on ? p.water.surfHi : p.shadow}"
                            fill-opacity="${on ? 0.95 : 0.35}"
                            stroke="${p.foam.rim}" stroke-width="2"/>`);
        }
        return out.join('');
    },

    // ---------- УКАЗАТЕЛЬ НЕПОКРЫТОГО ----------
    // Порог 92% без подсказки превращается в поиск пикселя: игрок водит и не
    // понимает, почему этап не кончается (план, §1).
    spot(x, y, r) {
        return `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${r.toFixed(1)}"
                        fill="none" stroke="${btPal().foam.hi}" stroke-width="4"
                        opacity="0.9"/>`;
    }
};
