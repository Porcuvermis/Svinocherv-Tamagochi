// ================= АППАРАТ АЛЧНОСТИ: ВИД ИГРЫ ПО УРОВНЮ =================
// Версия 1 (гаражная сборка) — первая ступень, версия 2 (литой премиум) —
// апгрейд. Каждая игра прокачивается отдельно и приносит свой вид:
// бандит — весь корпус и всё, чем играют руками (экран, рычаг, монетоприёмник,
// копилка, шкала), колесо и пачинко — свои модули в гнёздах корпуса.
// Смешанные уровни — честные: каждая игра своим видом в любом корпусе
// (docs/plan/31-greed-premium.md, раздел 0).
//
// Рисовальщики деталей спрашивают вид ТОЛЬКО здесь, а не уровень у бэкенда:
// отладка подменяет вид без покупки, а покупка не должна знать о рисунке.
const GreedSkin = {
    GAMES: ['slots', 'wheel', 'pachinko'],

    // Отладка (🐞): '1' или '2' — вид без оглядки на покупки; нет ключа —
    // по уровню игры. Уровень 0 (не куплено) — вид первой ступени: гнёзда
    // рисует корпус, а он — бандита.
    key(game) { return 'gj-skin-' + game; },
    forced(game) {
        try { const v = localStorage.getItem(this.key(game)); return v === '1' || v === '2' ? +v : 0; } catch (e) { return 0; }
    },
    of(game) {
        const f = this.forced(game);
        if (f) return f;
        const lvl = typeof Backend !== 'undefined' && Backend.greedLevel ? Backend.greedLevel(game) : 1;
        return lvl >= 2 ? 2 : 1;
    },
    // Аппарат собирается один раз, поэтому смена вида — с перезагрузкой
    // (как переключатели колеса и пачинко в 🐞).
    toggle(game) {
        try { localStorage.setItem(this.key(game), String(this.of(game) === 2 ? 1 : 2)); } catch (e) { /* нет хранилища */ }
    }
};
