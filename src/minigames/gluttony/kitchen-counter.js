            const L = G.L, R = G.R, back = G.back, front = G.front;
            const f = (v) => v.toFixed(1);
            const g = koUid('cook'), gl = koUid('cookgl');
            // Конфорка — эллипс, а не круг: панель лежит, и круг на ней виден
