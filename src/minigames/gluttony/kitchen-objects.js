// ---------- дверь холодильника ----------
// bandFn — верх фаски, topFn — верх лицевой плоскости, botFn — низ двери.
function koFridgeDoor(bandFn, topFn, botFn, cls) {
    const p = koPal().fridge, g = KITCHEN_OBJECTS.fridgeGeom;
    const L = g.L, R = g.R;
    const face = koUid('fdoor'), band = koUid('fband');
    const f = (v) => v.toFixed(1);
    return `<g class="ko ${cls}">
    <defs>
        ${koLin(face, L, 0, R, 0, koRamp(p.door,
            [0, 0.06, 0.075, 0.31, 0.35, 0.46, 0.57, 0.68, 0.79, 0.89, 1]))}
        ${koLin(band, L, 0, R, 0, [[0, p.side[3]], [0.35, p.top[1]], [1, p.faceHi]])}
    </defs>
    <!-- фаска: верхняя грань дверной плиты, она ловит свет сверху -->
    ${koPoly([L, f(bandFn(L)), R, f(bandFn(R)), R, f(topFn(R)), L, f(topFn(L))],
             `url(#${band})`)}
    <!-- лицо -->
    ${koPoly([L, f(topFn(L)), R, f(topFn(R)), R, f(botFn(R)), L, f(botFn(L))],
             `url(#${face})`)}
</g>`;
}

// ---------- мягкая тень предмета на фон ----------
// Светлая сталь на светлой плитке пропадает: у кастрюли и смесителя больше
// четверти контура не отличалось от стены за ними (карта силуэтов в
// audit-kitchen). Обводить их нельзя — в этой графике нет контуров вообще.
// Правильный ответ тот же, что в жизни: предмет отбрасывает на стену тень,
// и она отделяет силуэт, ничего не обводя.
function koHalo(shape, dx, dy, opacity, blur) {
    const g = koUid('halo');
    return `<g opacity="${opacity || 0.45}">
    <defs><filter id="${g}" x="-40%" y="-40%" width="180%" height="180%">
        <feGaussianBlur stdDeviation="${blur || 9}"/></filter></defs>
    <g filter="url(#${g})" fill="${koPal().inside.shadow}"
       transform="translate(${dx} ${dy})">${shape}</g>
</g>`;
}

