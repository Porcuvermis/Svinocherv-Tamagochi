// audit-kitchen). Обводить их нельзя — в этой графике нет контуров вообще.
// Правильный ответ тот же, что в жизни: предмет отбрасывает на стену тень,
// и она отделяет силуэт, ничего не обводя.
function koHalo(shape, dx, dy, opacity, blur) {
    const g = koUid('halo');
    return `<g opacity="${opacity || 0.45}">
    <defs><filter id="${g}" x="-40%" y="-40%" width="180%" height="180%">
        <feGaussianBlur stdDeviation="${blur || 9}"/></filter></defs>
    <g filter="url(#${g})" fill="${koPal().inside.shadow}"
       transform="translate(${dx} ${dy})">${shape}</g>
</g>`;
}

// ---------- бутыль с жидкостью ----------
// Стекло само по себе бесцветное: цвет бутыли — это цвет ТОГО, ЧТО В НЕЙ.
// Поэтому содержимое рисуется отдельным телом внутри стеклянного силуэта, а
// пустая бутыль остаётся стеклянной и сразу отличима от полной.
function koLiquidBottle(key, empty) {
    const P = koPal(), L = P[key] || P.broth, gl = P.glass;
    const gBody = koUid('lqb'), gGlass = koUid('lqg');
    // Силуэт: горлышко, ПЛЕЧИ и тулово. Плечи обязательны — без них
    // получается банка, а не бутыль, и ряд на столешнице читается консервами.
    const body = `M-6 -46 h12 v16 q0 7 5 12 q6 7 6 16 v40 q0 8 -8 8
                  h-18 q-8 0 -8 -8 v-40 q0 -9 6 -16 q5 -5 5 -12 Z`;
    return `<g class="ko ko-liquid-bottle">
    <defs>
        ${koLin(gBody, -26, 0, 26, 0,
            [[0, L.lo], [0.28, L.hi], [0.5, L[500]], [0.82, L.lo], [1, L[500]]])}
        ${koLin(gGlass, -26, 0, 26, 0,
            [[0, gl.lo], [0.3, gl.hi], [0.7, gl[500]], [1, gl.lo]])}
    </defs>
    ${koGrab(28, 52)}
    <rect x="-9" y="-54" width="18" height="12" rx="3" fill="${L.cap}"/>
    <path d="${body}" fill="url(#${empty ? gGlass : gBody})"/>
    <!-- блик по левому ребру: он и делает бутыль стеклянной -->
    <path d="M-11 -2 V32" stroke="${gl.hi}" stroke-width="4" opacity="${empty ? 0.5 : 0.6}"
          stroke-linecap="round"/>
    <path d="M12 6 V30" stroke="${L.lo}" stroke-width="3" opacity="0.4"
          stroke-linecap="round"/>
</g>`;
}

// ---------- баночка специй ----------
// Стекло с содержимым: сама банка светлая и полупрозрачная, специя внутри
// занимает нижние две трети. Без этого раздела банка читается пробкой.
function koSpiceJar(x, y, w, h) {
    const j = koPal().spice;
    const g = koUid('jar'), gg = koUid('jarg');
    return `<g class="ko ko-spice-jar">
    <defs>
        ${koLin(g, x, 0, x + w, 0, [[0, j.lo], [0.35, j.hi], [0.7, j[500]], [1, j.lo]])}
        ${koLin(gg, x, 0, x + w, 0, [[0, j.cap], [0.4, j.glass], [1, j.cap]])}
    </defs>
    <rect x="${x}" y="${y}" width="${w}" height="11" rx="2" fill="url(#${gg})"/>
    <rect x="${x}" y="${y + 10}" width="${w}" height="${h - 10}" rx="2"
          fill="url(#${g})"/>
</g>`;
}

// ---------- ручка холодильника ----------
// y0/y1 — верх и низ штанги. Штанга x 272..288: слева тёмная фаска, по
// центру белая нить блика, справа скат в тень. Три полосы — это минимум,
// на котором металл читается металлом, а не серым прямоугольником.
function koFridgeHandle(x, y0, y1) {
    const c = koPal().chrome;
    const bar = koUid('hbar');
    const w = 16, brH = 13, brW = 11;   // штанга и кронштейн
    return `<g class="ko ko-fridge-handle">
    <defs>
        ${koLin(bar, x, 0, x + w, 0, [
            [0, c[700]], [0.14, c[300]], [0.42, c[100]],
            [0.62, c[500]], [0.86, c[900]], [1, c[700]]
        ])}
    </defs>
    <!-- Кронштейны — не плоские плашки: у них своя рампа поперёк, иначе на
         блестящей штанге они читаются наклейками. -->
    <rect x="${x - brW}" y="${y0}" width="${brW + 4}" height="${brH}" rx="2"
          fill="url(#${bar})"/>
    <rect x="${x - brW}" y="${y1 - brH - 5}" width="${brW + 4}" height="${brH}" rx="2"
          fill="url(#${bar})"/>
    <!-- скос на торце штанги: сверху видно её верхнюю грань -->
    ${koPoly([x, y0 + 4, x + w, y0, x + w, y0 + 4, x, y0 + 8], c[100])}
    <rect x="${x}" y="${y0 + 4}" width="${w}" height="${y1 - y0 - 4}" fill="url(#${bar})"/>
</g>`;
}

