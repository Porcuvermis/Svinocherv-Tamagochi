//
// ---------- ПОЧЕМУ ПО ПРЕДМЕТАМ, А НЕ ОДНОЙ КАРТИНКОЙ ----------
// Кухня мини-игры (kitchen-art.js) нарисована одной простынёй. Пока картинка
// плоская и мультяшная, это терпимо. Как только у предмета появляются блик,
// фаска и отражение, простыня перестаёт правиться: чтобы подвинуть кастрюлю,
// надо найти её двадцать строк среди девятисот и не задеть соседей.
// Разобранный склад правится по одному предмету и им же проверяется.
//
// ---------- ОДНА СИСТЕМА КООРДИНАТ НА ВСЕХ ----------
// Все предметы нарисованы СРАЗУ В КООРДИНАТАХ СЦЕНЫ 720×1440 (пропорция
// референса, ровно вдвое от 360×720). Это выглядит странно — обычно предмет
// рисуют от собственного нуля, — но выбрано намеренно:
//
//   • сборка сцены превращается в склейку строк, без арифметики смещений,
//     то есть без единственного места, где предметы могут разъехаться;
//   • габарит предмета (box) известен точно и берётся как viewBox, поэтому
//     «показать предмет отдельно» — это одна строка, а не пересчёт;
//   • перенести предмет в другое место можно обёрткой translate(), и это
//     явное, видимое в коде действие, а не скрытая договорённость.
//
// Числа геометрии сняты с референса промерами по пикселям, а не на глаз:
// нарисованный «примерно там же» предмет собирается в сцену, которая
// «примерно похожа», а нужна точная.
//
// ---------- ЦВЕТ ----------
// Только PALETTE.kitchenScene (см. комментарий в palette.js о том, почему
// это отдельное семейство, а не PALETTE.kitchen). Хардкод hex запрещён.
// Длинные рампы (дверь холодильника, паркет) лежат там же массивами: цвет —
// данные, а СМЕЩЕНИЯ ступеней остаются здесь, потому что они геометрия.
//
// ---------- ЛИНИЯ ----------
// Контура-обводки здесь нет вовсе, и это отличие от остальной игры. В
// референсе форму держит перепад светлоты между гранями, а не линия. Обводка
// поверх такой заливки мгновенно превращает её в клипарт — проверено на
// первой версии холодильника.

const koPal = () => PALETTE.kitchenScene;

// Уникальные id градиентов. Один предмет может стоять в кадре дважды
// (две баночки специй), и общий id склеил бы им заливку.
let koSeq = 0;
const koUid = (name) => 'ko' + (++koSeq) + '-' + name;

// Градиент в ПОЛЬЗОВАТЕЛЬСКИХ координатах, а не в долях фигуры. Доли врут:
// у наклонной грани bounding box больше самой грани, и свет уезжает вбок.
function koLin(id, x1, y1, x2, y2, stops) {
    const s = stops.map(st =>
        `<stop offset="${st[0]}" stop-color="${st[1]}"` +
        (st[2] != null ? ` stop-opacity="${st[2]}"` : '') + `/>`).join('');
    return `<linearGradient id="${id}" gradientUnits="userSpaceOnUse"
             x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}">${s}</linearGradient>`;
}

function koRad(id, cx, cy, r, stops, extra) {
    const s = stops.map(st =>
        `<stop offset="${st[0]}" stop-color="${st[1]}"` +
        (st[2] != null ? ` stop-opacity="${st[2]}"` : '') + `/>`).join('');
    return `<radialGradient id="${id}" gradientUnits="userSpaceOnUse"
             cx="${cx}" cy="${cy}" r="${r}" ${extra || ''}>${s}</radialGradient>`;
}

// Рампа из палитры + смещения из кода → готовый список стопов.
const koRamp = (colors, offsets) => colors.map((c, i) => [offsets[i], c]);

// Невидимая зона захвата. Предмет из тонких деталей палец ловит плохо:
// прозрачная заливка (не `none` — `none` событий не ловит) делает захват
// честным по габаритам.
const koGrab = (rx, ry, cx, cy) =>
    `<ellipse cx="${cx || 0}" cy="${cy || 0}" rx="${rx}" ry="${ry}"
              fill="#000" fill-opacity="0" pointer-events="all"/>`;

// Полигон по плоскому списку чисел: koPoly([x,y, x,y, ...], fill).
const koPoly = (pts, fill, extra) =>
    `<polygon points="${pts.join(' ')}" fill="${fill}" ${extra || ''}/>`;

