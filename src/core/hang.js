// ================= СВИСАЮЩЕЕ =================
// Гибкий кусочек, закреплённый одним концом: кончик нитки, бахрома,
// ленточка, провод, хвостик. Ведёт себя как упругий стержень-консоль под
// собственным весом (балка Эйлера — Бернулли): у основания он держит своё
// направление, и чем ближе к кончику, тем сильнее его гнёт тяжесть. Сила
// изгиба растёт с длиной быстро (прогиб ~ L⁴/жёсткость), поэтому короткий
// хвостик почти стоит, гнётся только кончик, а длинный повисает целиком.
//
// Модель — цепочка звеньев с пружинами на сгибах. На сгиб i давят
//   * упругость: k · (свой угол − угол предыдущего звена), у первого —
//     угол крепления (откуда кусочек выходит);
//   * тяжесть всего, что висит дальше: вес × длина хвоста × плечо
//     (половина длины хвоста) × sin(угол между звеном и «вниз»).
// Звенья качаются с инерцией и затуханием, поэтому наклон телефона
// раскачивает кончик, а не переставляет его.
//
// Углы: 0 — прямо вниз по экрану, плюс — к правому краю. «Вниз» берётся из
// Tilt.down() — тяжесть в плоскости экрана; без датчика — просто вниз.
//
// Свойства материала (MATERIALS.<m>.hang): stiff — жёсткость на изгиб,
// weight — вес единицы длины. Числа на глаз; задача — правильное поведение:
// короче или жёстче — меньше гнётся.
const Hang = {
    // len — длина в единицах сцены, root — угол крепления (рад), mat — имя
    // материала из MATERIALS (там свойства hang), n — сколько звеньев.
    create(len, root, mat, n) {
        n = n || 8;
        const m = (typeof MATERIALS !== 'undefined' && MATERIALS[mat] && MATERIALS[mat].hang) || { stiff: 1, weight: 1 };
        const s = { len, n, seg: len / n, root, stiff: m.stiff, weight: m.weight, th: [], v: [] };
        for (let i = 0; i < n; i++) { s.th.push(root); s.v.push(0); }
        // встать в покой под отвесной тяжестью, чтобы не дёргаться на старте
        for (let k = 0; k < 400; k++) this.step(s, 0);
        return s;
    },

    // Жёсткость сгиба i. Растёт к закрепу: у узла нитка скручена, сжата и
    // держит направление, к кончику волокна расходятся, и он мягкий. Без
    // этого (ровная жёсткость, как у идеальной балки) сильнее всего гнулось
    // основание, и короткий хвостик повисал целиком.
    kAt(s, i) {
        const t = 1 - i / s.n;                       // 1 у закрепа, 0 у кончика
        return s.stiff * (0.12 + 0.88 * t * t * t);
    },

    // Один шаг (кадр). g — угол «вниз» в плоскости экрана.
    step(s, g) {
        const n = s.n, seg = s.seg;
        for (let i = 0; i < n; i++) {
            const prev = i === 0 ? s.root : s.th[i - 1];
            const tail = (n - i) * seg;                          // что висит дальше сгиба
            const k = this.kAt(s, i) / seg, k2 = i < n - 1 ? this.kAt(s, i + 1) / seg : 0;
            const grav = s.weight * tail * tail * 0.5 * Math.sin(g - s.th[i]);
            const spring = k * (prev - s.th[i]);
            // следующий сгиб тянет назад (его пружина сжата нашим поворотом)
            const back = i < n - 1 ? k2 * (s.th[i + 1] - s.th[i]) : 0;
            // «масса» с запасом на жёсткость: иначе тонкий кончик с жёсткой
            // пружиной раскачивался до бесконечности
            const inertia = s.weight * tail * tail * tail / 3 + (k + k2) * 0.04;
            s.v[i] += (grav + spring + back) / inertia * 0.02;
            s.v[i] *= 0.86;                                      // затухание: воздух и трение волокон
        }
        for (let i = 0; i < n; i++) s.th[i] += s.v[i];
    },

    // Точки цепочки от закрепа (x, y).
    points(s, x, y) {
        const pts = [[x, y]];
        for (let i = 0; i < s.n; i++) {
            x += Math.sin(s.th[i]) * s.seg; y += Math.cos(s.th[i]) * s.seg;
            pts.push([x, y]);
        }
        return pts;
    },

    // «Вниз» по датчику, в радианах.
    down() {
        const D = (typeof Tilt !== 'undefined' && Tilt.down) ? Tilt.down() : { live: false, x: 0, y: 1 };
        return D.live ? Math.atan2(D.x, Math.max(0.2, D.y)) : 0;
    }
};
