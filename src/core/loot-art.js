// ================= СУНДУК: «ВОТ ЧТО ТУТ МОЖНО ВЗЯТЬ» =================
// Один нарисованный предмет, который заменяет собой целую строку чисел.
//
// ---------- ЗАЧЕМ ----------
// Окно входа в забег показывало добычу списком: значок жетона с числом,
// значок осколка с числом, монета с числом. Три пары «картинка плюс цифра»
// подряд не читаются вовсе — это таблица без заголовков (docs/traps.md,
// п. 82). Хуже того, добыча — не то, что игрок обязан знать до входа: он
// решает «идти или нет», а подробности смотрит, если хочет.
//
// Сундук говорит «здесь добыча» сам, без подписи и без обучения: он значит
// это во всех играх, какие игрок видел. Числа прячутся внутрь и показываются
// по нажатию — кто хочет, откроет.
//
// ---------- ПОЧЕМУ НЕ ЭМОДЗИ ----------
// Системный 🧰 на айфоне — ящик с инструментами, на андроиде — портфель.
// Значок, который на половине телефонов значит не то, хуже отсутствия
// значка. Та же причина, по которой рисуются монета и жетон
// (src/core/palette.js, currencyMark).
//
// ---------- ДВА СОСТОЯНИЯ ----------
// Закрытый — на карточке, он же кнопка. Открытый — в окне, которое по
// нажатию и раскрылось: крышка откинута, изнутри бьёт свет. Открытие и есть
// ответ на нажатие, объяснять его нечем и незачем.
const LootArt = {

    BOX: 100,

    // Цвета берутся из палитры сада: там уже живут доска и железо, и заводить
    // сундуку свою древесину значило бы завести второй сорт дерева в игре
    // (docs/art-direction.md — хардкод цвета в рендерере запрещён).
    wood() { return (PALETTE.garden && PALETTE.garden.wood) || { 700: '#6f4a26', 500: '#9a6b39', 300: '#c19255' }; },
    iron() { return (PALETTE.garden && PALETTE.garden.iron) || { 700: '#5a5f63', 500: '#868d92', 300: '#b3babe' }; },
    gold() { return (PALETTE.redCarpet && PALETTE.redCarpet.gold) || { 700: '#8a6a12', 500: '#c9a227', 300: '#f0d878' }; },

    // ---------- СУНДУК ----------
    // Первый вариант читался грибом, и разбор оказался полезным: сундук
    // узнаётся НЕ по форме крышки, а по трём вещам сразу, и убери любую —
    // остаётся ящик.
    //
    //   1. ГОРИЗОНТАЛЬНЫЙ СТЫК между крышкой и корпусом. Это единственное,
    //      что говорит «оно открывается». Без него любая коробка — коробка.
    //   2. ПОЛОСЫ, ПЕРЕСЕКАЮЩИЕ СТЫК. Они идут по крышке и уходят на
    //      корпус — то есть охватывают предмет целиком. Полосы, не
    //      доходящие до стыка, читаются ножками (так и вышло с первого раза).
    //   3. НИЗКАЯ крышка. Высокий купол делает из сундука гриб или хижину:
    //      подъём крышки должен быть заметно меньше высоты корпуса.
    //
    //   open — крышка откинута назад и изнутри бьёт свет
    //   size — сторона в точках; без неё растягивается по месту
    chest(opts) {
        const o = opts || {};
        const id = 'ch' + Math.random().toString(36).slice(2, 8);
        const W = this.wood(), I = this.iron(), G = this.gold();
        const ink = PALETTE.ink;

        // Свет из верхнего левого угла — как у всего остального в игре.
        // Отдельная лампочка у каждого предмета разваливает сцену быстрее,
        // чем разный цвет (docs/art-direction.md, раздел 3).
        const defs = `
            <linearGradient id="${id}b" x1="0.1" y1="0" x2="0.9" y2="1">
                <stop offset="0" stop-color="${W[500]}"/>
                <stop offset="1" stop-color="${W[700]}"/>
            </linearGradient>
            <linearGradient id="${id}l" x1="0.15" y1="0" x2="0.85" y2="1">
                <stop offset="0" stop-color="${W[300]}"/>
                <stop offset="1" stop-color="${W[500]}"/>
            </linearGradient>
            <linearGradient id="${id}i" x1="0" y1="0" x2="0.7" y2="1">
                <stop offset="0" stop-color="${I[300]}"/>
                <stop offset="0.5" stop-color="${I[500]}"/>
                <stop offset="1" stop-color="${I[700]}"/>
            </linearGradient>
            <radialGradient id="${id}g" cx="0.5" cy="0.6" r="0.55">
                <stop offset="0" stop-color="${G[300]}" stop-opacity="1"/>
                <stop offset="0.5" stop-color="${G[500]}" stop-opacity="0.5"/>
                <stop offset="1" stop-color="${G[500]}" stop-opacity="0"/>
            </radialGradient>`;

        // Корпус — ящик с лёгким сужением кверху: ровный прямоугольник
        // выглядит коробкой из-под обуви.
        const body = `
            <path d="M17 54 L83 54 L86 87 Q86 90 83 90 L17 90 Q14 90 14 87 Z"
                  fill="url(#${id}b)" stroke="${ink}" stroke-width="${STROKE.contour}"
                  stroke-linejoin="round"/>`;

        // Крышка: низкая дуга. Подъём 16 при корпусе в 36 — вдвое меньше, и
        // силуэт остаётся сундуком, а не избушкой.
        const lidShape = 'M14 54 Q14 36 50 33 Q86 36 86 54 Z';

        // ---------- ПОЛОСЫ ----------
        // Главное в рисунке. Идут ОТ ВЕРХА КРЫШКИ ДО НИЗА КОРПУСА, пересекая
        // стык: предмет охвачен, а не составлен из двух. Рисуются под замком
        // и после корпуса, чтобы стык был виден сквозь них.
        const strap = (x, tilt) => `
            <path d="M${x} ${o.open ? 54 : 37} L${x + tilt} 90"
                  stroke="url(#${id}i)" stroke-width="8" stroke-linecap="butt"/>
            <path d="M${x} ${o.open ? 54 : 37} L${x + tilt} 90"
                  stroke="${ink}" stroke-width="${STROKE.hairline}" fill="none" opacity="0.55"/>`;

        // Стык крышки и корпуса — тёмная линия во всю ширину. У открытого его
        // нет: крышки на этом месте уже нет, и линии взяться неоткуда.
        const seam = o.open ? '' : `
            <path d="M14 54 L86 54" stroke="${ink}" stroke-width="${STROKE.structure}"/>`;

        // Замок сидит НА стыке, наполовину на крышке, наполовину на корпусе —
        // так он и держит. У открытого он уезжает вниз вместе со стыком.
        const lock = `
            <rect x="42" y="${o.open ? 56 : 47}" width="16" height="17" rx="3"
                  fill="url(#${id}i)" stroke="${ink}" stroke-width="${STROKE.structure}"/>
            <circle cx="50" cy="${o.open ? 64 : 55}" r="3" fill="${ink}" opacity="0.85"/>`;

        // Откинутая крышка: та же дуга, повёрнутая вокруг ЗАДНЕЙ КРОМКИ и
        // прижатая к ней. Первый вариант её просто отодвигал, и она висела над
        // сундуком отдельным предметом. Изнутри крышка темнее: видна другая
        // сторона доски, а не та же самая.
        const openLid = `
            <g transform="rotate(-26 16 53) translate(1 -1)">
                <path d="${lidShape}" fill="url(#${id}b)" stroke="${ink}"
                      stroke-width="${STROKE.contour}" stroke-linejoin="round"/>
                <path d="M20 50 Q50 38 80 50" stroke="${ink}" stroke-width="${STROKE.hairline}"
                      fill="none" opacity="0.45"/>
            </g>`;

        const closedLid = `
            <path d="${lidShape}" fill="url(#${id}l)" stroke="${ink}"
                  stroke-width="${STROKE.contour}" stroke-linejoin="round"/>`;

        // Свет изнутри — единственное, что говорит «там что-то есть». Только
        // у открытого: у закрытого светиться нечему.
        const shine = o.open
            ? `<ellipse cx="50" cy="52" rx="33" ry="14" fill="url(#${id}g)"/>
               <path d="M18 54 Q50 42 82 54 Q50 60 18 54 Z" fill="${G[300]}" opacity="0.6"/>`
            : '';

        return `<svg class="loot-chest${o.open ? ' open' : ''}" viewBox="0 0 ${this.BOX} ${this.BOX}"
                     ${o.size ? `width="${o.size}" height="${o.size}"` : ''}
                     aria-hidden="true" focusable="false">
            <defs>${defs}</defs>
            ${o.open ? openLid : ''}
            ${body}
            ${shine}
            ${o.open ? '' : closedLid}
            ${strap(26, -3)}
            ${strap(74, 3)}
            ${seam}
            ${lock}
        </svg>`;
    }
};

if (typeof window !== 'undefined') window.LootArt = LootArt;
