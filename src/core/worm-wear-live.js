// ================= ЧЕРВЬ: НАРЯД ЖИВЁТ ВМЕСТЕ С ТЕЛОМ =================
// Часть покадрового цикла (tick в worm-renderer.js): одежда на теле повторяет
// часть, сужается ракурсом, режется силуэтом живота, а висящее качается
// пружиной. Читает круги силуэта, которые только что разложил
// layoutWormChain (worm-chain.js), — других источников положения у неё нет.
// Как вещи собираются — worm-garment.js и worm-build.js; здесь только кадр.
function updateWornClothes(state, hullCircles, bellySeg, geomDtSec) {
    // ---------- НАРЯД ЖИВЁТ ВМЕСТЕ С ТЕЛОМ ----------
    // Сегменты ставятся одним сдвигом, БЕЗ поворота, поэтому
    // одежда на них стояла горизонтально к ЭКРАНУ, а не к телу:
    // тело изгибалось, а пиджак и бант оставались приколоченными.
    // Угол части берём из положения соседей — из тех же кругов,
    // что и силуэт, так что расходиться нечему.
    if ((state.built.wearOnBody && state.built.wearOnBody.length)
        || (state.built.wearSwings && state.built.wearSwings.length)) {
        // ---------- ТЕЛО ПОВОРАЧИВАЕТСЯ, А НЕ КРУТИТСЯ ----------
        // Первая версия поворачивала одежду по оси части — и это
        // читалось как шарик, крутящийся под фраком. Для игрока
        // червь стоит вертикально и поворачивается ЦЕЛИКОМ, как
        // очки на лице: предмет уезжает вбок и сужается, показывая
        // то один бок, то другой. Ракурс тела — тот же признак, по
        // которому доворачивается грудная клетка.
        const live = state.livePose.bodyYaw;
        const bodyK = live != null ? Math.max(-1, Math.min(1, live))
                                   : -Math.cos(state.tailAngle * Math.PI / 180);

        // ---------- ВИСЯЩЕЕ СЛУШАЕТСЯ ТЯЖЕСТИ ----------
        // Фалды, ленты и подвески висят ВНИЗ ПО ЭКРАНУ, а не по
        // своей части: один конец пришит к телу, второй свободен.
        // Угол считается пружиной с затуханием — отсюда и упругость,
        // и раскачка после остановки. Ведёт её скорость персонажа
        // по сцене и наклон телефона (если он есть).
        const dt = Math.max(0.001, Math.min(0.05, geomDtSec || 0.016));
        const vx = state.wearPrevX == null ? 0 : (state.wormX - state.wearPrevX) / dt;
        state.wearPrevX = state.wormX;
        // ---------- ЗНАК СЧИТАЕТСЯ В ОДНОМ МЕСТЕ ----------
        // Угол здесь — это «куда уехал СВОБОДНЫЙ КОНЕЦ»: плюс —
        // вправо по экрану. В этих понятиях оба источника
        // очевидны и не путаются:
        //   • завалили телефон вправо — тяжесть тянет вправо, плюс;
        //   • пошли вправо — ткань ОТСТАЁТ и уходит влево, минус.
        // В сам rotate() это уезжает со знаком минус, потому что у
        // svg ось Y вниз и положительный поворот уводит висящий
        // конец ВЛЕВО (docs/traps.md, п. 116).
        const tiltDeg = (typeof Tilt !== 'undefined' && Tilt.x) ? Tilt.x() * 16 : 0;
        const target = Math.max(-24, Math.min(24, -vx * 0.035)) + tiltDeg;

        // ---------- КТО СТОИТ ВПЕРЕДИ ВСЕХ ----------
        // Слой одежды один на всё тело: он лежит выше КАЖДОЙ
        // части, потому что обязан лежать выше колец, кишки и еды
        // в ней (они тоже общие и рисуются после частей). Пока
        // части не налезали друг на друга, порядок внутри слоя
        // значения не имел.
        //
        // Живот — единственная часть, которая меняет размер и при
        // этом нарисована ПОСЛЕ всех остальных, то есть стоит
        // впереди них. Раздувшись, он закрывает соседей телом —
        // но не их одеждой: та лежит в общем слое и оставалась
        // нашлёпкой поверх живота. Поэтому одежда всех прочих
        // частей режется его силуэтом.
        const front = bellySeg ? hullCircles[bellySeg.idx] : null;
        state.built.wearOnBody.forEach(w => {
            if (w.idx == null) return;
            const me = hullCircles[w.idx];
            if (!me) return;
            // ---------- НАДЕТОЕ ПОВТОРЯЕТ ЧАСТЬ ----------
            // Слой одежды лежит выше кожи и потому вне группы
            // части. Положение он не вычисляет, а списывает у
            // самой части: раскладок у цепочки три (прямая линия,
            // вертикаль, цепь с глубиной), и четвёртая копия
            // расчёта разошлась бы с ними в первую же правку.
            // Чтение атрибута не трогает раскладку и стоит ноль.
            //
            // ---------- ВЕЩЬ ЖИВЁТ И РАЗМЕРОМ ЧАСТИ ТОЖЕ ----------
            // Списать трансформ группы мало: часть меняет размер
            // НЕ трансформом группы, а своим эллипсом — дыхание
            // и раздутие живота переписывают rx/ry/cx/cy. Одежда
            // об этом не узнавала и оставалась прежнего размера:
            // накормленный червь вылезал из фрака голым животом.
            // Живой масштаб и смещение центра лежат в круге
            // силуэта (wk / ox / oy) — надеваем их поверх.
            const wk = me.wk || 1, ox = me.ox || 0, oy = me.oy || 0;
            {
                let t = '';
                for (let m = 0; w.mirror && m < w.mirror.length; m++) {
                    t += (w.mirror[m].getAttribute('transform') || '') + ' ';
                }
                if (wk !== 1 || ox || oy) {
                    t += `translate(${ox.toFixed(2)},${oy.toFixed(2)}) scale(${wk.toFixed(4)})`;
                }
                if (t !== w.mirrored) { w.mirrored = t; setAttr(w.hostNode, 'transform', t); }
            }
            // Полный масштаб от корня до местных координат вещи:
            // к живому размеру части добавляется то, что уже несёт
            // её группа (глубина у звеньев на полу). Нужен он
            // ровно для одного — перевести корневое расстояние
            // между частями в местные единицы.
            const sc = (me.gs || 1) * wk;

            // ---------- ВЫРЕЗ ПО СИЛУЭТУ ПЕРЕДНЕЙ ЧАСТИ ----------
            // Считается в местных координатах вещи — там же, где
            // она нарисована. Пока живот далеко, выреза нет вовсе:
            // атрибут не ставится, и стоит это ноль.
            if (w.clipPath && front && front !== me) {
                const dxF = front.x - me.x, dyF = front.y - me.y;
                const near = Math.hypot(dxF, dyF) < (front.r + (me.r || 0) * 1.25);
                if (!near) {
                    if (w.clipOn) { w.clipOn = false; w.clipWrap.removeAttribute('clip-path'); }
                } else {
                    const k = sc || 1;
                    const cxF = dxF / k, cyF = dyF / k;
                    const rxF = (front.erx || front.r) / k, ryF = (front.ery || front.r) / k;
                    // Прямоугольник во весь свет МИНУС эллипс
                    // живота: evenodd делает из двух контуров
                    // «всё, кроме». Числа округлены до десятых —
                    // иначе дыхание переписывало бы путь каждый
                    // кадр ради невидимого глазу.
                    const d = 'M -9999 -9999 H 9999 V 9999 H -9999 Z'
                        + ` M ${(cxF - rxF).toFixed(1)} ${cyF.toFixed(1)}`
                        + ` a ${rxF.toFixed(1)} ${ryF.toFixed(1)} 0 1 0 ${(rxF * 2).toFixed(1)} 0`
                        + ` a ${rxF.toFixed(1)} ${ryF.toFixed(1)} 0 1 0 ${(-rxF * 2).toFixed(1)} 0 Z`;
                    if (d !== w.clipShown) { w.clipShown = d; setAttr(w.clipPath, 'd', d); }
                    if (!w.clipOn) { w.clipOn = true; setAttr(w.clipWrap, 'clip-path', w.clipRef); }
                }
            }
            // Хвост живёт в своей группе изгиба — она его и
            // поворачивает; тело поворота не имеет вовсе.
            // ---------- РАКУРС ДВИГАЕТ ЛИЦО, А НЕ ВСЮ ВЕЩЬ ----------
            // У ткани есть узел [data-face] — то, что нарисовано
            // на груди. Сужается и съезжает он, а обшивка стоит:
            // она обнимает часть кругом и достаёт до обоих краёв
            // силуэта при любом ракурсе. Пока сужалась вся вещь,
            // она скукоживалась к центру и по бокам вылезала
            // голая кожа — «повернулся» это не читалось.
            const moved = w.faceNode || w.node;
            const half = w.faceNode ? w.faceHalf : w.halfW;
            if (w.part !== 'tail' || w.faceNode) {
                const p = WormSilhouette.wearBodyPlace(bodyK, half, !!w.faceNode);
                // Лицо половины выстраивается по оси ОПОРНОЙ
                // части вещи: сегменты не стоят на одной
                // вертикали, и манишка, отцентрованная по
                // каждому своему, шла по шву зигзагом.
                const ref = (w.faceNode && w.refIdx != null) ? hullCircles[w.refIdx] : null;
                const scRef = ref ? ((ref.gs || 1) * (ref.wk || 1)) : sc;
                let x;
                if (w.faceNode) {
                    // Ось опорной части и ракурсный сдвиг — оба в
                    // КОРНЕВЫХ единицах (раздутый живот уезжает
                    // вбок, и лицо обязано уехать с ним), поэтому
                    // в местные переводятся делением на свой
                    // масштаб. Пока деления не было, накормленный
                    // живот утаскивал манишку верхней половины, а
                    // нижняя оставалась на месте — вещь рвалась
                    // пополам и половины расходились в стороны.
                    const dx = ref ? (ref.x - me.x) : 0;
                    x = (dx + p.x * (w.faceR || 1) * scRef) / (sc || 1);
                } else {
                    // Обшивка живёт целиком в местных единицах
                    // части: её мера — РОДНОЙ радиус (br), а не
                    // живой. Живой уже учтён масштабом узла.
                    x = w.baseX + p.x * (me.br || me.r || 1);
                }
                const shown = +x.toFixed(2);
                if (w.shownX !== shown || w.shownSq !== p.squash) {
                    w.shownX = shown; w.shownSq = p.squash;
                    setAttr(moved, 'transform',
                        `translate(${shown},0) scale(${p.squash.toFixed(3)},1)`);
                }
            }
        });

        // ---------- ВИСЯЩЕЕ КАЧАЕТСЯ ВЕЗДЕ ОДИНАКОВО ----------
        // Список общий для тела и головы: качание собиралось
        // только у надетого на тело, и серьга в ухе не качалась
        // вовсе — у головы своя ветка монтажа.
        const sw = state.built.wearSwings || [];
        for (let k = 0; k < sw.length; k++) {
            const s2 = sw[k];
            // Пружина: тянет к цели, гасится, потому качается.
            // Чем дальше по подвеске, тем мягче — так цепочка из
            // нескольких звеньев изгибается, а не едет одним куском.
            const n = s2.order || 0;
            const stiff = 46 / (1 + n * 0.9), damp = 7.5 + n * 1.2;
            s2.vel = (s2.vel || 0) + ((target * s2.k - (s2.ang || 0)) * stiff
                                     - (s2.vel || 0) * damp) * dt;
            s2.ang = (s2.ang || 0) + s2.vel * dt;
            // Куда повёрнут сам носитель: висящее обязано это
            // вычесть, иначе оно висит «вниз по хвосту», а не вниз.
            // Носителей три: тело (не поворачивается вовсе), хвост
            // (его угол считает tick) и ухо (свой наклон, живой —
            // он меняется с ракурсом головы).
            const host = s2.ear ? (s2.ear.baseAngle || 0)
                       : s2.part === 'tail' ? (state.tailWearRot || 0) : 0;
            // s2.ang — куда уехал свободный конец (плюс вправо), а
            // поворот носителя вычитается, чтобы висящее держало
            // свой угол по ЭКРАНУ.
            //
            // ---------- ЗЕРКАЛО МЕНЯЕТ ЗНАК ПОВОРОТА ----------
            // Левая серьга живёт внутри scale(-1,1): там
            // положительный поворот виден на экране отрицательным.
            // Пока множителя не было, серьги на одном завале
            // телефона обе съезжались к голове, а на другом
            // расходились — вместо того чтобы обе искать низ.
            // Угол носителя НЕ зеркалится: он уже экранный.
            const want = (s2.flip || 1) * (-s2.ang - host);
            if (Math.abs(want - s2.now) < 0.2) continue;
            s2.now = want;
            setAttr(s2.el, 'transform', s2.pre + want.toFixed(1) + s2.post);
        }
    }
}
