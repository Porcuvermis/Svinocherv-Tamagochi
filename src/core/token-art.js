// ================= ЖЕТОН: КРУГЛАЯ ЭМБЛЕМА, СОБИРАЕМАЯ ПО ЧАСТЯМ =================
// Жетон — валюта четырёх грехов сразу (гнев, кухня, лень, похоть), и у всех
// четырёх он собирается одинаково: три осколка = жетон (ECONOMY.exchange).
// Поэтому рисуется он ЗДЕСЬ, в ядре, одной функцией на все грехи, а не
// четырежды по мини-играм.
//
// ---------- ЧТО БЫЛО НЕ ТАК ----------
// Жетон и осколок были эмодзи со счётчиком: «🎟 2» и «🩸 1/3». Такая пара
// говорит игроку ЧИСЛО, но не говорит ГЛАВНОГО — сколько осталось. Дробь
// «1/3» надо прочитать и додумать, а до этого ещё догадаться, что 🩸 и 🎟
// вообще связаны между собой. Связь была написана буквами в конфиге и нигде
// на экране.
//
// ---------- КАК УСТРОЕНО ТЕПЕРЬ ----------
// Жетон рисуется ВСЕГДА ЦЕЛИКОМ, независимо от того, сколько его собрано.
// Что не получено — бледный пунктирный контур, что получено — закрашено. То
// есть на экране всегда виден размер цели и расстояние до неё.
//
// Делится он дважды, и оба деления соответствуют настоящим наградам:
//
//   ТРЕТЬ  — осколок. Победа в бою даёт ровно её.
//   ДЕВЯТАЯ — треть осколка. Три поражения складываются в осколок
//             (ECONOMY.rewards.<грех>.<режим>.lose.everyN), то есть каждое
//             поражение — это одна девятая жетона.
//
// Отсюда и рисунок: кольцо из девяти клиньев, разбитое на три группы по три.
// Просвет между группами шире, чем внутри группы, — по нему видно, что
// девятки складываются в трети, а трети в жетон. Без этого получилась бы
// просто круговая диаграмма из девяти долек.
//
// ---------- ПОЧЕМУ КОЛЬЦО, А НЕ ПИРОГ ----------
// У сплошного круга, поделённого на секторы, все клинья сходятся в одну
// точку, и при малом размере (в кошельке жетон высотой 18 точек) центр
// превращается в кашу. У кольца середина пустая, и каждая долька читается
// отдельно даже в кошельке. Заодно дырка в середине — это то, чем жетон
// отличается от монеты: монета сплошная, жетон дырявый.
//
// ---------- ЦВЕТ ----------
// Цвет берётся у ГРЕХА (ECONOMY.sins.<грех>.color), а не задаётся жетону
// отдельно: цвет — это имя греха в игре без слов (инвариант 9), и жетон
// гнева обязан быть того же красного, что рамка его мини-игры и луч в
// колесе. Своей палитры у жетона нет и заводить её не надо.
const TokenArt = {

    // Сколько долек в жетоне и сколько в трети. Числа не выдуманы: они обязаны
    // совпадать с разменом в конфиге, и совпадение проверяется в parts().
    THIRDS: 3,
    PER_THIRD: 3,

    get PIECES() { return this.THIRDS * this.PER_THIRD; },

    // ---------- ГЕОМЕТРИЯ ----------
    // Холст 100×100, кольцо по центру. Числа подобраны так, чтобы жетон
    // читался и в кошельке (18 точек), и в строке награды (26), и крупно.
    BOX: 100,
    R_OUT: 44,
    R_IN: 19,
    // Просветы. Между третями он ВЧЕТВЕРО шире, чем внутри трети, и это не
    // вкусовщина: на первом рисунке они отличались втрое, и девять клиньев
    // читались просто как девять клиньев. Три по три видно только тогда,
    // когда группы разведены заметно сильнее, чем дольки внутри группы.
    GROUP_GAP: 11,    // градусов между третями
    PIECE_GAP: 3.5,   // градусов между девятками внутри трети

    // Ключ греха по ключу валюты: 'wrath_token' → 'wrath'. Жетон и осколок
    // ведут к одному и тому же греху, поэтому суффикс просто отрезается.
    sinOf(currencyKey) {
        return String(currencyKey || '').replace(/_(token|shard)$/, '');
    },

    color(currencyKey) {
        const sin = (typeof ECONOMY !== 'undefined' && ECONOMY.sins)
            ? ECONOMY.sins[this.sinOf(currencyKey)] : null;
        return (sin && sin.color) || '#d8d2c4';
    },

    // ---------- СКОЛЬКО СОБРАНО ----------
    // Переводит состояние игрока в число закрашенных девяток. Считает ЗДЕСЬ,
    // а не в мини-игре, по той же причине, по которой рисует здесь: правило
    // одно на четыре греха.
    //
    //   shards — осколков в кошельке (0…2: третий тут же складывается в жетон)
    //   toward — сколько поражений накоплено к следующему осколку (0…2)
    //
    // Возвращает 0…8. Девятка не бывает: как только набирается девятая долька,
    // размен превращает её в жетон, и скелет начинается заново.
    parts(shards, toward) {
        const per = this.PER_THIRD;
        const filled = (Math.max(0, shards || 0) % this.THIRDS) * per
                     + (Math.max(0, toward || 0) % per);
        return Math.min(this.PIECES - 1, filled);
    },

    // Готовые числа для греха, у которого жетон копится боем: осколки из
    // кошелька, поражения — из накопительного счётчика.
    progress(currencyKey, loseCounter) {
        const exch = (typeof ECONOMY !== 'undefined' && ECONOMY.exchange) || {};
        const shardKey = this.sinOf(currencyKey) + '_shard';
        const rule = exch[shardKey];
        if (!rule || typeof GameState === 'undefined') return 0;
        const shards = GameState.currency(shardKey);
        const toward = loseCounter ? (GameState.totalCounter(loseCounter) % this.PER_THIRD) : 0;
        return this.parts(shards, toward);
    },

    // ---------- ОДИН КЛИН ----------
    // Кольцевой сектор: дуга по внешнему радиусу, дуга обратно по внутреннему.
    // Углы отсчитываются от ВЕРХА и по часовой стрелке — так первая долька
    // оказывается там, где взгляд её и ищет, а заполнение идёт как у часов.
    wedge(from, to) {
        const c = this.BOX / 2;
        const pt = (deg, r) => {
            const a = (deg - 90) * Math.PI / 180;
            return [(c + r * Math.cos(a)).toFixed(2), (c + r * Math.sin(a)).toFixed(2)];
        };
        const big = (to - from) > 180 ? 1 : 0;
        const [x1, y1] = pt(from, this.R_OUT);
        const [x2, y2] = pt(to,   this.R_OUT);
        const [x3, y3] = pt(to,   this.R_IN);
        const [x4, y4] = pt(from, this.R_IN);
        return `M ${x1} ${y1} A ${this.R_OUT} ${this.R_OUT} 0 ${big} 1 ${x2} ${y2}`
             + ` L ${x3} ${y3} A ${this.R_IN} ${this.R_IN} 0 ${big} 0 ${x4} ${y4} Z`;
    },

    // Углы всех девяти долек, по порядку. Внутри трети просветы узкие, между
    // третями широкие — из этого и читается «три по три».
    slices() {
        const per = 360 / this.THIRDS;
        const meat = per - this.GROUP_GAP;                       // на дольки трети
        const piece = (meat - this.PIECE_GAP * (this.PER_THIRD - 1)) / this.PER_THIRD;
        const out = [];
        for (let t = 0; t < this.THIRDS; t++) {
            const base = t * per + this.GROUP_GAP / 2;
            for (let p = 0; p < this.PER_THIRD; p++) {
                const from = base + p * (piece + this.PIECE_GAP);
                out.push([from, from + piece]);
            }
        }
        return out;
    },

    // ---------- РАЗМЕТКА ----------
    //   key     — ключ валюты ('wrath_token'); от него берётся цвет греха
    //   filled  — сколько долек закрашено, 0…9
    //   opts.size  — сторона в точках (по умолчанию наследует размер строки)
    //   opts.whole — рисовать целым независимо от filled: так показывается
    //                ЗАРАБОТАННЫЙ жетон, тот, что уже лежит в кошельке
    svg(key, filled, opts) {
        const o = opts || {};
        const color = this.color(key);
        const n = o.whole ? this.PIECES : Math.max(0, Math.min(this.PIECES, filled || 0));
        const id = 'tok' + Math.random().toString(36).slice(2, 8);
        const c = this.BOX / 2;

        const body = this.slices().map(([from, to], i) => {
            const d = this.wedge(from, to);
            return i < n
                // Закрашенная долька: заливка греха и чернильный контур, как у
                // всего остального в игре (docs/art-direction.md).
                ? `<path d="${d}" fill="url(#${id}g)" stroke="${PALETTE.ink}"
                         stroke-width="${STROKE.detail}" stroke-linejoin="round"/>`
                // Недостающая: только пунктир, и бледный. Он обязан быть
                // ВИДЕН (иначе не понять, сколько осталось), но не спорить с
                // закрашенным — отсюда и прозрачность, и тонкая линия.
                // Недостающая: только пунктир, и бледный. Он обязан быть
                // ВИДЕН (иначе не понять, сколько осталось), но не спорить с
                // закрашенным. Толщина взята НЕ hairline: жетон в кошельке
                // высотой 18 точек, а холст у него 100 — то есть всё, что
                // здесь тоньше полутора единиц, на телефоне исчезает вовсе.
                : `<path d="${d}" fill="${color}" fill-opacity="0.07" stroke="${color}"
                         stroke-opacity="0.45" stroke-width="1.8" stroke-dasharray="5 3.5"
                         stroke-linejoin="round"/>`;
        }).join('');

        // ---------- ПЕРЕМЫЧКИ ПО ГРАНИЦАМ ТРЕТЕЙ ----------
        // Одних просветов не хватило. На первых двух рисунках девять клиньев
        // читались просто как девять клиньев: глаз не собирает их в группы,
        // сколько ни расширяй промежутки. Поэтому границы третей проведены
        // ЛИНИЕЙ — чернильной и толстой, наравне с ободком.
        //
        // Теперь иерархия видна сразу: жетон разламывается на три крупных
        // куска (осколки), каждый — ещё на три (то, что падает за поражение).
        // И это ровно та иерархия, что записана в конфиге награды.
        // Цветом греха, а не чернилами: фон игры тёмный, и чернильная линия на
        // нём пропадает — на пробном рисунке перемычек не было видно вовсе.
        // Линия ПЕРЕСЕКАЕТ ободок и уходит чуть наружу: так она читается как
        // разлом жетона, а не как спица внутри кольца.
        const spokes = Array.from({ length: this.THIRDS }, (_, t) => {
            const a = (t * 360 / this.THIRDS - 90) * Math.PI / 180;
            const at = (r) => [(c + r * Math.cos(a)).toFixed(2), (c + r * Math.sin(a)).toFixed(2)];
            const [x1, y1] = at(this.R_IN - 1);
            const [x2, y2] = at(this.R_OUT + 7);
            return `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"
                          stroke="${PALETTE.ink}" stroke-width="4.2" stroke-linecap="round"/>
                    <line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"
                          stroke="${color}" stroke-width="2" stroke-linecap="round"
                          stroke-opacity="0.95"/>`;
        }).join('');

        // Ободок и дырка рисуются ВСЕГДА и сплошными: это тот самый «скелет»,
        // по которому видно размер цели. Если бы ободок тоже собирался по
        // частям, пустой жетон превратился бы в пустоту.
        return `<svg class="token-art${o.whole ? ' whole' : ''}" viewBox="0 0 ${this.BOX} ${this.BOX}"
                     ${o.size ? `width="${o.size}" height="${o.size}"` : ''}
                     aria-hidden="true" focusable="false">
            <defs>
                <linearGradient id="${id}g" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="0" stop-color="${color}" stop-opacity="1"/>
                    <stop offset="1" stop-color="${color}" stop-opacity="0.62"/>
                </linearGradient>
            </defs>
            <circle cx="${c}" cy="${c}" r="${this.R_OUT + 3}" fill="none"
                    stroke="${PALETTE.ink}" stroke-width="${STROKE.structure}"/>
            <circle cx="${c}" cy="${c}" r="${this.R_OUT + 3}" fill="none"
                    stroke="${color}" stroke-opacity="${n ? 0.9 : 0.5}" stroke-width="1.4"/>
            ${body}
            ${spokes}
            <circle cx="${c}" cy="${c}" r="${this.R_IN - 3}" fill="none"
                    stroke="${PALETTE.ink}" stroke-width="${STROKE.structure}"/>
        </svg>`;
    }
};

if (typeof window !== 'undefined') window.TokenArt = TokenArt;
