// ================= ВЫКРОЙКА: КАК ОДЕЖДА САДИТСЯ НА ТЕЛО =================
// Движок кроя. Здесь нет ни одного предмета — только правила, по которым
// любой предмет ложится на часть тела. Сами предметы (цвет, вырез, линии)
// живут в src/core/worm-cosmetics.js и после этого файла состоят из одной
// художественной работы.
//
// ---------- ЗАЧЕМ ЭТО ПОЯВИЛОСЬ ----------
// Одежду описывали теми же понятиями, что шрам: «точка на части плюс своя
// картинка в долях радиуса». Шраму этого хватает — он отметина НА коже.
// Одежде не хватает ничего: у неё есть ОХВАТ (докуда по телу), КРОМКА
// (лежащая на силуэте), и ПОДОЛ (свисающий вниз). Их в каркасе не было, и
// каждая из восьми вещей заново изобретала свои края — тремя разными
// самодельными способами, каждый по-своему промахиваясь.
//
// Чем это кончилось, видно на фраке: два узких клина у краёв живота,
// сходящихся к золотой бусине, и пара клиньев ниже. Геометрически это
// буква «X» с бусиной посередине — то есть ровно галстук-бабочка, только
// вдвое больше. Между клиньями и верхом сегмента оставалась голая кожа,
// поэтому ткань читалась не надетой, а приклеенной.
//
// ---------- СИСТЕМА КООРДИНАТ ВЫКРОЙКИ ----------
// Художник больше не пишет `rx * 0.46`. Он пишет (u, v):
//
//     u — ПОПЕРЁК тела: 0 — середина, ±1 — РОВНО край части на этой высоте;
//     v — ВДОЛЬ охвата: 0 — верхняя кромка вещи, 1 — нижняя.
//
// Полуширина части считается по её эллипсу, поэтому u = 1 попадает на
// силуэт и на узком месте, и на широком. Отсюда бесплатно берётся всё, за
// чем раньше гонялись руками:
//
//   * вещь всегда доходит до краёв тела — «приклеенной» она быть не может;
//   * плечи сами получаются у́же подола, если охват начат выше середины
//     части: это не подобранная трапеция, это форма самого сегмента;
//   * ничто не вылезает за силуэт — u и v зажаты, выйти наружу нечем;
//   * кромка между двумя точками НА краю идёт дугой по телу, а не хордой.
//
// ---------- ЧТО ДЕЛАЕТ ДВИЖОК САМ ----------
//   1. строит выкройку (замкнутый путь) по охвату и списку точек;
//   2. кладёт непрозрачную основу — тело под тканью не просвечивает;
//   3. обводит выкройку ОДНОЙ линией чернил: у одежды есть край;
//   4. вешает свисающее в <g data-swing> — его качает рендерер;
//   5. отдаёт полуширину вещи (у одежды она равна единице по построению),
//      по ней рендерер прижимает надетое к телу при повороте.
//
// Художнику остаётся: охват, форма выреза, цвета и две-три линии внутри.
//
// ---------- ДВА РОДА ВЕЩЕЙ ----------
//   cloth — ткань, скроенная по телу (фрак, лента, воротник, гетра);
//   rigid — твёрдый предмет, который НЕ кроится, а надевается: очки садятся
//           на глаза, цилиндр на макушку, бант на хвост. У них своя опора,
//           и выкройка им только мешала бы.
const WormGarment = {

    // ---------- КРОМКА ДОХОДИТ РОВНО ДО КРАЯ ----------
    // Здесь стояло 0.96 — ткань нарочно не доходила до силуэта. Между её
    // краем и чёрным контуром тела оставалась полоска голой кожи, и вещь
    // выглядела так, будто у неё пропал край: у персонажа контур есть, а у
    // одежды на том же месте нет.
    //
    // Единица ставит край ткани РОВНО на контур. Собственной линии там не
    // рисуется и не надо: контур тела и есть край одежды — той же толщины и
    // того же цвета, то есть ровно в стиле персонажа. Он рисуется ПОД телом
    // (createHullLayers), поэтому кольцо остаётся видно целиком.
    HUG: 1,

    // Сколько точек на дугу по краю тела. Меньше — кромка идёт гранями.
    EDGE_STEPS: 10,

    // ---------- ПОЧЕМУ КРОМКИ ПРОГНУТЫ ----------
    // Прямая кромка поперёк круглого тела читается скотчем: ткань выглядит
    // наклеенной на шар, а не надетой. Камера в игре стоит чуть ВЫШЕ червя,
    // и любая опоясывающая линия на его теле — от верха фрака до полоски на
    // гетре — видна прогнутой книзу. Одна эта дуга и превращает нашлёпку в
    // одежду, поэтому её ставит движок, а не художник: забыть нельзя.
    // Доля ry на всю ширину тела.
    BOW: 0.17,
    // Короткие перемычки не гнутся: прогиб на вырезе манишки её бы скруглил
    // и съел клин.
    BOW_MIN_SPAN: 0.4,

    // ---------- КОНТЕКСТ ВЫКРОЙКИ ----------
    // Всё, чем пользуется художник. Больше ему ничего не дают — и не надо:
    // любая другая арифметика по радиусу и есть та самая ручная подгонка,
    // ради отмены которой этот файл написан.
    ctx(pattern, fit, skin, ref) {
        // ---------- ВДОЛЬ ДЛИННОЙ ЧАСТИ ----------
        // Хвост лежит поперёк экрана и длиннее себя же в толщину. Вещь,
        // скроенная по его поперечному радиусу, выходила колечком. `along`
        // говорит: кроить по длине, а не по толщине; середину куска и его
        // половину даёт сама часть (см. wearFitByPart.tail).
        const along = !!(pattern.along && fit && fit.long);
        const rx = along ? fit.long : ((fit && fit.rx) || 15);
        // Толщина в середине одеваемого куска: у капли она меньше, чем у
        // основания, и по основанию ткань вылезала за силуэт.
        const ry = (along && fit.longRy) || (fit && fit.ry) || 15;
        const hug = pattern.hug == null ? this.HUG : pattern.hug;
        const cover = pattern.cover || [-0.9, 0.9];
        const vTop = cover[0], vBot = cover[1];
        const self = this;

        // Высота в единицах части по доле охвата.
        const yAt = (v) => ry * (vTop + (vBot - vTop) * Math.max(0, Math.min(1, v)));
        // Полуширина ТЕЛА на этой высоте. Часть — эллипс (так её и рисует
        // рендерер), поэтому формула тут точная, а не приближение.
        const hwAt = (v) => {
            const t = Math.min(1, Math.abs(yAt(v)) / ry);
            return rx * Math.sqrt(Math.max(0, 1 - t * t)) * hug;
        };

        // ---------- ОДНА ЕДИНИЦА НА ВСЕ ЧАСТИ ВЕЩИ ----------
        // Верхняя одежда живёт на ДВУХ сегментах разной толщины. Если каждая
        // половина мерит ширину своим rx, они не сходятся по шву: манишка
        // сверху шире, чем снизу, и вещь разваливается ровно посередине.
        // `unit` — общая мера для всех частей вещи (радиус опорной части), а
        // `uOf` переводит её в местное u.
        const unit = ref || rx;

        const g = {
            rx, ry, skin, unit,

            // u, при котором точка стоит в `k` общих единиц от середины.
            // Половины вещи сходятся по шву по построению, а не подбором.
            uOf(v, k) {
                const h = hwAt(v);
                return h > 0.001 ? Math.max(-1, Math.min(1, k * unit / h)) : 0;
            },
            // Опорные точки лица — для твёрдых вещей, которые садятся не на
            // тело, а на черту: очки на глаза, цилиндр над бровью.
            eye: { y: (fit && fit.eyeY) || -ry * 0.35,
                   x: (fit && fit.eyeX) || rx * 0.55,
                   r: (fit && fit.eyeR) || rx * 0.2 },
            C: PALETTE.redCarpet,
            ink: PALETTE.ink,

            y: yAt,
            hw: hwAt,

            // Точка выкройки. u и v зажаты: наружу выйти нечем.
            at(u, v) {
                const uu = Math.max(-1, Math.min(1, u));
                const vv = Math.max(0, Math.min(1, v));
                return { x: hwAt(vv) * uu, y: yAt(vv) };
            },
            p(u, v) {
                const q = g.at(u, v);
                return q.x.toFixed(2) + ',' + q.y.toFixed(2);
            },

            // Замкнутый путь по списку [u, v]. Там, где два соседних узла
            // стоят на ОДНОМ краю тела, движок идёт дугой по силуэту: иначе
            // кромка срезает бок хордой и между тканью и телом открывается
            // серп голой кожи.
            d(points) { return self.pathOf(points, g); },

            // Полоса во всю ширину тела между двумя долями охвата.
            band(v0, v1) { return g.d([[-1, v0], [1, v0], [1, v1], [-1, v1]]); },

            // Точка НИЖЕ выкройки — для подола. Единственное место, где
            // разрешено выйти за тело: подол на то и подол.
            out(u, v, dy) {
                const base = g.at(u, v);
                return { x: base.x, y: base.y + ry * dy };
            },
            po(u, v, dy) {
                const q = g.out(u, v, dy);
                return q.x.toFixed(2) + ',' + q.y.toFixed(2);
            },

            // Качающееся. Число — податливость: 1 — обычная ткань, больше —
            // легче и размашистее.
            swing(k, inner) {
                return '<g data-swing="' + k + '">' + inner + '</g>';
            }
        };
        return g;
    },

    // Путь по списку [u, v] с дугами вдоль края тела.
    // Путь по списку [u, v]. Возвращает и заливку, и ОБВОДКУ — они разные,
    // и в этом всё дело (см. «кромка обводится не везде» ниже).
    pathOf(points, g) { return this.trace(points, g).fill; },

    // ---------- КРОМКА ОБВОДИТСЯ НЕ ВЕЗДЕ ----------
    // Ткань кончается двумя разными способами, и рисовать их одинаково
    // нельзя. Там, где она кончается НА теле (вырез, подол, край ленты), у
    // неё есть свой край — его надо обвести. А там, где она уходит ЗА
    // СИЛУЭТ, края у неё нет вовсе: видно ровно столько, сколько видно тела,
    // и границей служит контур тела, уже обведённый.
    //
    // Вторая линия поверх контура превращает вещь в КОРОБКУ: воротник на шее
    // выглядел картонным хомутом именно поэтому — у него по бокам шла
    // чернильная рамка там, где должен был быть край шеи.
    //
    // Отличать одно от другого движок умеет сам: участок, который идёт по
    // краю части (оба конца на u = ±1 с одной стороны), — это уход за силуэт.
    // Художнику решать нечего, и забыть нечего.
    // seam — какой кромкой половина стыкуется с соседней ('top' / 'bottom').
    // Такую кромку не обводят: это не край вещи, а середина. Пока обводили,
    // поперёк фрака шла чернильная линия, и он читался двумя надетыми друг
    // на друга кусками, а не одним пиджаком.
    trace(points, g, seam) {
        const pts = points.filter(p => p);
        if (!pts.length) return { fill: '', edges: [] };
        const onEdge = (p) => Math.abs(Math.abs(p[0]) - 1) < 0.001;
        let fill = 'M ' + g.p(pts[0][0], pts[0][1]);
        const edges = [];         // куски кромки, которые надо обвести
        let run = null;           // накопитель подряд идущих таких кусков

        for (let i = 1; i <= pts.length; i++) {
            const a = pts[i - 1], b = pts[i % pts.length];
            const alongEdge = onEdge(a) && onEdge(b) && a[0] * b[0] > 0
                              && Math.abs(b[1] - a[1]) > 0.001;
            let piece = '';
            if (alongEdge) {
                for (let s = 1; s <= this.EDGE_STEPS; s++) {
                    const v = a[1] + (b[1] - a[1]) * s / this.EDGE_STEPS;
                    piece += ' L ' + g.p(a[0], v);
                }
            } else {
                const span = Math.abs(b[0] - a[0]);
                if (span >= this.BOW_MIN_SPAN) {
                    // Квадратичная: чтобы кривая просела на s, опорная точка
                    // отводится на 2s.
                    const sag = g.ry * this.BOW * span / 2;
                    const m = g.at((a[0] + b[0]) / 2, (a[1] + b[1]) / 2);
                    piece = ' Q ' + m.x.toFixed(2) + ',' + (m.y + sag * 2).toFixed(2)
                          + ' ' + g.p(b[0], b[1]);
                } else {
                    piece = ' L ' + g.p(b[0], b[1]);
                }
            }
            fill += piece;
            // Стык половин — не край вещи, а её середина.
            const atSeam = seam && ((seam === 'top' && a[1] < 0.001 && b[1] < 0.001)
                                 || (seam === 'bottom' && a[1] > 0.999 && b[1] > 0.999));
            // Уход за силуэт не обводим, остальное копим в связный кусок.
            if (alongEdge || atSeam || (onEdge(a) && onEdge(b) && a[0] === b[0])) {
                if (run) { edges.push(run); run = null; }
            } else {
                if (!run) run = 'M ' + g.p(a[0], a[1]);
                run += piece;
            }
        }
        if (run) edges.push(run);
        return { fill: fill + ' Z', edges };
    },

    // ---------- СБОРКА ----------
    // sub — какая ЧАСТЬ многочастной вещи строится ('upper' / 'lower').
    // ref — общая мера для всех её частей (радиус опорной части).
    build(pattern, fit, skin, sub, ref) {
        if (!pattern) return null;
        if (sub) {
            const half = pattern.parts && pattern.parts[sub];
            if (!half) return null;
            // Половина наследует всё общее у вещи и добавляет своё.
            pattern = Object.assign({}, pattern, half, { parts: null });
        } else if (pattern.parts) {
            return null;   // многочастную вещь целиком не строят
        }
        const g = this.ctx(pattern, fit, skin, ref);
        if (pattern.kind === 'rigid') {
            const hang = pattern.hang ? g.swing(pattern.swing || 1, pattern.hang(g)) : '';
            return '<g class="worm-cos">' + (pattern.draw ? pattern.draw(g) : '') + hang + '</g>';
        }
        const cut = pattern.cut ? pattern.cut(g) : [[-1, 0], [1, 0], [1, 1], [-1, 1]];
        const path = this.trace(cut, g, pattern.seam);
        const base = pattern.base ? pattern.base(g) : g.C.cloth[500];
        // ---------- У ОДЕЖДЫ ВСЕГДА ЕСТЬ КРАЙ ----------
        // Здесь обводились только те куски кромки, что кончаются на теле, а
        // уход за силуэт оставался голым. Смысл был верный (не класть вторую
        // линию поверх контура), результат — нет: вещь выглядела квадратом,
        // нарисованным двумя сторонами из четырёх. У персонажа контур есть
        // всегда, в любом ракурсе, — и у одежды должен быть всегда.
        //
        // Линия та же, что у самой фигуры: STROKE.contour, чернила. Там, где
        // кромка идёт по силуэту, она ЛОЖИТСЯ НА контур тела — той же
        // толщины и того же цвета, поэтому шва не видно. Там, где ткань
        // кончается на теле, это её собственный край.
        const ink = '<path d="' + path.fill + '" fill="none" stroke="' + PALETTE.ink
            + '" stroke-width="' + STROKE.contour
            + '" stroke-linejoin="round" stroke-linecap="round"/>';
        // ---------- ОБШИВКА И ЛИЦО: ДВА РАЗНЫХ СЛОЯ ----------
        // Вещь на развороте просто ужималась к центру — и читалась не
        // повёрнутой, а скукоженной: по бокам вылезала голая кожа там, где
        // ткань обязана быть.
        //
        // Потому что сужать надо не всю вещь. ОБШИВКА обнимает часть кругом и
        // при любом ракурсе достаёт до обоих краёв силуэта — как рукав на
        // руке. Сужается и съезжает вбок только ЛИЦО: то, что нарисовано на
        // груди — манишка, лацканы, пуговица, бант.
        //
        //   base + cut + кромка  → обшивка, ракурсу не подчиняется
        //   paint                → рисунок НА ткани, едет с обшивкой
        //   face + over          → лицевая сторона, сужается и съезжает
        //
        // Подол идёт ПЕРВЫМ: он выходит из-под ткани, а не лежит на ней.
        const face = (pattern.face ? pattern.face(g) : '')
                   + (pattern.over ? pattern.over(g) : '');
        return '<g class="worm-cos">'
             + (pattern.hang ? g.swing(pattern.swing || 1, pattern.hang(g)) : '')
             + '<path d="' + path.fill + '" fill="' + base + '"/>'
             + (pattern.paint ? pattern.paint(g) : '')
             + ink
             + (face ? '<g data-face="' + (pattern.faceHalf || 0.62) + '">' + face + '</g>' : '')
             + '</g>';
    },

    // ---------- ПОЛУШИРИНА ----------
    // У ткани она равна единице ПО ПОСТРОЕНИЮ: выкройка доходит до краёв
    // части. Раньше это число стояло отдельной таблицей и жило своей жизнью
    // — восемь значений, подобранных на глаз под восемь картинок, ни одно из
    // которых нельзя было проверить.
    halfWidth(pattern) {
        if (!pattern) return 0;
        if (pattern.kind === 'rigid') return pattern.halfW || 0;
        return pattern.hug == null ? this.HUG : pattern.hug;
    }
};

if (typeof window !== 'undefined') window.WormGarment = WormGarment;
