// ================= ПАЛИТРА ПРОЕКТА (единый источник цвета) =================
// До этого файла цвет жил 26 захардкоженными hex-константами, разбросанными
// по worm-renderer.js, плюс отдельным набором в worm-model.js. Управлять
// стилем так невозможно: чтобы поменять настроение персонажа, надо было найти
// и согласовать между собой два с половиной десятка мест.
//
// Теперь цвет — ДАННЫЕ. Любой эксперимент со стилем = правка этого файла.
//
// ---------- ПРИНЦИП: "ДЖЕНТЛЬМЕН С СИРЕНЕВЫМ ИРОКЕЗОМ" ----------
// Полный свод правил — docs/art-direction.md. Здесь только то, что цвет
// обязан обеспечивать:
//
//   • БАЗА (смокинг) — приглушённая, органическая, мясная. Низкая насыщенность
//     (28-40%). Она занимает ~90% площади и НЕ должна привлекать внимание.
//   • АКЦЕНТ (ирокез) — ядовитый синтетический сиреневый. Занимает НЕ БОЛЕЕ
//     8-10% площади. Проверено экспериментально: сиреневый на всём пятаке
//     (~10%) уже кричит и тянет одеяло на себя. Значит акцент — только
//     точечно: слизь, дёсны, ноздри изнутри, больные сосуды.
//   • ГРЯЗЬ (bile) — жёлчно-охристая линия. Это "изнанка": налёт, зубы,
//     засохшие потёки. Не акцент, а фактура.
//
// ---------- ПРИНЦИП: СДВИГ ТОНА (hue shift) ----------
// Главное отличие профессиональной раскраски от любительской: тень — это НЕ
// тот же цвет, прикрученный к чёрному. Тени уходят в холод, света — в тепло.
// Рампа мяса построена именно так, тон едет по кругу:
//     тень 316° → 338° → база 352° → 8° → свет 26°
// Поэтому мешать цвета к '#000000'/'#ffffff' в рендерере ЗАПРЕЩЕНО —
// вместо этого берётся соседняя ступень рампы (см. PALETTE.flesh).
//
// ---------- ПРИНЦИП: КОНТУР НЕ ЧЁРНЫЙ ----------
// Чистый чёрный контур мгновенно читается как клипарт. INK — очень тёмный
// холодный сливовый, он родственник рампы мяса и потому "сидит" на теле.

const PALETTE = {
    // ---------- КОНТУР И ЧЕРНОТА ----------
    // Единственная легальная замена чёрному. Всё, что раньше было #000000,
    // #0e0405, #2a0d14 и т.п., должно приходить сюда.
    ink: '#23101d',

    // ---------- МЯСО: основная рампа тела (тёмное → светлое) ----------
    // Индексы намеренно как в дизайн-системах (900 = самое тёмное), чтобы
    // "на ступень темнее" читалось однозначно и не требовало арифметики.
    flesh: {
        900: '#3d1f35', // глубокая тень, холодная сливовая
        700: '#603444', // тень
        500: '#a75863', // БАЗА тела — то, чем залит сегмент
        300: '#cb8f86', // подсвеченная сторона
        100: '#ebd1bc'  // тёплый свет, почти кремовый
    },

    // ---------- СИРЕНЕВЫЙ: акцент-"ирокез" ----------
    // Семантика жёсткая: сиреневый = всё ВНУТРЕННЕЕ и всё НЕПРАВИЛЬНОЕ.
    // Дёсны, язык, ноздри изнутри, больные сосуды, блик слизи. Снаружи на
    // здоровой коже сиреневого быть не должно — иначе он перестанет работать
    // как нарушение и станет просто вторым цветом тела.
    violet: {
        600: '#64277c', // глубокий, для теней внутри пасти
        400: '#b649e9', // АКЦЕНТ. Использовать скупо
        200: '#d694f9'  // свечение/блик на акценте
    },

    // ---------- ЖЁЛЧЬ: грязь, налёт, зубы, засохшее ----------
    bile: {
        600: '#55582d',
        400: '#aeae5b',
        200: '#ded6a6'
    },

    // ---------- СРЕДА ----------
    // Холодный зеленовато-серый фон: он дополнителен к тёплому мясу, поэтому
    // персонаж отделяется от фона сам, без обводки и свечения.
    void: {
        900: '#171c1a', // дальний фон
        700: '#252d2a'  // пол / ближний план
    },

    // ---------- ПОДКОЖНОЕ: органы, видимые СКВОЗЬ кожу ----------
    // Отдельное семейство, а не прямое использование violet/bile. Причина:
    // всё, что видно сквозь кожу, обязано терять насыщенность — иначе
    // читается как рисунок ПОВЕРХ тела, а не как нутро под ним. Проверено:
    // кишка чистым violet[600] превращается в фиолетовую полосу, наклеенную
    // на бок. Это те же цвета, приглушённые слоем кожи.
    // Насыщенный сиреневый остаётся привилегией ОБНАЖЁННОГО внутреннего —
    // пасть, дёсны, ноздри изнутри, слизь (docs/art-direction.md §2.1).
    subskin: {
        gut: '#622e5d',
        sac: '#5b4639',
        node: '#836b4e',
        vessel: '#52235c'
    },

    // ---------- БЕЛОК ГЛАЗА ----------
    // Не чистый белый: чистый белый в глазу — второй по силе признак клипарта
    // после чёрного контура. Тёплый грязноватый костяной.
    sclera: '#e4d5c4'
};

// ---------- ЕДИНЫЙ ИСТОЧНИК СВЕТА ----------
// Раньше каждый эллипс получал собственный радиальный градиент с одинаковыми
// cx/cy — то есть каждый кусок тела был освещён СВОЕЙ лампочкой и выглядел
// самостоятельным глянцевым шариком. Отсюда эффект "гирлянда бус из пластика".
//
// Свет в проекте один: сверху-слева-спереди. Части тела не должны светиться
// одинаково — то, что дальше от источника, должно быть в целом темнее.
// LIGHT.dirX/dirY задают смещение блика, а attenuate() отдаёт множитель
// яркости по вертикальному положению части в фигуре.
const LIGHT = {
    // Смещение центра блика в долях радиуса части (не в процентах градиента) —
    // одинаковое для ВСЕХ частей, поэтому блики выстраиваются в одну линию.
    dirX: -0.34,
    dirY: -0.38,
    // Насколько сильно нижние части фигуры притемняются относительно верхних.
    // 0 = плоско (как было), 1 = очень контрастно.
    verticalFalloff: 0.55,
    // Базовая сила блика и тени в градиенте части.
    highlight: 0.26,
    shadow: 0.34
};

// Множитель яркости для части, находящейся на относительной высоте t
// (0 = верх фигуры, 1 = низ). Возвращает 1.0 наверху и заметно меньше внизу.
function lightAttenuation(t) {
    const clamped = Math.max(0, Math.min(1, t));
    return 1 - LIGHT.verticalFalloff * clamped;
}

if (typeof window !== 'undefined') {
    window.PALETTE = PALETTE;
    window.LIGHT = LIGHT;
    window.lightAttenuation = lightAttenuation;
}
