    structure: 1.7, // границы крупных частей ВНУТРИ силуэта: пятак, губа, ухо изнутри
    detail: 1.0,    // складки, борозды, сосуды, шрамы
    hairline: 0.6   // микродетали: щетина, поры, насечки
