// Локация, в которой живёт червь: горизонт, доски пола, стены, плинтус.
// Второй файл стопки рендерера (карта — в worm-basis.js).
//
// Комната описана ДАННЫМИ (ROOM + src/core/rooms.js), а не кодом: новая
// локация — запись в таблице. Перспектива у неё одна на всю игру, и считают
// её roomScaleAt/roomYAt/roomDepthAt — кто рисует на полу, спрашивает их, а
// не подбирает свои числа (docs/stage-and-room.md).

// ============================================================================
//                       КОМНАТА: ПОЛ В ПЕРСПЕКТИВЕ (2.5D)
// ============================================================================
// Главный экран был плоским: персонаж ползал по однородному тёмному фону, и
// его размер не менялся, куда бы он ни шёл. Комната даёт сцене третье
// измерение, не превращая проект в 3D.
//
// Вся геометрия выводится из ЧЕТЫРЁХ чисел, и это не случайность: пол,
// границы блуждания и масштаб персонажа обязаны считаться из одного
// источника, иначе персонаж рано или поздно окажется по колено в полу или
// вырастет не в том месте.
//
// Модель — честное перспективное деление, а не линейная интерполяция:
//   scale(d) = 1 / (1 + d*k),  где k подобрано так, что scale(1) = minScale.
// Отсюда сразу всё остальное: экранная высота точки пола, ширина пола на
// этой глубине и размер персонажа — это одно и то же число scale(d).
// Линейная интерполяция дала бы «складной» пол: у камеры шаг вглубь съедал
// бы столько же пикселей, сколько у дальней стены, и глубина бы не читалась.
const ROOM = {
    // ---------- КОМНАТА — КОРОБКА ВНУТРИ КАДРА ----------
    // Раньше пол уходил за нижнюю кромку экрана и за боковые края: комната
    // была не помещением, а «полом до горизонта». Персонаж от этого регулярно
    // оказывался наполовину за экраном.
    //
    // Теперь у комнаты видны все четыре края: передний край пола, две боковые
    // стены и задняя. Червю физически некуда выйти из кадра — он ходит по
    // ограниченному полу, и границы выгула считаются из той же геометрии, что
    // и сам пол.
    // ---------- ВЗГЛЯД СВЕРХУ, А НЕ В УПОР ----------
    // Раньше камера смотрела почти горизонтально: пол занимал по вертикали
    // 355 единиц, стены — 269, и комната читалась колодцем. Экран при этом
    // не заполнялся: сверху и снизу оставались широкие пустые поля, а сама
    // коробка не доставала до боковых краёв.
    //
    // Теперь камера поднята и наклонена вниз. Пол занимает по вертикали 506
    // единиц против 158 у задней стены — то есть видно в основном ПОЛ, как и
    // должно быть при взгляде сверху. Точка схода при таких числах уезжает
    // выше экрана, и это признак того, что наклон реальный, а не
    // нарисованный.
    //
    // Сверху остаётся полоса пустоты, и убрать её нельзя: чтобы стены дотянули
    // до верхней кромки, они должны стать вдвое выше пола, а это уже не
    // комната, а колодец. Полоса не мешает — под ней стоит HUD.
    // Пол доходит до самого низа кадра. Передний край при этом совпадает с
    // кромкой экрана и перестаёт быть видимой линией — раньше он был четвёртой
    // видимой гранью коробки, но оставлял под собой полосу пустоты. Выгул
    // червя считается из той же геометрии, поэтому уйти за кадр он всё равно
    // не может: граница есть, просто она не нарисована.
    floorFrontRatio: 1.0,
    // Глубина пола выбрана не «побольше», а по ФОРМЕ ПЯТНА пола на экране.
    // При 0.27 пол выходил 390×574 — вытянутый прямоугольник, и комната
    // читалась коридором, ровно как предупреждает абзац выше. Ширина упёрта
    // в экран и расти не может, значит ограничивать надо глубину: 390×506
    // (примерно 1:1.3) уже помещение, а не проход. Недостающий верх добирают
    // стены — их высота дешевле, она не превращает комнату в тоннель.
    floorBackRatio: 0.40,   // стык пола с задней стеной
    // ---------- КОМНАТА ШИРЕ ЭКРАНА ----------
    // Ширина комнаты в долях ширины ЭКРАНА. Экран — окно в неё, вбок оно
    // ездит свайпом.
    //
    // Зачем: ширина упиралась в 390 единиц экрана, а размах тела червя — 258.
    // Из этого не выкрутиться отступами: он физически занимал две трети
    // комнаты, и «не касаться стен» означало «стоять в середине». Плюс пол
    // 390×506 читался коридором. При 1.9 пол становится 741×506 — уже
    // помещение, у червя втрое больше места вбок, и остаётся куда ставить
    // мебель.
    widthRatio: 1.9,
    // Ровно половина ширины КОМНАТЫ: передние углы пола ложатся на её края,
    // и зазора между стеной и краем мира не остаётся.
    frontHalfRatio: 0.5,
    // Высота стен считается от ширины ЭКРАНА, а не комнаты. Иначе расширение
    // мира задирало бы стены вместе с ним, и вся вертикальная композиция,
    // подобранная выше, поехала бы.
    wallHeightRatio: 0.78,
    // Сила перспективы: scale(d) = 1 / (1 + d*depthK).
    //
    // Была 0.42 — при закрытой коробке это превращало комнату в длинный
    // тоннель: дальняя стена втрое уже передней. Комната у тамагочи — не
    // коридор, она должна читаться помещением почти сразу, поэтому схождение
    // умеренное: дальняя грань уже передней примерно вдвое.
    //
    // Убавлять его вслед за наклоном камеры (ближе к изометрии — слабее
    // схождение) пробовали: при 0.12 стены становятся почти параллельными, и
    // на узком вертикальном экране пол превращается в плоскую ленту без
    // глубины. Наклон камеры задаётся долями выше, а это число отвечает за то,
    // читается ли пол уходящим вдаль.
    depthK: 0.20,
    farDepth: 4.6,         // глубина дальней стены
    // Червь ходит НЕ по всей глубине: у дальней стены он мельче, а стена там
    // ниже него, и голова начинала бы торчать над комнатой.
    // ---------- ГРАНИЦЫ ВЫГУЛА ----------
    // Это не «где червю разрешено стоять», а лишь ВНЕШНИЕ рамки поиска.
    // Настоящая граница считается от габаритов тела: см. refreshWanderRange
    // и clampFloorPoint. Причина — константа не может знать, какого размера
    // червь: он растёт с возрастом, и подобранный вручную отступ перестал бы
    // работать на первом же новом сегменте.
    wanderNear: 0.25,      // ближняя граница поиска
    wanderFar: 3.4,        // дальняя граница поиска
    // Отступ от стен и кромок кадра в условных единицах холста. Меряется от
    // ГАБАРИТА ТЕЛА, а не от точки касания: тело лежит вдоль пола и занимает
    // место, поэтому «касание внутри пола» ещё не значит, что хвост не заехал
    // в стену.
    wanderMargin: 12,
    // Сколько места вбок должно остаться на глубине, чтобы она вообще
    // считалась пригодной. Без этого условия дальняя часть комнаты
    // формально проходима, но полоса там уже тела: червь оказывается
    // намертво прижат к середине и перестаёт двигаться вбок вовсе. Дешевле
    // объявить такую глубину непригодной и не пускать его туда.
    wanderMinSpan: 18,
    // ---------- ПРИГЛУШЕНИЕ МАСШТАБА ПЕРСОНАЖА ----------
    // Пол считается по ЧЕСТНОЙ перспективе, а размер персонажа — нет, и это
    // осознанное расхождение.
    //
    // Если дать персонажу полный перспективный масштаб, у дальней стены он
    // ужмётся вдвое: это читается не «отошёл вглубь», а «провалился в яму»,
    // и мелкую мимику становится не разглядеть. Если же приглушить саму
    // перспективу пола, комната станет плоской.
    //
    // Поэтому глубина у них общая, а сила отклика разная: пол — 1.0,
    // персонаж — вот столько. Так комната остаётся глубокой, а размер
    // меняется заметно, но не пугающе.
    charScaleStrength: 0.45
};

// w — ширина ЭКРАНА (окна), h — его высота. Сама комната шире: её ширина
// возвращается в g.roomW, и все координаты пола/стен считаются в ней.
function roomGeometry(w, h) {
    const roomW = w * ROOM.widthRatio;
    const frontY = h * ROOM.floorFrontRatio;
    const backY = h * ROOM.floorBackRatio;
    const frontHalf = roomW * ROOM.frontHalfRatio;
    const farScale = roomScaleAt(ROOM.farDepth);
    // Точка схода не задаётся числом, а ВЫВОДИТСЯ из того, где должны
    // оказаться передний и дальний края пола. Иначе перспектива и границы
    // комнаты живут отдельными жизнями: подвинул край — пол перестал в него
    // упираться.
    const horizonY = (backY - farScale * frontY) / (1 - farScale);
    return {
        // w/h — ОКНО (экран), roomW — сама комната. Центр по комнате, а не по
        // экрану: вся геометрия пола и стен живёт в координатах комнаты.
        w, h, roomW, cx: roomW / 2,
        // Насколько далеко камера может уехать вбок: от левого края комнаты
        // до правого минус окно.
        panMax: Math.max(0, roomW - w),
        horizonY, frontY, frontHalf,
        backY, backHalf: frontHalf * farScale,
        // Высота стены у переднего края; у дальней она во столько же раз
        // меньше, во сколько уже пол. Считается от ширины ЭКРАНА — см.
        // wallHeightRatio.
        wallH: w * ROOM.wallHeightRatio,
        farScale
    };
}
// Геометрический масштаб на глубине d (0 = у самой камеры).
function roomScaleAt(d) {
    return 1 / (1 + Math.max(0, d) * ROOM.depthK);
}
// Масштаб ПЕРСОНАЖА на той же глубине — приглушённый, см. charScaleStrength.
function roomCharScaleAt(d) {
    return 1 + (roomScaleAt(d) - 1) * ROOM.charScaleStrength;
}
function roomYAt(g, d) { return g.horizonY + (g.frontY - g.horizonY) * roomScaleAt(d); }
function roomHalfAt(g, d) { return g.frontHalf * roomScaleAt(d); }
// Обратная задача: по экранной высоте — глубина. Нужна, чтобы масштабировать
// персонажа и след слизи, зная только их положение на полу.
function roomDepthAt(g, y) {
    const s = (y - g.horizonY) / Math.max(1e-6, g.frontY - g.horizonY);
    return Math.max(0, (1 / Math.max(1e-4, s) - 1) / ROOM.depthK);
}

// Отрисовка комнаты. Намеренно скупая: по формуле стиля интерьер — это
// «смокинг», он не имеет права спорить с персонажем за внимание
// (docs/art-direction.md §1.2, §5). Поэтому только плоскости, одна линия
// стыка и несколько очень слабых линий схода — самый дешёвый признак
// глубины из существующих.
// ---------- РИСУНОК ПОЛА ----------
// Паркет в перспективе. Доски лежат ВДОЛЬ взгляда, поэтому их края — это те
// же линии схода, что раньше изображали глубину: рисунок пола и признак
// глубины здесь одно и то же, и платить за них дважды не нужно.
//
// Поперёк идут торцы досок. Их шаг обязан сжиматься с глубиной по той же
// формуле, что и всё остальное в комнате (roomYAt), иначе пол выглядит
// наклеенной текстурой, а не уходящей поверхностью. Шаг по глубине берётся
// равномерным, а перспектива сама сгущает дальние ряды.
//
// Торцы вразбежку: у соседних рядов они смещены на полдоски. Ровная сетка
// стык-в-стык читается кафелем, а не паркетом, — вразбежку и кладут.
function buildFloorPattern(layer, g, loc) {
    if (loc.pattern !== 'planks') return;

    const PLANKS = 9;          // досок по ширине комнаты
    const ROW_DEPTH = 0.62;    // шаг торцов по глубине (в единицах глубины комнаты)

    // Ряды торцов: доли глубины, на которых доски стыкуются. Считаем один раз
    // и пользуемся в обоих проходах.
    const rows = [{ d: 0, y: g.frontY, half: g.frontHalf }];
    for (let d = ROW_DEPTH; d < ROOM.farDepth; d += ROW_DEPTH) {
        const y = roomYAt(g, d);
        if (y <= g.backY + 0.5) break;
        rows.push({ d, y, half: roomHalfAt(g, d) });
    }
    rows.push({ d: ROOM.farDepth, y: g.backY, half: g.backHalf });

    const xAt = (u, half) => g.cx + u * half;

    // ---------- ПРОХОД 1: заливки ----------
    // Тон меняется ПО ДОСКЕ и остаётся постоянным вдоль всей её длины.
    //
    // Первая версия меняла тон по клеткам «доска × ряд» — и пол получился
    // шахматкой, то есть крупной плиткой, а не паркетом. Разница
    // принципиальная: доска — цельный кусок дерева, у неё один тон от начала
    // до конца, и именно это отличает дощатый пол от кафеля. Разбежку даёт не
    // цвет, а короткие торцевые швы ниже.
    //
    // Тон берётся от номера доски синусом: нужен разброс без «через одну»
    // (полосатый пол читается зеброй) и без случайности (комната
    // перестраивается при каждом изменении размера окна, и пол не должен
    // перекрашиваться на глазах).
    const front = rows[0], back = rows[rows.length - 1];
    for (let i = 0; i < PLANKS; i++) {
        const shade = Math.sin(i * 2.399) * 0.5 + 0.5;    // 0..1, вразнобой
        const u0 = (i / PLANKS) * 2 - 1;
        const u1 = ((i + 1) / PLANKS) * 2 - 1;
        layer.appendChild(svgEl('path', {
            d: 'M ' + xAt(u0, front.half).toFixed(1) + ',' + front.y.toFixed(1) +
               ' L ' + xAt(u1, front.half).toFixed(1) + ',' + front.y.toFixed(1) +
               ' L ' + xAt(u1, back.half).toFixed(1) + ',' + back.y.toFixed(1) +
               ' L ' + xAt(u0, back.half).toFixed(1) + ',' + back.y.toFixed(1) + ' Z',
            fill: shade > 0.5 ? loc.floor.light : loc.floor.seam,
            opacity: (Math.abs(shade - 0.5) * 0.34).toFixed(3)
        }));
    }

    const line = (x1, y1, x2, y2, opacity) => {
        layer.appendChild(svgEl('line', {
            x1: x1.toFixed(1), y1: y1.toFixed(1), x2: x2.toFixed(1), y2: y2.toFixed(1),
            stroke: loc.floor.seam, 'stroke-width': SW.hairline, opacity
        }));
    };

    // ---------- ПРОХОД 2: швы ----------
    // Продольные — от переднего края к дальнему. Они же и есть линии схода:
    // рисунок пола и признак глубины здесь одно и то же.
    for (let i = 1; i < PLANKS; i++) {
        const u = (i / PLANKS) * 2 - 1;
        line(xAt(u, g.frontHalf), g.frontY, xAt(u, g.backHalf), g.backY, 0.5);
    }

    // Торцы — стыки двух досок в длину. Рисуются коротким отрезком в пределах
    // ОДНОЙ доски: сплошная линия через всю комнату превратила бы пол в кафель.
    //
    // И они редкие. Доска длинная, на видимом куске пола её стык попадается
    // не в каждом ряду; если ставить торец через одну, стыки выстраиваются в
    // регулярную сетку — снова кафель. Признак берётся хешем от номера доски
    // и ряда: разброс есть, но он один и тот же при каждой перестройке.
    for (let r = 1; r < rows.length - 1; r++) {
        const row = rows[r];
        for (let i = 0; i < PLANKS; i++) {
            if ((Math.sin(i * 12.9898 + r * 78.233) * 43758.5453 % 1 + 1) % 1 > 0.34) continue;
            const u0 = (i / PLANKS) * 2 - 1;
            const u1 = ((i + 1) / PLANKS) * 2 - 1;
            line(xAt(u0, row.half), row.y, xAt(u1, row.half), row.y, 0.42);
        }
    }
}

function buildRoom(layer, g, locationKey) {
    while (layer.firstChild) layer.removeChild(layer.firstChild);

    // Облик берётся из таблицы локаций (src/core/rooms.js), а не задаётся
    // здесь: комната — косметика, её будут менять на подвал, церковь, пещеру.
    // Отрисовка обязана уметь нарисовать любую, не зная, какая именно.
    const loc = (typeof RoomLocations !== 'undefined')
        ? RoomLocations.get(locationKey)
        : null;
    if (!loc) return;   // rooms.js не подключён — рисовать нечего

    const backY = g.backY, backHalf = g.backHalf;
    const wallH = g.wallH, backWallH = wallH * g.farScale;
    const L = g.cx - g.frontHalf, R = g.cx + g.frontHalf;   // передние углы пола
    const bl = g.cx - backHalf, br = g.cx + backHalf;       // дальние углы пола
    const topFront = g.frontY - wallH;                      // верх стены у камеры
    const topBack = backY - backWallH;                      // верх стены у дальней грани

    const floorFill = loc.floor.base;
    const wallBack = loc.walls.back;
    const wallLit = loc.walls.lit;
    const wallShade = loc.walls.shade;

    const poly = (pts, fill, opacity) => {
        const d = 'M ' + pts.map(p => p[0].toFixed(1) + ',' + p[1].toFixed(1)).join(' L ') + ' Z';
        const el = svgEl('path', { d, fill });
        if (opacity != null) setAttr(el, 'opacity', opacity);
        layer.appendChild(el);
        return el;
    };

    // Пустота вокруг коробки. Тот же тон, что у полей за пределами холста, —
    // тогда поля на нетипичном экране не читаются обрезкой, а выглядят
    // продолжением темноты вокруг комнаты.
    layer.appendChild(svgEl('rect', { x: 0, y: 0, width: g.roomW, height: g.h, fill: loc.surround }));

    // Боковые стены: от передних углов пола к дальним, вверх на высоту стены.
    poly([[L, g.frontY], [bl, backY], [bl, topBack], [L, topFront]], wallShade);
    poly([[R, g.frontY], [br, backY], [br, topBack], [R, topFront]], wallLit);

    // Задняя стена.
    poly([[bl, backY], [br, backY], [br, topBack], [bl, topBack]], wallBack);

    // Пол — трапеция между передними и дальними углами.
    poly([[L, g.frontY], [R, g.frontY], [br, backY], [bl, backY]], floorFill);

    // Рисунок пола. Единственное место, где локация требует не цвета, а кода:
    // доски, камень и земля рисуются по-разному.
    buildFloorPattern(layer, g, loc);

    // Плинтус по низу задней стены — самая дешёвая деталь, превращающая две
    // плоскости в комнату: без неё стык читается обрывом.
    const plinthH = Math.max(2, backWallH * 0.14);
    poly([[bl, backY], [br, backY], [br, backY - plinthH], [bl, backY - plinthH]],
         loc.plinth);

    // Плинтус по БОКОВЫМ стенам. Он уходит в перспективу вместе с ними,
    // поэтому у камеры выше, чем у дальней стены — во столько же раз, во
    // сколько сама стена. Без него плинтус задней стены обрывался в воздухе
    // на стыке углов, и было видно, что комната сделана из трёх отдельных
    // плоскостей, а не из стен.
    const plinthFront = plinthH / g.farScale;
    poly([[L, g.frontY], [bl, backY], [bl, backY - plinthH], [L, g.frontY - plinthFront]],
         mixColor(loc.plinth, P_.ink, 0.28));                  // левая — в тени
    poly([[R, g.frontY], [br, backY], [br, backY - plinthH], [R, g.frontY - plinthFront]],
         loc.plinth);

    // Рёбра коробки. Самые тёмные линии сцены после контура персонажа:
    // именно они делают комнату комнатой, а не набором пятен.
    // Прозрачности рёбер заданы относительно локации: в СВЕТЛОЙ комнате та же
    // контурная линия бьёт в глаза куда сильнее, чем в тёмной, и комната
    // начинает спорить с персонажем за внимание. Множитель локации убавляет
    // их все разом, не трогая соотношение между ними.
    const edgeK = loc.edges.opacity / 0.85;
    const edge = (x1, y1, x2, y2, opacity, width) => {
        layer.appendChild(svgEl('line', {
            x1: x1.toFixed(1), y1: y1.toFixed(1), x2: x2.toFixed(1), y2: y2.toFixed(1),
            stroke: loc.edges.ink, 'stroke-width': width || SW.structure,
            opacity: (opacity * edgeK).toFixed(3)
        }));
    };
    edge(bl, backY, br, backY, 0.85);                    // стык задней стены с полом
    edge(L, g.frontY, bl, backY, 0.6);                   // стык левой стены с полом
    edge(R, g.frontY, br, backY, 0.6);                   // стык правой стены с полом
    edge(bl, backY, bl, topBack, 0.5, SW.detail);        // дальние вертикальные рёбра
    edge(br, backY, br, topBack, 0.5, SW.detail);
    edge(L, topFront, bl, topBack, 0.45, SW.detail);     // верхние кромки стен
    edge(R, topFront, br, topBack, 0.45, SW.detail);
    edge(bl, topBack, br, topBack, 0.45, SW.detail);
    // Передний край пола — нижняя кромка коробки.
    edge(L, g.frontY, R, g.frontY, 0.7);

    // Мягкая тень у дальнего стыка: пол уходит в темноту вдали, а не
    // обрывается ступенькой.
    const gradId = 'worm-room-depth-grad';
    if (!layer.querySelector('#' + gradId)) {
        const defs = svgEl('defs');
        const grad = svgEl('linearGradient', { id: gradId, x1: '0', y1: '0', x2: '0', y2: '1' });
        // Тон притемнения задаёт локация. Он НЕ контурный ink: сливовый ink
        // давал полу отчётливый лиловый налёт у дальней стены. У деревянного
        // пола это тёмное дерево — угол комнаты уходит в тень, а не в грязь.
        grad.appendChild(svgEl('stop', {
            offset: '0%', 'stop-color': loc.depth.color, 'stop-opacity': String(loc.depth.opacity)
        }));
        grad.appendChild(svgEl('stop', {
            offset: '100%', 'stop-color': loc.depth.color, 'stop-opacity': '0'
        }));
        defs.appendChild(grad);
        layer.appendChild(defs);
    }
    poly([[bl, backY], [br, backY],
          [g.cx + (g.frontHalf + backHalf) * 0.5, (backY + g.frontY) * 0.5],
          [g.cx - (g.frontHalf + backHalf) * 0.5, (backY + g.frontY) * 0.5]],
         `url(#${gradId})`);
}

