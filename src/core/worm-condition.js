// ================= СОСТОЯНИЕ ЧЕРВЯ: ДОВОЛЬНОСТЬ И СМЕРТЬ =================
// Семь шкал грехов сворачиваются в одно число — довольность (0..1), и из неё
// выводится всё, что видно на персонаже: выражение морды, худоба, серость.
// Здесь же живёт ответ на вопрос «что при нуле»: смерть.
//
// ---------- ПОЧЕМУ ЗДЕСЬ НЕТ НИ ОДНОГО ТАЙМЕРА ----------
// Соблазн был написать «если все шкалы на нуле — запустить суточный отсчёт».
// Это ровно тот тикающий таймер состояния, который запрещён инвариантом 1:
// он не идёт при закрытом приложении, а тамагочи должен умирать и в кармане.
//
// Вместо отсчёта — формула. У каждой шкалы известны последнее значение и
// метка времени, поэтому МОМЕНТ, когда она обнулилась (или обнулится),
// вычисляется точно:
//
//     zeroAt = updated_at + value / rate
//
// Все семь пусты с того мгновения, когда обнулилась ПОСЛЕДНЯЯ из них, то есть
// с максимума этих моментов. Прошли сутки от него — червь мёртв. Ничего
// хранить не надо: ответ выводится из тех же данных, что и сами шкалы, и
// одинаков хоть при открытой игре, хоть после недели в закрытой.
//
// Побочная выгода: отсчёт сам сбрасывается при любой кормёжке. Заполнил одну
// шкалу — её zeroAt уехал в будущее, максимум вместе с ним, и до смерти снова
// сутки. Отдельного кода «сбросить таймер» не существует.

const WormCondition = {

    // Момент, когда обнулится (или обнулилась) одна шкала. Для пустой шкалы
    // это прошлое, для полной — будущее.
    zeroAt(sinKey) {
        const sin = GameState.data ? GameState.data.sins[sinKey] : null;
        if (!sin) return -Infinity;

        const rate = GameState.decayRate(sinKey);
        // Шкала, которая не падает (rate 0 — например, отключена множителем),
        // не обнулится никогда, и червь при ней не умрёт. Это правильно:
        // смерть наступает от заброшенности, а не от арифметики.
        if (!(rate > 0)) return Infinity;

        // Считается от СОХРАНЁННОГО значения и его метки, а не от текущего.
        // Текущее (GameState.sinValue) обрезано нулём снизу, и у давно пустой
        // шкалы оно равно нулю — то есть «обнулится прямо сейчас», сколько бы
        // недель она ни стояла пустой. Отсчёт до смерти при этом вечно
        // начинался заново, и червь не умирал никогда.
        return sin.updated_at + (sin.value / rate) * 1000;
    },

    // С какого момента ПУСТЫ ВСЕ СЕМЬ. Будущее (или бесконечность) означает,
    // что сейчас пусты не все.
    starvingSince() {
        let last = -Infinity;
        for (const key of ECONOMY.sinOrder) {
            const at = this.zeroAt(key);
            if (at > last) last = at;
        }

        // Воскрешение обнуляет прошлое: червя подняли — считать голодание с
        // меток, оставшихся от прошлой жизни, нельзя, иначе он умрёт снова в
        // ту же секунду.
        const revived = GameState.data && GameState.data.worm ? GameState.data.worm.revived_at : null;
        if (revived && revived > last) last = revived;

        return last;
    },

    // Сколько часов червь уже голодает по всем семи. Ноль — значит не голодает.
    starvingHours() {
        const since = this.starvingSince();
        if (!isFinite(since)) return 0;
        return Math.max(0, (GameTime.now() - since) / 3600000);
    },

    dead() {
        return this.starvingHours() >= ECONOMY.condition.deathAfterHours;
    },

    // Сколько часов осталось до смерти. null — часы не идут (хоть одна шкала
    // не на нуле). Пригодится предупреждению игроку и debug-панели.
    hoursLeft() {
        const since = this.starvingSince();
        if (!isFinite(since)) return null;
        const left = ECONOMY.condition.deathAfterHours - this.starvingHours();
        return Math.max(0, left);
    },

    // ---------- ДОВОЛЬНОСТЬ ----------
    // 0..1. Все шкалы полные — 1, все пустые — 0. Смесь среднего и самой
    // пустой шкалы; почему не чистое среднее — см. ECONOMY.condition.
    mood() {
        if (!GameState.data) return 1;

        let sum = 0, worst = 1, count = 0;
        for (const key of ECONOMY.sinOrder) {
            const max = GameState.maxValue(key);
            if (!(max > 0)) continue;
            const share = Math.max(0, Math.min(1, GameState.sinValue(key) / max));
            sum += share;
            if (share < worst) worst = share;
            count++;
        }
        if (!count) return 1;

        const cfg = ECONOMY.condition;
        const avg = sum / count;
        const total = cfg.moodAverage + cfg.moodWorst || 1;
        return (avg * cfg.moodAverage + worst * cfg.moodWorst) / total;
    },

    // ---------- ВЫРАЖЕНИЕ МОРДЫ ----------
    // Довольность → набор «живых» каналов рендерера. Никакой отдельной ветки
    // кода на грустного червя: те же самые параметры, что двигают мимику в
    // мини-играх, просто взятые в другой точке.
    //
    // Все кривые линейные и без порогов — довольность меняется медленно
    // (часами), и любая ступенька в ней читалась бы как подмена лица.
    facePose(mood) {
        const m = Math.max(0, Math.min(1, mood));

        return {
            // Рот: положительное — улыбка, отрицательное — грусть. Самая
            // сильная часть выражения, поэтому размах наибольший.
            mouthCurve: -0.34 + m * 0.78,

            // Веки: у довольного открыты, у несчастного наползают. Не до
            // конца — закрытые глаза читаются сном, а не унынием.
            eyelidLevel: (1 - m) * 0.42,

            // Взгляд вниз: положительное — вниз (ось экрана). Опущенный
            // взгляд делает грусть безошибочной даже на мелком экране.
            gazeY: (1 - m) * 0.55,

            // Брови домиком. Слегка ПОДНЯТЫ, а не нахмурены: нахмуренные
            // читаются злостью, а нужен несчастный, а не сердитый.
            browRaise: (1 - m) * 0.3,

            // Уши — САМАЯ сильная часть выражения у этого персонажа, и это
            // выяснилось на скриншотах. Рот у свиночервя мелкий, сидит сбоку
            // и наполовину прячется под пятачком: в три четверти его кривая
            // почти не читается, особенно на телефоне. А уши огромные, торчат
            // выше головы и видны при любом ракурсе. Положительный угол
            // разводит их наружу и вниз — поникшие уши узнаются мгновенно,
            // даже когда всё остальное едва заметно.
            earTilt: (1 - m) * 24
        };
    },

    // ---------- ИСТОЩЕНИЕ ТЕЛА ----------
    // Худоба и потеря цвета. Начинается не сразу: выше порога червь выглядит
    // здоровым, иначе он был бы вечно полудохлым — шкалы почти никогда не
    // стоят полными.
    wither(mood) {
        const cfg = ECONOMY.condition;
        const from = cfg.witherFrom;
        if (mood >= from) return { belly: 1, saturation: 1 };

        // 0 у порога → 1 на дне.
        const depth = from > 0 ? Math.max(0, Math.min(1, (from - mood) / from)) : 0;
        return {
            belly: 1 - depth * cfg.witherThin,
            saturation: 1 - depth * cfg.witherGrey
        };
    }
};

if (typeof window !== 'undefined') window.WormCondition = WormCondition;
