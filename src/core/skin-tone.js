// ================= ТОН КОЖИ: ОТ ПЕРСОНАЖА, А НЕ ИЗ ПАЛИТРЫ =================
// Всё, что растёт из тела и рисуется ОТДЕЛЬНО от рендерера червя (хвост в
// ванне, в будущем — другие приросты), берёт цвет не из палитры, а у кожи
// самого персонажа. Тогда особь другого цвета (createVariedWormModel,
// будущие эволюции) и истощённый червь получают такой же хвост, как их
// тело, без единой правки в рисунке.
//
// Цвет собирается в три слоя, всегда в этом порядке:
//   1. КОЖА — цвет части модели (belly.fill и т.п.);
//   2. СВОЙ ТОН — относительные операции: светлее/темнее, сочнее/бледнее,
//      прилив крови. Относительные, а не «смешать с таким-то цветом»:
//      смешивание с розовым сделало бы синего червя лиловым, а «на 20%
//      сочнее» у синего червя даёт более сочный синий;
//   3. САМОЧУВСТВИЕ — то же обесцвечивание, что рендерер запекает в тело
//      (witherColor с той же насыщенностью), — последним, поверх всего.
//
// Операции считаются в OKLCH — пространстве, где «светлее» меняет только
// светлоту, а «сочнее» — только насыщенность, и оттенок при этом не плывёт.
// В rgb или hsl «ярче» у красного и у синего выходило бы по-разному.

const SkinTone = {
    // ---------- sRGB ↔ OKLab ↔ OKLCH ----------
    toLch(css) {
        const c = parseCssColor(css);
        const lin = (v) => { v /= 255; return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
        const r = lin(c.r), g = lin(c.g), b = lin(c.b);
        const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
        const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
        const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
        const L = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s;
        const A = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s;
        const B = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s;
        return { L, C: Math.hypot(A, B), H: Math.atan2(B, A) };
    },
    toCss(lch) {
        const A = lch.C * Math.cos(lch.H), B = lch.C * Math.sin(lch.H), L = lch.L;
        const l = Math.pow(L + 0.3963377774 * A + 0.2158037573 * B, 3);
        const m = Math.pow(L - 0.1055613458 * A - 0.0638541728 * B, 3);
        const s = Math.pow(L - 0.0894841775 * A - 1.2914855480 * B, 3);
        const out = [
            4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
            -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
            -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
        ].map(v => {
            v = Math.max(0, Math.min(1, v));
            v = v <= 0.0031308 ? 12.92 * v : 1.055 * Math.pow(v, 1 / 2.4) - 0.055;
            return Math.round(v * 255);
        });
        return `rgb(${out[0]},${out[1]},${out[2]})`;
    },

    // Оттенок крови — у нутра из палитры: прилив тянет кожу К НЕМУ.
    bloodHue() {
        if (this._blood == null) this._blood = this.toLch(PALETTE.viscera[500]).H;
        return this._blood;
    },

    // Свой тон поверх кожи. Все поля необязательны, ноль — «как кожа»:
    //   light  — светлее (+) или темнее (−), в долях шкалы светлоты;
    //   chroma — сочнее (+) или бледнее (−), доля от своей насыщенности;
    //   blood  — прилив крови 0..1: сочнее и глубже; у тёплой кожи
    //            оттенок ещё и тянется к крови.
    shift(css, op) {
        if (!op) return css;
        const c = this.toLch(css);
        let { L, C, H } = c;
        if (op.blood) {
            const k = Math.max(0, Math.min(1, op.blood));
            let d = this.bloodHue() - H;
            d = Math.atan2(Math.sin(d), Math.cos(d));   // кратчайший путь по кругу
            // Оттенок тянется к крови ТОЛЬКО у тёплой кожи — чем ближе, тем
            // сильнее. Первая версия тянула всех: у зелёного червя путь к
            // красному шёл через жёлтый, и головка выходила оливковой. У
            // холодной кожи прилив — это сочность и глубина СВОЕГО цвета.
            H += d * k * Math.max(0, Math.cos(d));
            C *= 1 + 0.5 * k;
            L -= 0.05 * k;
        }
        if (op.chroma) C *= Math.max(0, 1 + op.chroma);
        if (op.light) L += op.light;
        return this.toCss({ L: Math.max(0, Math.min(1, L)), C, H });
    },

    // Несколько операций подряд складываются: так ступень прокачки и
    // ситуация (налив) не знают друг о друге.
    sum(...ops) {
        const out = { light: 0, chroma: 0, blood: 0 };
        for (const o of ops) if (o) {
            out.light += o.light || 0;
            out.chroma += o.chroma || 0;
            out.blood += o.blood || 0;
        }
        return out;
    },

    // Кожа части модели — то, что рендерер берёт за основу тела.
    skin(model, part) {
        const p = model && (model[part || 'belly'] || model.belly);
        return (p && p.fill) || PALETTE.flesh[500];
    },

    // Самочувствие — последним: ровно то, что рендерер запекает в тело.
    wither(css, sat) {
        return (sat == null || sat >= 0.999) ? css : (witherColor(css, sat) || css);
    }
};

if (typeof window !== 'undefined') window.SkinTone = SkinTone;
