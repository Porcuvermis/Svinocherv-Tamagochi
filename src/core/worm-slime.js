// ================= СЛЕД СЛИЗИ НА ПОЛУ =================
// Отдельный файл, потому что это отдельная механика: она ничего не знает о
// червe, кроме того, где он сейчас и идёт ли. Жила она внутри mount() — той
// самой функции на две с половиной тысячи строк, — и найти в ней что-либо
// было нельзя.
//
// ---------- ЧТО НАРУЖУ ----------
// WormSlime.attach(ctx) отдаёт два метода:
//   fade(now)                       — высыхание уже нарисованного;
//   update(now, isMoving, anchor)   — продолжить след за идущим червём.
// ctx: { svg, wet, glow, state, instanceId, opts } — холст, две группы
// наложения, состояние экземпляра, его номер и настройки.
//
// Числа и ПОЧЕМУ след устроен из пяти слоёв — ниже, вместе с константами.


// ---------- СЛЕД — ЭТО НЕ КРАСКА, А СЛИЗЬ НА ПОЛУ ----------
// Две попытки до этой провалились одинаково — плоско.
//
// Первая: заливка, оливковый штрих поверх пола. Заливка не знает, на чём
// лежит: на светлых досках зелёная полоса, на тёмных её нет вовсе.
// Вторая: только затемнение (multiply). Пол честно намокал, но это была
// ровная полоса с каймой — влажное место, а не слизь.
//
// Слизь на референсах собирается из ЧЕТЫРЁХ вещей, и без любой из них она
// разваливается в плоское пятно:
//   1. неровный, натёкший силуэт — с наплывами, языками и оторвавшимися
//      каплями рядом; ровная ширина мгновенно читается полосой краски;
//   2. затемнение основы — плёнка мокрая, под ней пол темнее и холоднее;
//   3. КРУПНЫЕ мягкие блики — главный признак глянца. Не искры и не
//      тонкая жила, а размытые пятна отражённого света в полширины следа.
//      Объём плёнке даёт только это: свет по краю и тень под пятном
//      пробовали, и то и другое читается обводкой и ореолом;
//   4. пузырьки — мелкие светлые точки внутри. Это то, что отличает гель
//      от воды: в воде нечему держать пузырь.
//
// Мягкость всех бликов — радиальными градиентами, а не размытием: фильтр
// на каждое пятно стоил бы кадров, а градиент рисуется как обычная
// заливка (тот же приём, что у пятен на теле, см. ensureSoftGradient).
const WORM_SLIME_WIDTH = 26;
// ПЛОТНОСТЬ ЗАДАЁТ ГРУППА, А НЕ ЦВЕТ. Внутри мокрой группы все куски —
// штрих, наплывы, сгустки, начальная клякса — рисуются ОДНИМ непрозрачным
// цветом, и только вся группа целиком получает прозрачность и умножение.
//
// Так было не сразу, и «не сразу» выглядело плохо: пока у каждого куска
// была своя прозрачность, каждый торчащий за тело кусок читался отдельным
// тёмным облаком, а вместе они давали неровный ореол вокруг следа. Ровно то
// же и с мягким краем в три ступени ширины — это и есть ореол, только
// аккуратный. Однородная плёнка с ЧЁТКИМ краем оказалась и правильнее, и
// проще: у слизи край резкий, она не туман.
const WORM_SLIME_WET_ALPHA = 0.32;
// Растушёвка края: две ступени ЧУТЬ шире тела и полупрозрачные — внутри
// изолированной группы они складываются в короткий спад плотности вместо
// ножевого среза.
//
// Ключевое слово «чуть» и «те же». Первая попытка мягкого края была шире
// тела в полтора раза и накрывала не всю форму (наплывы шли своей шириной),
// поэтому спад читался не краем, а отдельным тёмным облаком вокруг следа.
// Ступени идут по ОБОИМ штрихам — и по телу, и по наплывам, — и выходят за
// силуэт на считанные единицы: тогда это край, а не ореол.
const WORM_SLIME_EDGE = [[1.2, 0.18], [1.1, 0.45]];
// Канта света по краю здесь НЕТ и не будет. Пробовали дважды: широкий и
// сдвинутый давал светящийся ободок вокруг следа, узкий и точно по кромке —
// аккуратную светлую обводку. И то и другое читается контуром, наведённым
// поверх пятна, а не мокрой плёнкой: обводка — признак наклейки. Объём
// плёнке даёт только блеск на ней самой.
// Всё, что сыплется по ходу — раз в N шагов следа (шаг = MIN_STEP единиц).
const WORM_SLIME_BUBBLE_EVERY = 7;   // пузырьки
const WORM_SLIME_SHINE_EVERY = 4;    // крупные блики
const WORM_SLIME_LUMP_EVERY = 5;     // сгустки и оторвавшиеся капли
const WORM_SLIME_DROP_EVERY = 11;    // капли кислоты
const WORM_SLIME_DROP_R = 2.1;
const WORM_SLIME_DROP_ALPHA = 0.42;
const WORM_SLIME_SHINE_ALPHA = 0.5;
const WORM_SLIME_BUBBLE_ALPHA = 0.45;
// ---------- ВЫСЫХАНИЕ: СЛЕД НЕ ГАСНЕТ, А УБЫВАЕТ ----------
// Прозрачности при высыхании больше НЕТ ни у одного куска следа, и это не
// экономия, а единственный способ убрать то, ради чего вся плёнка и была
// сведена в одну группу. Пока подсыхающий отрезок гас прозрачностью, он
// снова становился полупрозрачным слоем поверх соседей: в местах, где след
// пересекал сам себя, оттенки перемножались, и на полу опять проступали
// отдельные куски.
//
// Поэтому слизь УБЫВАЕТ С ХВОСТА: то, что нарисовано раньше, стирается
// раньше, а стирается оно обрезкой самого штриха (stroke-dasharray), а не
// прозрачностью. Плёнка в каждой точке либо есть целиком, либо её нет —
// значит перекрытия одинаковы всегда, и швов между отрезками не видно
// никогда.
//
// ФРОНТ ВЫСЫХАНИЯ ОДИН НА ВСЁ. Это главное правило здесь, и оно куплено
// дорого. Сначала у слоёв были РАЗНЫЕ сроки жизни (край 1000 и 1400, блеск
// 1500, тело 2000): выглядело это как бесплатное сужение хвоста, а на деле
// давало три отдельных фронта, идущих далеко друг от друга. Считать просто:
// след живёт две секунды, значит слой со сроком 1000 стёрт по всей СТАРШЕЙ
// ПОЛОВИНЕ следа. То есть у половины дорожки разом пропадала мягкая кромка,
// а следом и блеск — «сначала на всём отрезке отключаются эффекты, и только
// потом стирается сам след». Именно так это и выглядело на телефоне.
//
// Теперь сроки различаются на КОНЧИК — шесть десятых доли секунды, не
// больше. При обычной скорости червя это единицы, а не десятки единиц пути:
// скос у самого стираемого края, а не полследа без эффектов. Кромка, блеск и
// плёнка уходят в одном месте и в один момент, и место это едет по следу от
// хвоста к червю.
//
// Числа — возраст слизи (мс), в котором пропадает слой. Полная жизнь две
// секунды: секунду след лежит целым, вторую убывает.
const WORM_SLIME_LIFE_MS = 2000;        // возраст, в котором пропадает тело плёнки
// Ширина скоса на кончике, в миллисекундах возраста. Разницу сроков задавать
// только через неё: любое «своё» число тут же разъезжается в отдельный фронт.
const WORM_SLIME_TIP_MS = 60;
// Ступени края: чем шире ступень, тем раньше она уходит — от этого кончик
// сходит на нет, а не обрубается.
const WORM_SLIME_EDGE_LIFE = [WORM_SLIME_LIFE_MS - WORM_SLIME_TIP_MS * 2,
                              WORM_SLIME_LIFE_MS - WORM_SLIME_TIP_MS];
// Блеск гаснет на том же кончике. А СГУСТКИ — часть самой плёнки, и
// снимаются они не по возрасту, а вместе с ней: у каждого украшения
// помнится, на каком месте следа оно лежит, и оно исчезает ровно тогда,
// когда край высыхания дошёл до этого места.
const WORM_SLIME_SHINE_LIFE = WORM_SLIME_LIFE_MS - WORM_SLIME_TIP_MS;
// Такт высыхания: как часто пересчитывается обрезка. Чаще не нужно — за
// семьдесят миллисекунд край сдвигается на пару единиц.
const WORM_SLIME_FADE_TICK = 70;
// Длина штриха в узоре обрезки. Заведомо длиннее любого отрезка следа: узор
// ставится один раз и никогда не повторяется, двигается только его смещение.
//
// Смещение при этом ПОЛОЖИТЕЛЬНОЕ: «начать с пропуска в q единиц» — это
// не -q, а период минус q (период = штрих + пропуск = два раза по числу
// ниже). Арифметически это то же самое, но отрицательное смещение — место,
// где движки исторически расходятся: в SVG 1.1 отрицательное значение
// объявлено ОШИБКОЙ, разрешил его только SVG 2. Игра живёт на айфоне, то
// есть на WebKit, а прогоны идут в Chromium — проверить эту разницу отсюда
// нечем. Значит на неё нельзя и опираться.
const WORM_SLIME_DASH = 100000;
// Длина одного отрезка следа в опорных точках и сколько отрезков живёт разом.
// Оба числа — про цену, а не про вид: короткий путь перерисовывается быстро,
// а предел отрезков не даёт беготне по комнате копить их без счёта.
const WORM_SLIME_SEG_POINTS = 16;
const WORM_SLIME_MAX_SEGS = 14;
// Шаг опорной точки следа. Точки соединяются КРИВОЙ, а не отрезками: на
// медленном устройстве персонаж успевает уехать далеко между кадрами, и
// ломаная из таких звеньев выглядела чертежом — прямые куски со стыками
// под углом. Кривая по тем же точкам идёт плавно.
const WORM_SLIME_MIN_STEP = 4;
// На сколько должен измениться масштаб глубины, чтобы начать новый отрезок следа.
const WORM_SLIME_DEPTH_STEP = 0.1;
// На сколько единиц след готов «догнать» точку выхода после остановки. Червь
// стоит на месте, но хвост при развороте уезжает на десятки единиц — и это
// честная слизь: хвост правда проволокли по полу. А вот прыжок через всю
// комнату (вернулись из мини-игры, персонажа переставили) слизью соединять
// нечем: там след начинается заново.
const WORM_SLIME_LINK_MAX = 120;

const WormSlime = {

    attach(ctx) {
        const svg = ctx.svg, state = ctx.state, opts = ctx.opts || {};
        const slimeWetAll = ctx.wet, slimeGlowAll = ctx.glow;
        const instanceId = ctx.instanceId;

        // ---------- СЛИЗИСТЫЙ СЛЕД (pose:'standing' + wander) ----------
        function randomBlobPath(cx, cy, rng, r) {
            const n = 6;
            const pts = [];
            for (let i = 0; i < n; i++) {
                const a = (i / n) * Math.PI * 2;
                const rr = r * (0.6 + rng() * 0.7);
                pts.push([cx + Math.cos(a) * rr, cy + Math.sin(a) * rr * 0.75]);
            }
            let d = `M ${pts[0][0].toFixed(1)},${pts[0][1].toFixed(1)} `;
            for (let i = 1; i <= n; i++) {
                const p = pts[i % n];
                d += `L ${p[0].toFixed(1)},${p[1].toFixed(1)} `;
            }
            return d + 'Z';
        }

        // Цвет "мокрого" — не краска, а множитель: на что умножается пол под
        // плёнкой. Он зелёный, но работает не как зелёная полоса поверх, а
        // как светофильтр: доска остаётся доской, только уходит в тень и в
        // зелень. Чистая кислота была бы ядовитой заливкой, чистая чернила —
        // просто тенью; нужна их середина.
        const SLIME_WET = mixColor(ACID_DEEP, P_.acid[400], 0.35);
        // Отдельный <defs> под градиенты слизи: они общие на все следы этого
        // персонажа, поэтому создаются один раз, а не на каждый блик.
        const slimeDefs = svgEl('defs');
        svg.appendChild(slimeDefs);
        const slimeCtx = { defs: slimeDefs, gradCache: Object.create(null) };
        const slimeShine = ensureSoftGradient(slimeCtx, `worm-slime-shine-${instanceId}`,
                                              SPEC, WORM_SLIME_SHINE_ALPHA);

        function startSlimeTrail(x, y, now) {
            // Наложения и изоляции здесь БОЛЬШЕ НЕТ: они лежат на двух общих
            // группах слоя (см. slimeWetAll/slimeGlowAll). Отрезок — просто
            // непрозрачные куски внутри них.
            const wetG = svgEl('g', { class: 'worm-slime-wet' });
            const glowG = svgEl('g', { class: 'worm-slime-gloss' });
            // След лежит НА ПОЛУ, значит подчиняется той же перспективе, что
            // и всё остальное: у дальней стены он должен быть уже. Но ширина
            // держится в состоянии, а не берётся у каждого отрезка своя:
            // отрезки нарезаются часто (это про цену перерисовки), и если
            // каждый брал бы текущую глубину, по следу пошли бы ступеньки
            // ширины на каждом стыке.
            const trailScale = state.slimeScale != null ? state.slimeScale
                                                        : (opts.room ? state.depthScale : 1);
            const w = WORM_SLIME_WIDTH * trailScale;
            const rng = mulberry32(hashStringSeed(`slime-${instanceId}-${state.slimeTrails.length}-${Math.round(x)}-${Math.round(y)}`));
            const start = `M ${Math.round(x)},${Math.round(y)}`;
            const strokes = [];
            // life — возраст, в котором слой пропадает. Разный у слоёв, и
            // именно из этой разницы получается сужение хвоста: широкие
            // ступени края стираются раньше узкого тела.
            // Каждый слой плёнки — сплошной штрих с круглыми торцами и с
            // узором, который задаётся ОДИН раз и заведомо длиннее любого
            // отрезка. Высыхание двигает только смещение узора — одно число
            // за такт на слой.
            //
            // Пунктирного штриха «наплывов» здесь больше нет. Обрезать его
            // высыханием можно было только через нулевой штрих в узоре, а
            // нулевой штрих с круглым торцом рисуется ТОЧКОЙ; с плоским
            // торцом капли превращались в прямоугольные зубцы по краю следа.
            // Неровный силуэт даёт то же, что и раньше давало половину
            // работы, — сгустки у кромки (см. ниже), просто их стало чаще.
            const stroke = (color, width, life) => {
                const el = svgEl('path', {
                    d: start, fill: 'none', stroke: color,
                    'stroke-width': (w * width).toFixed(2),
                    'stroke-linecap': 'round', 'stroke-linejoin': 'round',
                    // Узор задан ЯВНОЙ парой «штрих, пропуск», а не одним
                    // числом. Одно число спецификация велит удваивать самой,
                    // и период узора получается неявным — а от него зависит
                    // вся обрезка (см. ниже). Полагаться в этом на движок
                    // незачем: пара стоит столько же и читается одинаково
                    // везде.
                    'stroke-dasharray': WORM_SLIME_DASH + ' ' + WORM_SLIME_DASH
                });
                wetG.appendChild(el);
                strokes.push({ el, life, cut: -1 });
                return el;
            };
            // Снизу вверх: растушёвка края, тело плёнки, наплывы.
            WORM_SLIME_EDGE.forEach(([k, a], i) =>
                stroke(withAlpha(SLIME_WET, a), k, WORM_SLIME_EDGE_LIFE[i] || WORM_SLIME_EDGE_LIFE[0]));
            stroke(SLIME_WET, 1, WORM_SLIME_LIFE_MS);
            // Комки, капли и начальная клякса — своим слоем: при высыхании
            // они снимаются раньше плёнки, и её усыхание видно чисто.
            const lumps = svgEl('g', { class: 'worm-slime-lumps' });
            // Начальная клякса: след начинается лужицей, а не срезом. Она же
            // закрывает стык с предыдущим отрезком.
            const blob = svgEl('ellipse', {
                cx: 0, cy: 0, rx: (w * 0.5).toFixed(2), ry: (w * 0.36).toFixed(2),
                fill: SLIME_WET,
                transform: `translate(${x.toFixed(1)},${y.toFixed(1)}) rotate(${(rng() * 180).toFixed(1)})`
            });
            lumps.appendChild(blob);
            wetG.appendChild(lumps);
            const shine = svgEl('g', { class: 'worm-slime-shine' });
            const bubbles = svgEl('g', { class: 'worm-slime-bubbles' });
            glowG.appendChild(shine);
            glowG.appendChild(bubbles);
            slimeWetAll.appendChild(wetG);
            slimeGlowAll.appendChild(glowG);
            state.slimeTrails.push({
                wetG, glowG, strokes, lumps, shine, bubbles, rng, steps: 0,
                // Путь ДОСТРАИВАЕТСЯ, а не собирается заново из всех точек:
                // prefix — уже готовая часть строки, к ней приписывается
                // последнее звено. Пересборка была O(длины) на каждый шаг, и
                // чем длиннее след, тем дороже обходился каждый шаг червя.
                prefix: start, last: { x, y },
                // Возраст слизи считается ПО ДЛИНЕ: для каждой опорной точки
                // помнится, когда её положили и сколько пути к ней набежало.
                // Шестнадцать чисел на отрезок — по ним обрезка находит, где
                // сейчас проходит край высыхания.
                times: [now], lens: [0], len: 0,
                // Украшения снимаются поштучно, когда край до них дошёл.
                decor: [],
                scale: trailScale, points: 1
            });
            state.activeSlimeTrail = state.slimeTrails[state.slimeTrails.length - 1];
            state.activeSlimeTrail.decor.push({ el: blob, s: 0, shine: false });
            // Больше заданного числа отрезков на полу не живёт. При двух
            // секундах жизни это страховка, а не рабочий режим: сюда доходит
            // только тот случай, когда кадры провалились и высыхание не
            // успевало считаться.
            while (state.slimeTrails.length > WORM_SLIME_MAX_SEGS) {
                const t = state.slimeTrails.shift();
                if (t === state.activeSlimeTrail) state.activeSlimeTrail = null;
                t.wetG.remove();
                t.glowG.remove();
            }
        }

        // Точка со сносом ПОПЕРЁК следа: k = 0 — по центру, ±1 — у самого
        // края. Всё, что сыплется по ходу, ставится через неё, иначе капли
        // и блики выстраиваются в ровную линию по оси и получается разметка.
        function slimeSide(trail, x, y, prev, k) {
            const dx = x - prev.x, dy = y - prev.y;
            const len = Math.hypot(dx, dy) || 1;
            const half = WORM_SLIME_WIDTH * (trail.scale || 1) * 0.5;
            return {
                x: x - (dy / len) * half * k,
                y: y + (dx / len) * half * k,
                deg: Math.atan2(dy, dx) * 180 / Math.PI
            };
        }

        function extendSlimeTrail(x, y, now) {
            const trail = state.activeSlimeTrail;
            if (!trail) return;
            const last = trail.last;
            if (Math.hypot(x - last.x, y - last.y) < WORM_SLIME_MIN_STEP) return;

            // КРИВОЙ, а не ломаной. Между кадрами персонаж успевает уехать
            // на десятки единиц — тем дальше, чем слабее устройство, — и
            // ломаная из таких звеньев выглядит чертежом: прямые куски со
            // стыками под углом.
            //
            // Звено приписывается к уже готовой строке, а не пересобирается
            // из всех точек: та же кривая, но шаг стоит одинаково и на
            // третьей точке, и на трёхсотой.
            const mx = Math.round((last.x + x) / 2), my = Math.round((last.y + y) / 2);
            trail.prefix += ` Q ${Math.round(last.x)},${Math.round(last.y)} ${mx},${my}`;
            const d = trail.prefix + ` L ${Math.round(x)},${Math.round(y)}`;
            // Возраст слизи считается по длине пути: для новой точки
            // запоминаем, сколько его набежало и когда. По этим двум спискам
            // высыхание находит, где сейчас край.
            trail.len += Math.hypot(x - last.x, y - last.y);
            trail.times.push(now || performance.now());
            trail.lens.push(trail.len);
            trail.last = { x, y };
            trail.points++;
            // Одна строка пути на все штрихи: тело, наплывы и кайма — это
            // одна и та же линия, нарисованная разной толщиной.
            trail.strokes.forEach(s => setAttr(s.el, 'd', d));

            const n = ++trail.steps;
            const rng = trail.rng;
            const ts = trail.scale || 1;
            const w = WORM_SLIME_WIDTH * ts;

            // ПУЗЫРЬКИ. Мелкие светлые точки внутри плёнки — то, чем гель
            // отличается от воды. Ставятся вразнобой по всей ширине.
            if (n % WORM_SLIME_BUBBLE_EVERY === 0) {
                const p = slimeSide(trail, x, y, last, (rng() * 2 - 1) * 0.8);
                const r = w * (0.025 + rng() * 0.04);
                const el = svgEl('circle', {
                    cx: p.x.toFixed(1), cy: p.y.toFixed(1), r: r.toFixed(2),
                    fill: withAlpha(mixColor(SPEC, P_.acid[200], 0.5), WORM_SLIME_BUBBLE_ALPHA)
                });
                trail.bubbles.appendChild(el);
                trail.decor.push({ el, s: trail.len, shine: true });
            }

            // КРУПНЫЙ БЛИК — главный признак глянца. Мягкое пятно
            // отражённого света почти в полширины следа, вытянутое по ходу.
            // Сторона ВСЕГДА одна (верхне-левая): свет в игре падает оттуда
            // (art-direction §3), и от этого блики выстраиваются в одну
            // жилу вдоль следа, а не сыплются пылью в разные стороны —
            // именно это отличает глянец от крапа.
            // ...но С РАЗРЫВАМИ. Сплошная жила бликов вдоль всего следа —
            // это светящийся кабель, проверено. Блик рвётся: две-три
            // соседние вспышки, потом промежуток, где плёнка легла неровно
            // и света нет.
            if (n % WORM_SLIME_SHINE_EVERY === 0 && rng() < 0.6) {
                const p = slimeSide(trail, x, y, last, -0.34 + (rng() * 2 - 1) * 0.16);
                const el = svgEl('ellipse', {
                    cx: 0, cy: 0,
                    rx: (w * (0.3 + rng() * 0.42)).toFixed(2),
                    ry: (w * (0.13 + rng() * 0.08)).toFixed(2),
                    fill: slimeShine,
                    transform: `translate(${p.x.toFixed(1)},${p.y.toFixed(1)}) rotate(${p.deg.toFixed(1)})`
                });
                trail.shine.appendChild(el);
                trail.decor.push({ el, s: trail.len, shine: true });
            }

            // СГУСТКИ И ОТОРВАВШИЕСЯ КАПЛИ. Кляксы того же мокрого цвета:
            // те, что у кромки, сливаются со следом и делают его силуэт
            // рваным, те, что дальше — отдельные капельки рядом.
            if (n % WORM_SLIME_LUMP_EVERY === 0) {
                const far = rng() < 0.4;
                // Дальние сгустки сидят НА КРОМКЕ (k около единицы), а не
                // рядом с ней. Отдельно лежащая капля — это лишний предмет на
                // полу: игрок читает её не как рваный край лужи, а как то,
                // что след распался. Слизь должна быть одним телом, и всё,
                // что ей принадлежит, обязано её касаться.
                const p = slimeSide(trail, x, y, last, (rng() < 0.5 ? -1 : 1) * (far ? 0.85 + rng() * 0.2 : 0.55 + rng() * 0.3));
                // Эллипсом, а не многоугольником: у ломаной видны прямые
                // грани, и вместо натёка получается осколок.
                const lr = w * (far ? 0.07 + rng() * 0.05 : 0.17 + rng() * 0.13);
                const el = svgEl('ellipse', {
                    cx: 0, cy: 0, rx: lr.toFixed(2), ry: (lr * (0.55 + rng() * 0.4)).toFixed(2),
                    fill: SLIME_WET,
                    transform: `translate(${p.x.toFixed(1)},${p.y.toFixed(1)}) rotate(${(p.deg + (rng() * 60 - 30)).toFixed(1)})`
                });
                trail.lumps.appendChild(el);
                trail.decor.push({ el, s: trail.len, shine: false });
            }

            // КАПЛИ КИСЛОТЫ. Единственное место, где в следе есть цвет:
            // кислота — акцент, а акцент по правилу дозировки может быть
            // только точкой (art-direction §1.2).
            if (n % WORM_SLIME_DROP_EVERY === 0) {
                const p = slimeSide(trail, x, y, last, (rng() * 2 - 1) * 0.6);
                const r = WORM_SLIME_DROP_R * (0.6 + rng() * 0.8) * ts;
                const el = svgEl('ellipse', {
                    cx: p.x.toFixed(1), cy: p.y.toFixed(1),
                    rx: r.toFixed(2), ry: (r * (0.55 + rng() * 0.4)).toFixed(2),
                    fill: withAlpha(P_.acid[400], WORM_SLIME_DROP_ALPHA)
                });
                trail.bubbles.appendChild(el);
                trail.decor.push({ el, s: trail.len, shine: true });
            }

            // ОТРЕЗОК КОНЕЧЕН. Иначе за один проход по комнате вырастает
            // один путь на сотни звеньев: браузер перерисовывает его целиком
            // на каждый шаг червя, и площадь этой перерисовки — весь след.
            // Короткие отрезки стыкуются кляксой начала и в общей плёнке
            // неразличимы, зато меняется только последний из них.
            if (trail.points >= WORM_SLIME_SEG_POINTS) {
                // Отрезок кончился — и следующий начинается ЗДЕСЬ ЖЕ, в этой
                // самой точке, а не там, куда червь уедет к следующему кадру.
                //
                // Это не мелочь: между кадрами червь успевает проехать
                // десятки единиц (на слабом устройстве — тем больше, чем
                // хуже кадры). Пока новый отрезок начинался «где придётся»,
                // на каждом стыке оставался разрыв в один кадр хода, и
                // подсыхающий след рассыпался на куски — ровно то, за что
                // его и ругали.
                state.activeSlimeTrail = null;
                startSlimeTrail(x, y, now || performance.now());
            }
        }

        // ---------- СЛИЗЬ ЖИВЁТ ОТДЕЛЬНО ОТ ЧЕРВЯ ----------
        // Высыхание вынесено из updateSlimeTrail нарочно. Тот вызывался
        // только при opts.wander, а wander снимается со смертью персонажа —
        // и след мёртвого червя оставался на полу навсегда. След — это не
        // часть тела, а то, что тело оставило: он подсыхает сам по себе, что
        // бы ни случилось с червём, и по той же причине не красится фильтром
        // истощения (см. bakeWither).

        // Сколько пути отрезка положено РАНЬШЕ момента t. По этой длине
        // штрих и обрезается: всё, что старше, стёрто.
        //
        // Поиск идёт с конца: край высыхания почти всегда у первых точек, а
        // список короткий (шестнадцать штук на отрезок).
        function slimeCutAt(trail, t) {
            const times = trail.times, lens = trail.lens;
            if (!times.length || t <= times[0]) return 0;
            if (t >= times[times.length - 1]) return trail.len + 1;
            let i = 1;
            while (i < times.length && times[i] < t) i++;
            const t0 = times[i - 1], t1 = times[i];
            const k = t1 > t0 ? (t - t0) / (t1 - t0) : 1;
            return lens[i - 1] + (lens[i] - lens[i - 1]) * k;
        }

        function fadeSlimeTrails(now) {
            // Такт: за семьдесят миллисекунд край высыхания сдвигается на
            // пару единиц — чаще считать нечего.
            if (now - (state.slimeFadedAt || 0) < WORM_SLIME_FADE_TICK) return;
            state.slimeFadedAt = now;

            for (let i = state.slimeTrails.length - 1; i >= 0; i--) {
                const trail = state.slimeTrails[i];
                let alive = false;

                let cutBody = 0;
                for (let k = 0; k < trail.strokes.length; k++) {
                    const st = trail.strokes[k];
                    const cut = slimeCutAt(trail, now - st.life);
                    // Тело плёнки живёт дольше всех слоёв и стоит последним:
                    // его край и есть граница «здесь слизь ещё есть».
                    if (k === trail.strokes.length - 1) cutBody = cut;
                    if (cut <= trail.len) alive = true;
                    // Обрезка с начала пути. Прозрачности здесь нет НИ ОДНОЙ:
                    // плёнка в каждой точке либо есть целиком, либо её нет.
                    // Поэтому перекрытия одинаковы всегда и швов между
                    // отрезками не видно — ни свежих, ни подсыхающих.
                    const q = Math.round(Math.min(cut, trail.len + 2));
                    if (st.cut === q) continue;
                    st.cut = q;
                    // Узор стоит с рождения, двигается только его смещение:
                    // отрицательное смещение выставляет перед штрихом пропуск
                    // ровно в стёртое. Одно число за такт на слой.
                    setAttr(st.el, 'stroke-dashoffset', String(2 * WORM_SLIME_DASH - q));
                }

                // Украшения снимаются НЕ по своему возрасту, а по месту: у
                // каждого помнится, на какой длине следа оно лежит, и оно
                // уходит ровно тогда, когда край высыхания это место прошёл.
                // Так капля физически не может пережить плёнку под собой —
                // а именно одинокие капли и читались как распавшийся след.
                // Блеск — единственное исключение: у него свой, более ранний
                // край, потому что подсыхающая слизь сначала перестаёт
                // блестеть и только потом пропадает.
                const cutShine = trail.decor.length
                    ? slimeCutAt(trail, now - WORM_SLIME_SHINE_LIFE) : 0;
                for (let d = trail.decor.length - 1; d >= 0; d--) {
                    const it = trail.decor[d];
                    const edge = it.shine ? cutShine : cutBody;
                    // Три процента запаса. Край высыхания считается по
                    // ЛОМАНОЙ опорных точек, а рисуется по кривой, которая
                    // срезает углы и потому короче — замерено, до двух
                    // процентов на отрезок. Из-за этой разницы плёнка уходит
                    // чуть раньше расчёта, и без запаса капля успевала
                    // остаться на голом полу. Ошибаться надо в сторону
                    // «убрать раньше»: пропажу капли под плёнкой не видно, а
                    // каплю без плёнки видно сразу.
                    if (edge > it.s * 0.97) { it.el.remove(); trail.decor.splice(d, 1); }
                    else alive = true;
                }

                if (!alive) {
                    trail.wetG.remove();
                    trail.glowG.remove();
                    state.slimeTrails.splice(i, 1);
                    if (trail === state.activeSlimeTrail) state.activeSlimeTrail = null;
                }
            }
        }

        function updateSlimeTrail(now, isMoving, anchor) {
            if (!(isMoving && anchor)) {
                // Червь встал — отрезок закрывается. Но точка, где он
                // оборвался, ЗАПОМИНАЕТСЯ: пока эта плёнка не высохла,
                // следующий отрезок начнётся от неё, а не там, где окажется
                // хвост после разворота на месте. Иначе на каждой паузе в
                // следе оставалась дыра, и подсыхающий след читался как
                // распавшийся на куски.
                if (state.activeSlimeTrail) state.slimeResume = state.activeSlimeTrail;
                state.activeSlimeTrail = null;
                return;
            }
            // Ширина отрезка следа задаётся один раз, на его старте: это
            // обычный stroke, сузить его по длине нельзя. Поэтому когда червь
            // заметно меняет глубину, текущий отрезок закрывается и начинается
            // новый, уже своей ширины. Отрезки перекрываются, стык не виден, а
            // след честно сужается, уходя вглубь комнаты.
            if (opts.room && (state.slimeScale == null
                || Math.abs(state.depthScale / state.slimeScale - 1) > WORM_SLIME_DEPTH_STEP)) {
                // Глубина заметно изменилась — след честно сужается (или
                // расширяется), и для этого начинается новый отрезок. Он
                // начинается В КОНЦЕ предыдущего, а не в текущей точке:
                // иначе на стыке остаётся разрыв в один кадр хода.
                const act = state.activeSlimeTrail;
                state.slimeScale = state.depthScale;
                state.activeSlimeTrail = null;
                if (act) { state.slimeResume = null; startSlimeTrail(act.last.x, act.last.y, now); }
            }
            if (!state.activeSlimeTrail) {
                // Есть ли к чему пристыковаться: прошлый отрезок ещё лежит на
                // полу (не высох) и его конец недалеко.
                const back = state.slimeResume;
                const link = back && state.slimeTrails.indexOf(back) >= 0
                    && Math.hypot(anchor.x - back.last.x, anchor.y - back.last.y) <= WORM_SLIME_LINK_MAX
                    ? back.last : null;
                state.slimeResume = null;
                startSlimeTrail(link ? link.x : anchor.x, link ? link.y : anchor.y, now);
                if (link) extendSlimeTrail(anchor.x, anchor.y, now);
            } else extendSlimeTrail(anchor.x, anchor.y, now);
        }

        // ---------- КАДР НЕ СЧИТАЕТСЯ, ПОКА ХОЛСТ НЕ НА ЭКРАНЕ ----------
        // Это не «оптимизация на всякий случай», а лечение конкретной утечки.
        // Мини-игры («Тщеславие», «Чревоугодие») монтируют СВОЙ экземпляр
        // персонажа и намеренно держат его между открытиями, чтобы не платить
        // за пересборку семисот узлов. Но при закрытии никто не останавливал
        return { fade: fadeSlimeTrails, update: updateSlimeTrail };
    }
};

if (typeof window !== 'undefined') window.WormSlime = WormSlime;

