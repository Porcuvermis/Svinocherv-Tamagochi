// ================= ЛОКАЦИИ: ГДЕ ЖИВЁТ ЧЕРВЬ =================
// Комната — такая же косметика, как будущие шапки и ошейники: её можно будет
// купить и сменить. Поэтому она описана ДАННЫМИ, а не кодом.
//
// ---------- ПОЧЕМУ ИМЕННО ТАК ----------
// Соблазн был написать `if (location === 'cellar') { ...другие цвета... }`
// прямо в отрисовке. Тогда каждая новая локация означала бы правку рендерера,
// а их планируется много (подвал, церковь, пещера, лес). Здесь же новая
// локация — это одна запись в таблице ниже: рендерер не трогается вовсе.
//
// Геометрия коробки у всех локаций ОБЩАЯ и живёт в рендерере (ROOM). Это не
// упущение, а условие: червь ходит по полу, кучки ложатся на пол, тень
// считается от переднего края. Локация, которая меняет геометрию, ломает всё
// это разом — поэтому ей позволено менять только облик.
//
// Что локация задаёт:
//   walls    — три плоскости коробки. Свет один и он сверху-слева, поэтому
//              правая стена светлее левой; без этой разницы коробка
//              читается плоской раскраской, а не объёмом.
//   floor    — пол и его рисунок.
//   pattern  — какой рисунок класть на пол: 'planks' (доски), 'none' (гладкий).
//              Новый рисунок = новая ветка в buildFloorPattern рендерера,
//              и это единственное, ради чего рендерер придётся трогать.
//   surround — за коробкой. Тем же тоном закрашены поля холста на нетипичном
//              экране, поэтому они не читаются обрезкой.
//   depth    — чем притемняется пол у дальней стены.
//   edges    — насколько тёмные рёбра коробки. В светлой комнате контурная
//              линия видна сильнее, чем в тёмной, и её приходится убавлять.

const ROOM_LOCATIONS = {

    // ---------- ДОМ ----------
    // Стартовая и пока единственная. Светлая, тёплая, уютная: жильё, а не
    // склеп. Персонаж отделяется от неё по светлоте — он заметно темнее
    // и стен, и пола (см. комментарий к plaster/timber в palette.js).
    home: {
        name: 'Дом',
        walls: {
            back:  PALETTE.plaster[400],
            lit:   PALETTE.plaster[200],
            shade: PALETTE.plaster[600]
        },
        floor: {
            base:  PALETTE.timber[300],
            light: PALETTE.timber[100],
            seam:  PALETTE.timber[500],
            deep:  PALETTE.timber[700]
        },
        pattern: 'planks',
        plinth: PALETTE.timber[700],
        // Снаружи коробки темно: комната освещена, а то, что за ней, — нет.
        // Тёплый тёмный, а не чёрный: холодная рамка вокруг тёплой комнаты
        // выглядит вырезанной из другой картинки.
        surround: '#2a2119',
        depth: { color: PALETTE.timber[700], opacity: 0.42 },
        edges: { ink: PALETTE.ink, opacity: 0.45 }
    }

    // Дальше сюда добавляются подвал, церковь, пещера, лес. Каждая — такая же
    // запись: рендерер про них знать не обязан. Единственное, что может
    // потребовать кода, — новый рисунок пола (камень, земля, трава); всё
    // остальное набирается цветом.
};

const RoomLocations = {
    DEFAULT: 'home',

    get(key) {
        return ROOM_LOCATIONS[key] || ROOM_LOCATIONS[this.DEFAULT];
    },

    // Существует ли такая локация. Нужно там, где ключ приходит из
    // сохранения: сборка могла откатиться, а в сейве остался ключ локации,
    // которой в ней ещё (или уже) нет.
    has(key) {
        return Object.prototype.hasOwnProperty.call(ROOM_LOCATIONS, key);
    },

    keys() {
        return Object.keys(ROOM_LOCATIONS);
    },

    // Для будущего магазина: список с именами.
    list() {
        return Object.keys(ROOM_LOCATIONS).map(key => ({ key, name: ROOM_LOCATIONS[key].name }));
    }
};

if (typeof window !== 'undefined') {
    window.ROOM_LOCATIONS = ROOM_LOCATIONS;
    window.RoomLocations = RoomLocations;
}
