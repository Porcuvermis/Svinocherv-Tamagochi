// ============ МОДЕЛИ ВАННОЙ ============
// Процедурная геометрия для запекания (tools/bake-3d-core.js). Никаких
// внешних файлов моделей: geometry — это код, она весит ноль килобайт и
// правится там же, где всё остальное.
//
// Единица мира — примерно дециметр: ванна 17 × 7 × 6, чтобы числа читались.

const BATH_MODELS = {

    // ---------- ВАННА ----------
    // ТЕЛО ВРАЩЕНИЯ по профилю сечения, растянутое в овал. Не коробка с
    // вычтенной полостью: CSG в three.js нет, а вложенная оболочка не
    // работает — у наружной коробки есть верхняя грань, и она перекрывает
    // полость при любом порядке рисования. Проверено: чаша читалась
    // сплошным белым бруском.
    //
    // Профиль идёт от центра дна НАРУЖУ по внутренней стенке, перекатывается
    // через борт и спускается по наружной. Получается настоящий открытый
    // сосуд: верхней грани у него нет вовсе, внутренняя поверхность видна, а
    // борт имеет толщину и валик.
    // Сечение ОБМЕРЕНО С РЕФЕРЕНСА — обычной стальной ванны (glTF-модель
    // «Bath» AmongModels, CC-BY). Взята не геометрия, а пропорции: точки
    // ниже — обводка её сечения, поделённая на полуширину чаши. Своя модель
    // осталась своей (два десятка точек вместо четырёх тысяч, своя протяжка,
    // свои рампы), но форма теперь не выдумана.
    //
    // Что дал обмер и чего не было в выдуманном профиле:
    //  • БОРТ — самое широкое место ванны. Раньше ниже борта было «пузо»
    //    (вынос 1.115 против 1.00 на борту), и чаша читалась пластиковым
    //    тазом. У настоящей ванны стенка ПОДЖИМАЕТСЯ книзу: 0.87 сразу под
    //    бортом и 0.66 у подошвы. Перелив по стенке, ради которого пузо и
    //    вводилось, сужение даёт ничуть не хуже.
    //  • ПЛОСКИЙ ВЕРХ БОРТА шириной в 17% полуширины (0.821 → 0.995).
    //    Раньше борт был ножевым: одна точка на 1.00. Именно эта площадка и
    //    читается «загнутым краем» — валик без неё не виден.
    //  • ГАЛТЕЛЬ ДНА огромная: радиус около трети полуширины. Была фаска в
    //    один отрезок — она читалась срезом.
    // Пропорции корпуса: длина / ширина = 2.06, высота / полуширина = 1.44.
    TUB_PROFILE: [
        [0.000, -1.130],   // центр дна
        [0.250, -1.122],   // плоское дно кончилось
        [0.450, -1.070],   // галтель
        [0.600, -0.950],
        [0.710, -0.720],
        [0.775, -0.400],   // внутренняя стенка: почти отвесная
        [0.798, -0.090],
        [0.806, -0.020],   // подрез под кромку
        [0.821,  0.000],   // ВНУТРЕННЯЯ кромка борта  ← граница нутра и наружи
        [0.995,  0.000],   // НАРУЖНАЯ кромка: борт плоский и широкий
        [1.000, -0.036],   // валик заваливается наружу
        [0.955, -0.066],   // и круто уходит обратно
        [0.900, -0.100],
        [0.869, -0.240],   // стенка встала
        [0.828, -0.520],
        [0.750, -0.890],   // и поджимается книзу
        [0.700, -1.180],
        [0.600, -1.390],   // заворот в подошву
        [0.520, -1.439]    // подошва
    ],
    // Подошва у референса уходит внутрь до 0.30 полуширины, у нас — до 0.52.
    // Причина не в красоте: контур чаши смещается внутрь по нормали, и
    // смещение больше радиуса скругления УГОЛ ВЫВОРАЧИВАЕТ. При 0.30 вынос
    // (0.70·R = 2.24) обгонял радиус угла (2.2), все точки дуги схлопывались
    // в одну, и из угла вырастал веер осколков — под чашей висели два
    // чёрных плавника. Дно ванны всё равно стоит на полу и не видно.
    // Индекс точки, на которой профиль перекатывается с нутра на наружу.
    TUB_RIM: 8,
    // Высота референса в долях полуширины. Ею профиль растягивается под
    // нужную глубину: борт остаётся бортом, меняется только вытянутость.
    TUB_H: 1.439,

    // ---------- ВАННА ----------
    // ТЕЛО ВРАЩЕНИЯ по профилю сечения, растянутое в овал. Не коробка с
    // вычтенной полостью: CSG в three.js нет, а вложенная оболочка не
    // работает — у наружной коробки есть верхняя грань, и она перекрывает
    // полость при любом порядке рисования. Проверено: чаша читалась
    // сплошным белым бруском.
    //
    // Профиль идёт от центра дна НАРУЖУ по внутренней стенке, перекатывается
    // через борт и спускается по наружной. Получается настоящий открытый
    // сосуд: верхней грани у него нет вовсе, внутренняя поверхность видна, а
    // борт имеет толщину и валик.
    profile(o) {
        const R = o.wide / 2;
        // Растяжка по высоте: референс высотой 1.439·R, у нас deep.
        const k = o.deep / (BATH_MODELS.TUB_H * R);
        return BATH_MODELS.TUB_PROFILE.map(
            ([x, y]) => new THREE.Vector2(x * R, y * R * k));
    },

    // Вынос внутренней стенки на заданной высоте от борта. Им ставится вода:
    // раньше её край задавался отдельным числом «толщина стенки» и разъезжался
    // с профилем при каждой его правке.
    innerAt(o, y) {
        const p = BATH_MODELS.profile(o), rim = BATH_MODELS.TUB_RIM;
        for (let i = 0; i < rim; i++) {
            const a = p[i], b = p[i + 1];
            if (y >= a.y && y <= b.y) {
                const t = b.y === a.y ? 0 : (y - a.y) / (b.y - a.y);
                return a.x + (b.x - a.x) * t;
            }
        }
        return p[rim].x;
    },

    tub(opts) {
        const o = Object.assign({ len: 17, wide: 7.4, deep: 5.2, corner: 2.6, seg: 13 },
                                opts || {});
        const R = o.wide / 2;                       // радиус до наружного борта
        const profile = BATH_MODELS.profile(o);
        const rim = BATH_MODELS.TUB_RIM;
        // Профиль ПРОТЯГИВАЕТСЯ по контуру со скруглёнными углами, а не
        // крутится вокруг оси. Кручение даёт круглое сечение, и растянутый
        // круг читается тазом: у ванны бока ПРЯМЫЕ, и скруглены только углы.
        const plan = BATH_MODELS.roundedPlan(o.len, o.wide, o.corner, o.seg);
        const g = new THREE.Group();
        // Нутро и наружная стенка — РАЗНЫЕ куски, чтобы красить их разными
        // рампами. Заодно на борту появляется настоящий перелом нормали:
        // одной протяжкой он сглаживался, и борт терялся.
        const inner = new THREE.Mesh(BATH_MODELS.sweep(profile, plan, R, 0, rim));
        inner.userData.part = 'inner';
        g.add(inner);
        g.add(new THREE.Mesh(BATH_MODELS.sweep(profile, plan, R, rim,
                                               profile.length - 1)));
        // Дно чаши: тот же контур, смещённый внутрь ровно на вынос первой
        // точки профиля. Так дно попадает в стенку, а не рядом с ней.
        // Высота — тоже из профиля: дно чаши выше подошвы на толщину днища.
        const bottom = BATH_MODELS.flat(BATH_MODELS.fan(
            BATH_MODELS.inset(plan, R - profile[1].x), profile[0].y, true));
        bottom.userData.part = 'inner';
        g.add(bottom);
        // Ванна СТОИТ НА ПОЛУ. Модель строит её с бортом на нуле — это
        // удобный якорь для профиля, — но в комнате нулём является пол, и
        // без подъёма чаша оказывалась в него утопленной по самый борт.
        g.position.y = o.deep;
        return g;
    },

    // ---------- РАСКЛАДКА КОМНАТЫ ----------
    // Все числа мира в одном месте. Пол на нуле, ванна стоит на нём, стена
    // за ванной. Отсюда же берутся ЯКОРЯ — точки, которые запекание
    // проецирует в гнёзда игры: место крана, посадка червя, полка. Раньше
    // такие числа подбирались глазом и разъезжались с картинкой при каждой
    // её правке.
    LAYOUT: {
        // seg — сколько отрезков на скруглении угла чаши. Больше, чем нужно
        // для формы: гранёный край видно первым делом, а стоит он только
        // размера файла — в рантайм геометрия не попадает.
        // Пропорции корпуса — с референса (см. TUB_PROFILE): длина к ширине
        // 2.03, высота к полуширине 1.41. Прежние 5.2 высоты давали 2.5:1 при
        // натурных 3:1, и ближняя стенка выходила белой плитой в треть кадра.
        tub:   { len: 13, wide: 6.4, deep: 4.5, corner: 2.2, seg: 16 },
        wallZ: -3.9,          // стена сразу за ванной
        // Комната нарочно с ЗАПАСОМ по краям: камера наезжает вписыванием
        // прямоугольника целиком (contain), и на общем плане в кадр лезет
        // всё, что вокруг. Стены ровно по кадру не хватало — сверху зияла
        // дыра в фон окна.
        // Комната ЗНАЧИТЕЛЬНО больше кадра. Камера смотрит в лоб, а холст
        // игры вытянут по вертикали: любой наезд, при котором ванна влезает
        // по ширине, оставляет сверху и снизу по трети экрана — и всё это
        // обязана закрывать комната. Прежних 26 в высоту хватало косой
        // камере и не хватает этой: над плиткой зияла чёрная полоса.
        roomW: 16,            // половина ширины комнаты
        roomH: 38,            // до верха стены
        floorFront: 34,       // докуда виден пол перед ванной
        // Насколько высоко над бортом сидит червь. Воды в кадре нет вовсе:
        // камера смотрит СТРОГО В ЛОБ, внутренность чаши не видна, и борт
        // сам режет червя ровной линией. Рисовать поверхность, которой не
        // видно, — значит держать в игре целую подсистему ради нуля пикселей.
        sit: 1.2,
        // Душ ВЫСОКИЙ: он стоит у стены во весь рост, и низкая стойка рядом
        // с вынырнувшим червём читалась игрушечной. Лейка не ниже его головы.
        // Стойка растёт ИЗ СМЕСИТЕЛЯ (тот же x), а не стоит рядом с ним:
        // труба, обрывающаяся в воздухе рядом с краном, читалась недоделанной.
        // riser — где НАЧИНАЕТСЯ труба. Ровно на высоте смесителя: труба,
        // кончающаяся выше или ниже его корпуса, висит в воздухе обрубком.
        // Стойка УВЕДЕНА В САМЫЙ УГОЛ: в финале из ванны у левого борта
        // торчит хвост, и смеситель со стойкой стояли ровно на нём — тёмный
        // конус хвоста читался куском хрома.
        shower: { x: -7.6, y: 18.6, z: -1.6, riser: 8.4, arm: 7.0 },
        // Смеситель ВЫШЕ борта на три единицы. На 6.6 его закрывал
        // дальний борт: смотрим сверху, и борт проецируется вверх.
        faucet: { x: -7.6, y: 8.4 },
        // Полка ВЫШЕ и ПРАВЕЕ головы: на прежнем месте её закрывал собой
        // сам червь, и взять мыло было не с чего.
        // Полка ВЕРТИКАЛЬНАЯ, в два яруса: мыло на верхнем, мочалка на
        // нижнем. Горизонтальная полка тянулась поперёк кадра рядом с
        // головой червя, а над ней и под ней оставалось пустое поле плитки.
        // Игра вертикальная — и полка теперь тоже: два яруса ставят предметы
        // друг над другом и забирают ту самую пустоту.
        // Нижний ярус ОПУЩЕН ниже уха червя: на прежней высоте мочалка
        // приходилась ровно на него и пряталась за ним наполовину.
        shelf:  { x: 5.6, lo: 7.6, hi: 14.4, w: 3.0 }
    },

    // Якоря: точки МИРА, которые запекание переводит в координаты сцены.
    anchorPoints() {
        const L = BATH_MODELS.LAYOUT, T = L.tub;
        return {
            // Кран: тап по нему включает воду и начинает забег.
            faucet: { x: L.faucet.x, y: L.faucet.y, z: L.wallZ + 0.5 },
            // Лейка душа: из неё льётся на червя.
            showerHead: { x: L.shower.x + L.shower.arm, y: L.shower.y - 1.1,
                          z: L.shower.z },
            // Мыло и мочалка на полке — их ТАЩАТ на червя. Ярусы разные:
            // мыло сверху (им работают первым), мочалка снизу.
            //
            // Высота выведена ИЗ ДОСКИ и из самого предмета, а не подобрана:
            // предмет стоит подошвой на верхней грани доски, утопая в неё на
            // волосок. Подобранные числа оставляли между подошвой и доской
            // щель, и в лоб — а камера смотрит именно в лоб — предмет
            // читался висящим ПЕРЕД полкой, а не лежащим на ней.
            soap:  { x: L.shelf.x, y: L.shelf.hi + 0.17 + BATH_MODELS.SOAP.h / 2,
                     z: L.wallZ + 0.85 },
            cloth: { x: L.shelf.x, y: L.shelf.lo + 0.17 + BATH_MODELS.clothLift(),
                     z: L.wallZ + 0.8 },
            // Червь лежит в воде, ближе к дальнему борту: спереди в финале
            // всплывает хвост, и место ему надо оставить.
            // Червь сидит ВЫШЕ уровня воды на полтора корпуса: в финале
            // работает морда — открытый рот ловит струю, — и утопить её по
            // самые уши значит выбросить весь финал.
            worm: { x: 0, y: T.deep + L.sit, z: -0.9 },
            // Хвост торчит из ванны РЯДОМ С ЧЕРВЁМ, слева от его морды.
            //
            // Сначала его унесли к дальнему борту: на коротком плече у
            // баллистики нет дуги, прицел вырождался в нулевой изгиб. Но
            // виновата была не длина плеча, а СКОРОСТЬ: капля летела со
            // скоростью на пять метров, а бросок нужен был на два. Скорость
            // подобрали под плечо (economy.js), и дуга вернулась — заодно
            // став ПОЛОЖЕ по чувствительности к углу, то есть честнее.
            //
            // Взамен вернулась композиция старой версии игры: хвост крупным
            // передним планом, червь — большим фоном сразу за ним. На пол-
            // ванны врозь они не влезали в один кадр ни при каком наезде:
            // либо хвост с ноготь, либо от червя одно ухо.
            tail: { x: -2.6, y: T.deep, z: 0.1 },
            // Углы борта: по ним игра знает, где чаша, не повторяя чисел.
            rimL: { x: -T.len / 2, y: T.deep, z: 0 },
            rimR: { x: T.len / 2, y: T.deep, z: 0 },
            rimFront: { x: 0, y: T.deep, z: T.wide / 2 }
        };
    },

    // Сетка швов кафеля ОТРЕЗКАМИ В МИРЕ. Не геометрией: вдавленные швы
    // стоили бы тысяч треугольников. Не двумерной сеткой поверх готовой
    // картинки: между четырьмя углами проекции плоскости honest-интерполяция
    // не линейная, а проективная, и «на глаз» она разъедется. Отрезки
    // проецируются той же камерой, что и всё остальное, — и ложатся точно.
    tileLines(step) {
        const L = BATH_MODELS.LAYOUT, W = L.roomW, S = step || 1.7;
        const out = [];
        for (let x = -W; x <= W + 0.01; x += S)
            out.push([{ x, y: 0, z: L.wallZ }, { x, y: L.roomH, z: L.wallZ }]);
        for (let y = 0; y <= L.roomH + 0.01; y += S)
            out.push([{ x: -W, y, z: L.wallZ }, { x: W, y, z: L.wallZ }]);
        return out;
    },

    // Швы пола. Камера смотрит в лоб, и пол уходит вниз голой полосой в
    // четверть кадра: цвет есть, а поверхности нет — читается не полом, а
    // пустотой под картинкой. Швы стоят те же копейки, что и на стене, и
    // сразу дают полу и плоскость, и глубину: линии поперёк идут ровно
    // горизонтально, линии вдоль сходятся к центру кадра.
    floorLines(step) {
        const L = BATH_MODELS.LAYOUT, W = L.roomW, S = step || 2.4;
        const out = [];
        for (let x = -W; x <= W + 0.01; x += S)
            out.push([{ x, y: 0, z: L.wallZ }, { x, y: 0, z: L.floorFront }]);
        for (let z = L.wallZ; z <= L.floorFront + 0.01; z += S)
            out.push([{ x: -W, y: 0, z }, { x: W, y: 0, z }]);
        return out;
    },

    // ---------- КОМНАТА ----------
    // Пол и стена — РАЗНЫЕ предметы: у них разные рампы палитры. Одной
    // рампой на двоих комната выходила ровно белой, и ванна в ней терялась:
    // отделение по светлоте — основа всей графики игры.
    //
    // Кафель НЕ геометрией: сетка швов на плоской стене рисуется в 2д поверх
    // запечённого. Плоскость в перспективе и так правильная, а вдавленные
    // швы стоили бы тысяч треугольников ни за что.
    floor() {
        const L = BATH_MODELS.LAYOUT, W = L.roomW;
        // Одной плитой: порядок между предметами задан списком, и дробить
        // пол на ячейки ради сортировки больше незачем.
        //
        // Задняя кромка заходит ЗА стену на полторы единицы. Сведённые
        // встык, пол и стена оставляли по стыку светлую нить от сглаживания
        // — ту же самую, из-за которой на кухне действует правило
        // «стыки обязаны перекрываться».
        return BATH_MODELS.quad(
            [{ x: -W, y: 0, z: L.wallZ - 1.5 }, { x: W, y: 0, z: L.wallZ - 1.5 },
             { x: W, y: 0, z: L.floorFront }, { x: -W, y: 0, z: L.floorFront }]);
    },

    wall() {
        const L = BATH_MODELS.LAYOUT, W = L.roomW;
        // Стена плоская и стоит целиком дальше всего — дробить её незачем,
        // и одним путём она дешевле.
        return BATH_MODELS.quad(
            [{ x: -W, y: L.roomH, z: L.wallZ }, { x: W, y: L.roomH, z: L.wallZ },
             { x: W, y: 0, z: L.wallZ }, { x: -W, y: 0, z: L.wallZ }]);
    },

    // Плоский четырёхугольник с запомненным контуром: выйдет одним путём.
    quad(pts) {
        const v = [], idx = [0, 1, 2, 0, 2, 3];
        for (const p of pts) v.push(p.x, p.y, p.z);
        const geo = new THREE.BufferGeometry();
        geo.setAttribute('position', new THREE.Float32BufferAttribute(v, 3));
        geo.setIndex(idx);
        geo.computeVertexNormals();
        geo.userData.outline = pts.map(p => ({ x: p.x, y: p.y, z: p.z }));
        return BATH_MODELS.flat(geo);
    },

    // Тот же четырёхугольник, но РАЗБИТЫЙ на сетку. Нужен для больших
    // плоскостей — пола и стены.
    //
    // Порядок рисования у запекания — по глубине ЦЕНТРА фигуры, и у плиты
    // пола в десять единиц глубиной один центр ничего не решает: пол уходил
    // от стены до переднего края кадра, его середина оказывалась ближе
    // ванны, и он рисовался ПОВЕРХ неё. Разбитый на ячейки, он сортируется
    // с ванной вперемешку, как и должен.
    //
    // Швов от этого не возникает: у плоскости одна нормаль, значит все
    // ячейки одного цвета, а подряд идущие ячейки одного цвета запекание
    // сливает в один путь.
    quadGrid(pts, nu, nv) {
        const g = new THREE.Group();
        const lerp = (a, b, t) => ({ x: a.x + (b.x - a.x) * t,
                                     y: a.y + (b.y - a.y) * t,
                                     z: a.z + (b.z - a.z) * t });
        for (let i = 0; i < nu; i++) {
            for (let j = 0; j < nv; j++) {
                const u0 = i / nu, u1 = (i + 1) / nu;
                const v0 = j / nv, v1 = (j + 1) / nv;
                // Билинейная выборка по четырём углам исходной плиты.
                const at = (u, v) => lerp(lerp(pts[0], pts[1], u),
                                          lerp(pts[3], pts[2], u), v);
                g.add(BATH_MODELS.quad([at(u0, v0), at(u1, v0),
                                        at(u1, v1), at(u0, v1)]));
            }
        }
        return g;
    },

    // ---------- ДУШ ----------
    // Стояк по стене, колено и раструб лейки. Труба — протяжка окружности
    // по кривой: у three.js это TubeGeometry, и вручную её строить незачем.
    shower() {
        const L = BATH_MODELS.LAYOUT, S = L.shower;
        const g = new THREE.Group();
        // Хобот вынесен НАД ЧЕРВЁМ, а не над своей стойкой. Стойка стоит у
        // стены сбоку (она растёт из смесителя), и лейка над ней лила бы воду
        // в пустой угол ванны: червь сидит по центру. Настоящие душевые
        // штанги гнутся ровно за этим.
        const path = new THREE.CatmullRomCurve3([
            new THREE.Vector3(S.x, S.riser, L.wallZ + 0.35),
            new THREE.Vector3(S.x, S.y - 0.6, L.wallZ + 0.35),
            new THREE.Vector3(S.x, S.y + 1.0, L.wallZ + 0.9),
            new THREE.Vector3(S.x + 1.6, S.y + 1.5, S.z + 0.5),
            new THREE.Vector3(S.x + S.arm, S.y + 0.5, S.z)
        ], false, 'catmullrom', 0.4);
        g.add(new THREE.Mesh(new THREE.TubeGeometry(path, 24, 0.26, 12, false)));
        // Раструб: усечённый конус, широким концом ВНИЗ, НАКЛОНЁННЫЙ К ЧЕРВЮ.
        // Червь сидит не под самой лейкой: его голова смещена вправо от
        // посадочного якоря почти на два корпуса, и отвесная струя лила мимо
        // него в пустой угол. Тянуть штангу ещё на метр — нелепо; лейку
        // просто повернули, как её и поворачивают руками.
        const TILT = -0.26;
        const head = new THREE.Mesh(
            new THREE.CylinderGeometry(0.44, 1.15, 1.1, 22, 1, false));
        head.position.set(S.x + S.arm, S.y - 0.4, S.z);
        head.rotation.z = TILT;
        g.add(head);
        // Донце лейки — плоский диск, из него и льётся.
        const face = new THREE.Mesh(new THREE.CircleGeometry(1.15, 22));
        face.geometry.rotateX(-Math.PI / 2);
        face.position.set(S.x + S.arm + Math.sin(-TILT) * 0.56,
                          S.y - 0.96 + (Math.cos(TILT) - 1) * 0.56, S.z);
        face.rotation.z = TILT;
        g.add(face);
        return g;
    },

    // ---------- СМЕСИТЕЛЬ ----------
    // ---------- СМЕСИТЕЛЬ ----------
    // Настенный, с изливом вниз и одним рычагом. Собирается из четырёх
    // читаемых кусков: розетка на стене, корпус, излив, рычаг. Прежний
    // вариант был короткой трубкой в диске и на экране читался серой шишкой
    // — по силуэту в нём не опознавался кран.
    //
    // Из этого же корпуса растёт стойка душа (см. shower): труба,
    // обрывающаяся в воздухе рядом с краном, выглядела недоделанной.
    faucet() {
        const L = BATH_MODELS.LAYOUT, F = L.faucet;
        const g = new THREE.Group();
        const put = (m, x, y, z) => { m.position.set(x, y, z); g.add(m); return m; };

        // Розетка: плоский диск у самой стены.
        const rose = new THREE.Mesh(
            new THREE.CylinderGeometry(0.95, 1.05, 0.4, 16));
        rose.rotation.x = Math.PI / 2;
        put(rose, F.x, F.y, L.wallZ + 0.17);

        // Корпус: цилиндр от стены вперёд, со скруглённым торцом.
        const body = new THREE.Mesh(
            new THREE.CylinderGeometry(0.72, 0.8, 1.7, 16));
        body.rotation.x = Math.PI / 2;
        put(body, F.x, F.y, L.wallZ + 1.05);
        const cap = new THREE.Mesh(new THREE.SphereGeometry(0.72, 16, 10));
        put(cap, F.x, F.y, L.wallZ + 1.9);

        // Излив: колено вниз-вперёд, с лёгким расширением на конце.
        const path = new THREE.CatmullRomCurve3([
            new THREE.Vector3(F.x, F.y - 0.45, L.wallZ + 1.2),
            new THREE.Vector3(F.x, F.y - 1.25, L.wallZ + 2.0),
            new THREE.Vector3(F.x, F.y - 2.25, L.wallZ + 2.5)
        ], false, 'catmullrom', 0.4);
        g.add(new THREE.Mesh(new THREE.TubeGeometry(path, 14, 0.33, 11, false)));
        const lip = new THREE.Mesh(
            new THREE.CylinderGeometry(0.44, 0.37, 0.4, 13));
        put(lip, F.x, F.y - 2.45, L.wallZ + 2.55);

        // Рычаг: короткий цилиндр вверх-вперёд от корпуса.
        const lever = new THREE.Mesh(
            new THREE.CylinderGeometry(0.18, 0.16, 1.5, 11));
        lever.rotation.x = -0.5;
        put(lever, F.x, F.y + 1.0, L.wallZ + 1.45);
        const knob = new THREE.Mesh(new THREE.SphereGeometry(0.24, 11, 7));
        put(knob, F.x, F.y + 1.6, L.wallZ + 1.78);
        return g;
    },

    // ---------- ПОЛКА ----------
    // Плита с фаской по переднему краю и два кронштейна ПОД ней. Прежние
    // кронштейны торчали ниже полки отдельными брусками и читались ножками
    // висящего в воздухе столика.
    // Полка в два яруса — ДВЕ ОТДЕЛЬНЫЕ доски на кронштейнах, без общей рамы.
    //
    // Рама была дважды, и оба раза предмет опознавался не тем, чем он есть.
    // Со средней стойкой две одинаковые доски читались ГАНТЕЛЬЮ — два блина
    // на грифе. С боковыми стойками вышло хуже: две плиты в раме на ножках —
    // это форма ЗАЖИМА, и вся этажерка опознавалась прессом или весами, а
    // предметы на ней — зажатыми. Пустая середина рамы при этом занимала
    // больше половины предмета и перетягивала внимание на себя.
    //
    // Две доски на кронштейнах ни на что другое не похожи: горизонтальная
    // полка на стене — форма однозначная, и её ничто не перевешивает.
    shelf() {
        const L = BATH_MODELS.LAYOUT, S = L.shelf;
        const g = new THREE.Group();
        for (const y of [S.lo, S.hi]) {
            const slab = new THREE.Mesh(
                BATH_MODELS.roundedBox(S.w + 0.5, 0.32, 1.5, 0.14, 3));
            slab.position.set(S.x, y, L.wallZ + 0.95);
            g.add(slab);
            // Кронштейны под концами доски. Треугольник развёрнут К КАМЕРЕ,
            // а не поставлен ребром: ребром от него виден один прямоугольник
            // в две десятых шириной, и доска выходит на двух ножках, как
            // столик. Треугольник читается кронштейном сразу.
            const half = (S.w + 0.5) / 2;
            for (const k of [-1, 1]) {
                // Клин уходит ВНУТРЬ и вниз от конца доски. Наружу он торчал
                // за её край и читался не кронштейном, а хвостом ленты.
                const sh = new THREE.Shape();
                sh.moveTo(0, 0); sh.lineTo(-k * 0.72, 0);
                sh.lineTo(0, -0.52); sh.lineTo(0, 0);
                const br = new THREE.Mesh(new THREE.ExtrudeGeometry(sh,
                    { depth: 0.55, bevelEnabled: false }));
                br.position.set(S.x + k * (half - 0.12), y - 0.15, L.wallZ + 0.3);
                g.add(br);
            }
        }
        return g;
    },

    // Передний бортик доски — ОТДЕЛЬНЫЙ предмет, потому что рисуется ПОСЛЕ
    // мыла и мочалки. В этом весь смысл: камера смотрит в лоб, и «на полке»
    // от «перед полкой» отличается ровно одним — тем, что низ предмета
    // чем-то перекрыт.
    //
    // Перекрывать он обязан ПОДОШВУ, а не половину предмета. Полки висят
    // высоко над глазом, смотрим на них снизу, и всё, что ближе к камере,
    // проецируется ВЫШЕ: бортик, поднятый над доской на четверть своей
    // высоты, срезал брусок мыла посередине — предмет читался зажатым в
    // струбцине, а под бортиком снова торчал его низ.
    shelfRail() {
        const L = BATH_MODELS.LAYOUT, S = L.shelf;
        const g = new THREE.Group();
        for (const y of [S.lo, S.hi]) {
            // Бортик — это ПЕРЕДНЯЯ КРОМКА доски, чуть выступающая вперёд и
            // вверх, а не поручень над ней. Он обязан быть НЕ НИЖЕ подошвы
            // предмета: иначе под ним снова видно низ предмета, и тот
            // читается проходящим сквозь полку.
            const lip = new THREE.Mesh(
                BATH_MODELS.roundedBox(S.w + 0.5, 0.34, 0.18, 0.07, 2, 0.04));
            lip.position.set(S.x, y + 0.02, L.wallZ + 1.72);
            g.add(lip);
        }
        return g;
    },

    // ---------- МЫЛО ----------
    // Хозяйственный брусок «72%» с натуры: не мыльце-подушка, а КУСОК —
    // прямые грани, мелкая фаска, характерная подошва пошире корпуса
    // (след формы) и вдавленные цифры во всю переднюю грань.
    //
    // Пропорции с фотографии: длина к высоте чуть больше двух, глубина
    // чуть больше половины длины.
    SOAP: { w: 2.5, h: 1.15, d: 1.3, base: 0.16, turn: 0.16 },

    soap() {
        const a = BATH_MODELS.anchorPoints().soap, S = BATH_MODELS.SOAP;
        const g = new THREE.Group();
        // Корпус. Фаска мелкая (0.07 против обычных 0.18): с крупной брусок
        // читается подушкой.
        const body = new THREE.Mesh(
            BATH_MODELS.roundedBox(S.w, S.h - S.base, S.d, 0.09, 2, 0.07));
        body.position.y = S.base / 2;
        g.add(body);
        // Подошва: ЧУТЬ ШИРЕ корпуса и с ним не заподлицо. У настоящего
        // бруска это след формы — тонкий поясок по низу, и именно он не даёт
        // мылу выглядеть просто коробкой.
        const base = new THREE.Mesh(
            BATH_MODELS.roundedBox(S.w + 0.06, S.base, S.d + 0.05, 0.07, 2, 0.04));
        base.position.y = -(S.h - S.base) / 2;
        g.add(base);
        g.position.set(a.x, a.y, a.z);
        g.rotation.y = S.turn;
        return g;
    },

    // Клеймо «72%». Не геометрия, а ГРАВИРОВКА: ломаные, лежащие на
    // передней грани бруска. Вдавленные цифры мешем — это сотни
    // треугольников на предмет размером в сотню точек, и отбраковка всё
    // равно оставила бы от них кашу; линия по грани читается штампом и
    // стоит десяток отрезков (см. docs/bake-3d.md, «гравировка»).
    SOAP_GLYPHS: {
        '7': [[[0, 1], [0.62, 1]], [[0.62, 1], [0.24, 0]]],
        '2': [[[0.02, 0.76], [0.13, 0.93], [0.32, 1.0], [0.50, 0.93],
               [0.58, 0.76], [0.48, 0.56], [0.02, 0.02]],
              [[0.0, 0.02], [0.60, 0.02]]],
        '%': [[[0.58, 1.0], [0.02, 0.0]]]
    },

    soapMark() {
        const a = BATH_MODELS.anchorPoints().soap, S = BATH_MODELS.SOAP;
        const K = 0.56;          // высота цифры в единицах мира
        const TILT = -0.05;      // клеймо на бруске всегда чуть косое
        const ring = (cx, cy, r) => {
            const p = [];
            for (let i = 0; i <= 8; i++) {
                const t = i / 8 * Math.PI * 2;
                p.push([cx + Math.cos(t) * r, cy + Math.sin(t) * r * 1.05]);
            }
            return p;
        };
        const glyphs = Object.assign({}, BATH_MODELS.SOAP_GLYPHS);
        glyphs['%'] = glyphs['%'].concat([ring(0.17, 0.80, 0.15),
                                          ring(0.44, 0.20, 0.15)]);
        const out = [];
        const zf = S.d / 2 + 0.012;              // на самой грани, чуть поверх
        const cr = Math.cos(S.turn), sr = Math.sin(S.turn);
        let u0 = -1.09;   // клеймо по центру грани: три знака шагом 0.78
        for (const ch of ['7', '2', '%']) {
            for (const poly of glyphs[ch]) {
                const pts = poly.map(([u, v]) => {
                    const x0 = (u0 + u) * K, y0 = (v - 0.5) * K + 0.03;
                    const x = x0 * Math.cos(TILT) - y0 * Math.sin(TILT);
                    const y = x0 * Math.sin(TILT) + y0 * Math.cos(TILT);
                    return { x: a.x + x * cr + zf * sr, y: a.y + y,
                             z: a.z - x * sr + zf * cr };
                });
                for (let i = 1; i < pts.length; i++)
                    out.push([pts[i - 1], pts[i]]);
            }
            u0 += 0.78;
        }
        return out;
    },

    // ---------- ГУБКА ----------
    // С натуры: жёлтый поролон с ХВАТАМИ по бокам и тонкая зелёная
    // абразивная нашлёпка сверху.
    //
    // Наклонена НАЗАД почти на шестьдесят градусов, и это не поза, а
    // необходимость: полка висит выше глаза, камера смотрит на неё снизу, и
    // верхней грани не видно вовсе. Положи губку плашмя — весь абразив, то
    // есть половина предмета, уйдёт от зрителя. Наклон возвращает тот же
    // ракурс, с какого её снимают в каталоге: зелёный верх и жёлтый бок
    // одновременно. Прислонённая губка на полке — поза совершенно обычная.
    CLOTH: { w: 1.9, foam: 0.9, pad: 0.32, d: 1.4,
             // Наклон ПОЛОЖИТЕЛЬНЫЙ: поворот вокруг X на +a уводит верх
             // объекта К КАМЕРЕ (+z). С минусом губка заваливалась назад, и
             // вместо абразива в кадр выходила ярко освещённая передняя
             // грань поролона, а ворс ложился поверх неё.
             tiltX: 0.48, turnY: -0.24 },

    // Половина высоты НАКЛОНЁННОЙ губки: ею она и ставится на доску.
    // Считается, а не подбирается — иначе разъедется при первой же правке
    // наклона (docs/traps.md, п. 26).
    clothLift() {
        const C = BATH_MODELS.CLOTH;
        return (Math.abs(Math.cos(C.tiltX)) * (C.foam + C.pad)
              + Math.abs(Math.sin(C.tiltX)) * C.d) / 2;
    },

    // Общий поворот губки: им же кладётся её фактура.
    clothBasis() {
        const C = BATH_MODELS.CLOTH, a = BATH_MODELS.anchorPoints().cloth;
        const m = new THREE.Matrix4().makeRotationFromEuler(
            new THREE.Euler(C.tiltX, C.turnY, 0));
        m.setPosition(a.x, a.y, a.z);
        return m;
    },

    // Детерминированный шум: ворс обязан быть ОДИНАКОВЫМ у геометрии и у
    // фактуры, иначе линии лягут мимо своих бугров.
    noise(x, y) {
        const s = Math.sin(x * 127.1 + y * 311.7) * 43758.5453;
        return s - Math.floor(s);
    },

    cloth() {
        const C = BATH_MODELS.CLOTH;
        const g = new THREE.Group();
        const hw = C.w / 2, hd = C.d / 2;

        // Поролон: профиль торца (глубина × высота) с ВЫЕМКАМИ по бокам,
        // протянутый вдоль длинной оси. Выемки — те самые хваты для пальцев,
        // и они же главная примета губки: без них это просто брусок.
        const sh = new THREE.Shape();
        const y0 = -(C.foam + C.pad) / 2, y1 = y0 + C.foam;
        const cut = 0.26, lo = y0 + C.foam * 0.32, hi = y0 + C.foam * 0.64;
        sh.moveTo(-hd, y0);
        sh.lineTo(hd, y0);
        sh.lineTo(hd, lo - 0.1);
        sh.quadraticCurveTo(hd - cut, lo, hd - cut, (lo + hi) / 2);
        sh.quadraticCurveTo(hd - cut, hi, hd, hi + 0.1);
        sh.lineTo(hd, y1);
        sh.lineTo(-hd, y1);
        sh.lineTo(-hd, hi + 0.1);
        sh.quadraticCurveTo(-hd + cut, hi, -hd + cut, (lo + hi) / 2);
        sh.quadraticCurveTo(-hd + cut, lo, -hd, lo - 0.1);
        sh.lineTo(-hd, y0);
        const foam = new THREE.Mesh(new THREE.ExtrudeGeometry(sh, {
            depth: C.w, bevelEnabled: true, bevelThickness: 0.09,
            bevelSize: 0.09, bevelSegments: 2, curveSegments: 4
        }));
        // Протяжка идёт по Z, а длинная ось губки — X.
        foam.geometry.rotateY(Math.PI / 2);
        // Протяжка идёт из нуля в +длину, поэтому брусок надо сдвинуть на
        // половину назад: без этого поролон уезжал вбок от абразива и
        // предмет читался двумя плитами рядом.
        foam.geometry.translate(-hw, 0, 0);
        g.add(foam);

        // Абразив: тонкая плита, у которой ВЕРХНЯЯ ГРАНЬ ИЗОРВАНА шумом.
        // Это главный приём: мохнатость видна не по заливке, а по СИЛУЭТУ —
        // обводка предмета идёт по краю, и рваный край даёт рваную обводку.
        // Ровная плита с любой фактурой поверх читается наклейкой.
        const pad = new THREE.Mesh(
            new THREE.BoxGeometry(C.w, C.pad, C.d, 14, 1, 10));
        const pos = pad.geometry.attributes.position;
        const top = C.pad / 2;
        for (let i = 0; i < pos.count; i++) {
            if (pos.getY(i) < top - 1e-4) continue;
            // Смещение — чистая функция от (x, z), поэтому верхняя грань и
            // верхний ряд боковых граней расходятся согласованно и шов не
            // раскрывается.
            const x = pos.getX(i), z = pos.getZ(i);
            pos.setY(i, top + BATH_MODELS.noise(x * 8.3, z * 8.3) * 0.11);
        }
        pad.geometry.computeVertexNormals();
        pad.position.y = y1 + C.pad / 2;
        pad.userData.part = 'scour';
        g.add(pad);

        const a = BATH_MODELS.anchorPoints().cloth;
        g.position.set(a.x, a.y, a.z);
        g.rotation.set(C.tiltX, C.turnY, 0);
        return g;
    },

    // Фактура губки: поры поролона и ворс абразива. Оба слоя лежат на
    // гранях, которые видит камера, — на передней и на верхней.
    clothMarks() {
        const C = BATH_MODELS.CLOTH, B = PALETTE.bathScene;
        const M = BATH_MODELS.clothBasis();
        const hw = C.w / 2, hd = C.d / 2;
        const y0 = -(C.foam + C.pad) / 2, y1 = y0 + C.foam;
        const put = (x, y, z) => {
            const v = new THREE.Vector3(x, y, z).applyMatrix4(M);
            return { x: v.x, y: v.y, z: v.z };
        };
        const rnd = (() => { let s = 12345;
            return () => (s = (s * 1664525 + 1013904223) >>> 0) / 4294967296; })();

        // ПОРЫ. Не точки, а короткие дужки: точка в один пиксель на
        // проекции пропадает, а дужка держит размер и читается дыркой.
        const pore = [], poreLit = [];
        for (let i = 0; i < 105; i++) {
            const u = (rnd() - 0.5) * (C.w - 0.24);
            const v = y0 + 0.1 + rnd() * (C.foam - 0.2);
            const r = 0.02 + rnd() * 0.022;
            const a0 = rnd() * Math.PI * 2;
            const arc = [];
            for (let k = 0; k <= 3; k++) {
                const t = a0 + k / 3 * Math.PI * 1.4;
                arc.push(put(u + Math.cos(t) * r, v + Math.sin(t) * r, hd + 0.01));
            }
            for (let k = 1; k < arc.length; k++) pore.push([arc[k - 1], arc[k]]);
            // Блик по нижнему краю дырки — она сразу становится ямкой.
            poreLit.push([put(u - r * 0.7, v - r * 0.8, hd + 0.012),
                          put(u + r * 0.7, v - r * 0.8, hd + 0.012)]);
        }

        // ВОРС. Короткие штрихи ПОПЕРЁК верхней грани и по её краю: абразив
        // — это спутанное волокно, и читается оно направлением штриха, а не
        // пятном. Часть штрихов переваливает за край на переднюю грань:
        // ровно так выглядит мохнатая кромка.
        const fuzz = [], fuzzLit = [];
        for (let i = 0; i < 330; i++) {
            const u = (rnd() - 0.5) * (C.w - 0.06);
            const w = (rnd() - 0.5) * (C.d - 0.04);
            const h = y1 + C.pad + BATH_MODELS.noise(u * 8.3, w * 8.3) * 0.11;
            const len = 0.045 + rnd() * 0.055;
            const ang = rnd() * Math.PI * 2;
            const dz = Math.sin(ang) * len, dx = Math.cos(ang) * len;
            const line = [put(u, h + 0.01, w), put(u + dx, h + 0.01 + len * 0.35, w + dz)];
            (rnd() < 0.28 ? fuzzLit : fuzz).push(line);
        }
        // Ворс на ПЕРЕДНЕЙ грани абразива. Без него грань — ровная тёмная
        // стенка, и слой читается крашеным пластиком, а не волокном.
        for (let i = 0; i < 110; i++) {
            const u = (rnd() - 0.5) * (C.w - 0.06);
            const v = y1 + 0.02 + rnd() * (C.pad - 0.04);
            const len = 0.04 + rnd() * 0.05;
            const line = [put(u, v, hd + 0.012),
                          put(u + (rnd() - 0.5) * 0.05, v + len, hd + 0.016)];
            (rnd() < 0.3 ? fuzzLit : fuzz).push(line);
        }
        // Бахрома по переднему краю: штрихи, свисающие с кромки вниз.
        for (let i = 0; i < 90; i++) {
            const u = (rnd() - 0.5) * (C.w - 0.04);
            const h = y1 + C.pad + BATH_MODELS.noise(u * 8.3, hd * 8.3) * 0.11;
            const len = 0.06 + rnd() * 0.09;
            const line = [put(u, h, hd + 0.02),
                          put(u + (rnd() - 0.5) * 0.08, h - len, hd + 0.03)];
            (rnd() < 0.3 ? fuzzLit : fuzz).push(line);
        }

        return [
            { lines: pore,    color: B.spongePore, width: 1.15 },
            { lines: poreLit, color: B.spongeLit,  width: 1.0 },
            { lines: fuzz,    color: B.scourFuzz,  width: 1.15 },
            { lines: fuzzLit, color: B.scourLit,   width: 1.05 }
        ];
    },

    // Контур, смещённый внутрь на заданную величину. Им ставятся вода и дно
    // чаши: они обязаны попадать РОВНО на стенку, а не «примерно туда».
    inset(plan, by) {
        return plan.map(q => {
            // Смещение НЕ БОЛЬШЕ радиуса угла. Смещая дугу на её же радиус,
            // мы стягиваем её в точку, а сверх того — выворачиваем наизнанку:
            // соседние точки меняются местами, и из угла лезет веер
            // вывернутых треугольников. Ошибка тихая — контур остаётся
            // замкнутым, габарит верный, видно только по мусору в кадре.
            const d = q.r != null ? Math.min(by, q.r * 0.9) : by;
            return { x: q.x - q.nx * d, z: q.z - q.nz * d,
                     nx: q.nx, nz: q.nz, r: q.r - d };
        });
    },

    // Заливка контура веером от центра: дно чаши и поверхность воды.
    // Протяжка сама дно не закрывает — у неё профиль начинается НА контуре,
    // а не в центре, и середина остаётся сквозной дырой.
    //
    // up === true — поверхность смотрит вверх (вода, дно изнутри).
    fan(plan, y, up) {
        const v = [0, y, 0], idx = [];
        for (const q of plan) v.push(q.x, y, q.z);
        for (let i = 1; i <= plan.length; i++) {
            const j = i === plan.length ? 1 : i + 1;
            if (up) idx.push(0, j, i); else idx.push(0, i, j);
        }
        const geo = new THREE.BufferGeometry();
        geo.setAttribute('position', new THREE.Float32BufferAttribute(v, 3));
        geo.setIndex(idx);
        geo.computeVertexNormals();
        // Контур запоминается: запекание выведет плоскость ОДНИМ путём, а не
        // веером треугольников со швами (см. bake-3d-core.js).
        geo.userData.outline = plan.map(q => ({ x: q.x, y, z: q.z }));
        return geo;
    },

    // ---------- ПРОТЯЖКА ПРОФИЛЯ ПО КОНТУРУ ----------
    // Обобщение тела вращения: вместо окружности профиль ведут по
    // произвольному замкнутому контуру. Этим и отличается ванна от таза.
    //
    // profile — точки сечения (x = вынос наружу от контура, y = высота),
    // plan — контур в плане с наружной нормалью в каждой точке,
    // R — на какой вынос профиля рассчитан контур (профиль нормируется).
    // j0..j1 — какой КУСОК профиля протягивать. Чаша собирается из двух
    // таких кусков (нутро и наружная стенка), потому что красятся они
    // разными рампами: у ванны внутри всегда темнее, чем снаружи, и без
    // этого перепада она читается белым слитком.
    sweep(profile, plan, R, j0, j1) {
        const v = [], idx = [];
        const N = plan.length, M = profile.length;
        const a0 = j0 == null ? 0 : j0, a1 = j1 == null ? M - 1 : j1;
        for (let i = 0; i < N; i++) {
            const q = plan[i];
            for (let j = 0; j < M; j++) {
                const pr = profile[j];
                // Вынос откладывается ПО НОРМАЛИ контура, и контур проходит
                // по НАРУЖНОМУ борту: точка профиля с выносом меньше R лежит
                // внутрь от него на (R - x).
                //
                // Стояло умножение на радиус скругления угла — то есть на
                // произвольное число, никак не связанное с профилем. Стенка
                // чаши и поверхность воды вставали в разные места, и между
                // ними зияла дыра.
                const off = pr.x - R;
                v.push(q.x + q.nx * off, pr.y, q.z + q.nz * off);
            }
        }
        for (let i = 0; i < N; i++) {
            const i2 = (i + 1) % N;
            for (let j = a0; j < a1; j++) {
                const a = i * M + j, b = i * M + j + 1;
                const c = i2 * M + j, d = i2 * M + j + 1;
                // Порядок обхода задаёт, КАКАЯ сторона поверхности лицевая.
                // С обратным (a,b,d / a,d,c) чаша была вывернута наизнанку:
                // отбраковка оставляла ровно не те грани — сквозь ванну
                // виднелась изнанка её же дальней НАРУЖНОЙ стенки, а спереди
                // стояла изнанка ближней ВНУТРЕННЕЙ. Форма при этом
                // случайно складывалась в «ёмкость», поэтому ошибку было
                // видно только по цвету: нутро выходило светлее наружной
                // стенки, борт не имел толщины, а свет ложился на грани,
                // которых зритель не видит.
                idx.push(a, d, b, a, c, d);
            }
        }
        const geo = new THREE.BufferGeometry();
        geo.setAttribute('position', new THREE.Float32BufferAttribute(v, 3));
        geo.setIndex(idx);
        geo.computeVertexNormals();
        return geo;
    },

    // Контур в плане: прямоугольник со скруглёнными углами. Возвращает точки
    // с наружной нормалью — по ней протяжка и откладывает вынос профиля.
    roundedPlan(len, wide, corner, segPerCorner) {
        const hx = len / 2 - corner, hz = wide / 2 - corner;
        const pts = [];
        // Четыре угла, каждый — дуга; между ними прямые участки получаются
        // сами, потому что соседние точки дуг лежат на одной нормали.
        const corners = [[hx, hz, 0], [-hx, hz, Math.PI / 2],
                         [-hx, -hz, Math.PI], [hx, -hz, Math.PI * 1.5]];
        for (const [cx, cz, a0] of corners) {
            for (let k = 0; k <= segPerCorner; k++) {
                const a = a0 + (k / segPerCorner) * (Math.PI / 2);
                const nx = Math.cos(a), nz = Math.sin(a);
                pts.push({ x: cx + nx * corner, z: cz + nz * corner,
                           nx, nz, r: corner });
            }
        }
        return pts;
    },

    // Меш из плоской геометрии: контур переносится на сам меш, потому что
    // запекание спрашивает его именно там.
    flat(geo) {
        const m = new THREE.Mesh(geo);
        m.userData.outline = geo.userData.outline;
        return m;
    },

    // ---------- ВСПОМОГАТЕЛЬНОЕ ----------
    // Скруглённая коробка: сегменты по углам, а не фаска в одну грань.
    // Одна фаска на угол читается срезом, а не скруглением.
    // bevel — насколько скруглена кромка по высоте. По умолчанию щедро:
    // так строятся мягкие предметы ванной. Твёрдому бруску (мыло) нужна
    // МЕЛКАЯ фаска: с крупной он читается подушкой, а не куском мыла.
    roundedBox(w, h, d, r, seg, bevel) {
        const shape = new THREE.Shape();
        const hw = w / 2 - r, hd = d / 2 - r;
        shape.moveTo(-hw, -hd - r);
        shape.lineTo(hw, -hd - r);
        shape.absarc(hw, -hd, r, -Math.PI / 2, 0, false);
        shape.lineTo(hw + r, hd);
        shape.absarc(hw, hd, r, 0, Math.PI / 2, false);
        shape.lineTo(-hw, hd + r);
        shape.absarc(-hw, hd, r, Math.PI / 2, Math.PI, false);
        shape.lineTo(-hw - r, -hd);
        shape.absarc(-hw, -hd, r, Math.PI, Math.PI * 1.5, false);
        const bv = bevel == null ? 0.18 : bevel;
        const geo = new THREE.ExtrudeGeometry(shape, {
            depth: h, bevelEnabled: bv > 0, bevelThickness: bv,
            bevelSize: bv, bevelSegments: 2, curveSegments: seg || 4
        });
        // Выдавливание идёт по Z; разворачиваем, чтобы высота была по Y.
        geo.rotateX(-Math.PI / 2);
        // Центрируем по высоте. Стояло +h/2, то есть коробка уезжала вверх
        // на всю свою высоту, и вода оказывалась НИЖЕ ванны.
        geo.translate(0, -h / 2, 0);
        return geo;
    },

    // Вывернуть нормали и обход: нужна внутренняя сторона оболочки.
    flip(geo) {
        const idx = geo.index;
        if (idx) {
            for (let i = 0; i < idx.count; i += 3) {
                const t = idx.getX(i);
                idx.setX(i, idx.getX(i + 2));
                idx.setX(i + 2, t);
            }
            idx.needsUpdate = true;
        }
        geo.computeVertexNormals();
        return geo;
    }
};
