// ================= ПОХОТЬ: ФИНАЛ С ПРИЦЕЛИВАНИЕМ =================
// Сколько капель ловит червь ртом и что игрок за это получает — на старте и
// на каждой ступени прокачки.
//
// ---------- ПОЧЕМУ СЧИТАТЬ ОБЯЗАТЕЛЬНО ----------
// Разброс здесь НАМЕРЕННО непредсказуемый: ни силы, ни угла следующего толчка
// игрок заранее не видит. Это осознанное решение — случайность и есть то, что
// покупается прокачкой. Но у такого решения одно жёсткое условие:
// **на старте, без всякой прокачки, забег должен в среднем приносить хотя бы
// один осколок.** Иначе новичок играет и не получает ничего, а прокачка,
// которая должна его спасти, покупается ровно за то, чего у него нет.
// Здесь это условие и проверяется.
//
// Модель одного толчка:
//   сила  ~ U(minPower, 1), долетает при силе >= REACH;
//   угол  = ε (разброс струи) + δ (насколько сбился хвост под пальцем);
//   попал, если долетел И |ε + δ| <= MOUTH.
//
// Прокачка двигает три числа: minPower (нижняя граница силы), spread (разброс
// струи), slop (податливость хвоста — насколько точно он держится там, куда
// его поставили).
//
// Запуск:  node tools/sim-lust.js

const SHOTS = 10;          // толчков за финал
const REACH = 0.5;         // какая сила нужна, чтобы струя долетела до рта
const MOUTH = 10;          // полураствор рта в градусах — допуск по углу
const PER_SECTION = 2;     // попаданий на одну секцию шкалы
const SECTIONS = 3;        // секций в шкале: 1 → осколок, 2 → два, 3 → жетон
const RUNS = 200000;

// Ступеней ровно три, и это результат расчёта, а не вкусовщина. Пятая
// ступень (сила от 0.68, разброс ±6°, хвост ±3°) давала те же 3.00 осколка,
// что и четвёртая: шкала упирается в потолок, и покупать дальше нечего.
// Последняя ступень должна доводить жетон почти до гарантии — и на этом
// лестница кончается.
const TIERS = [
    { name: 'старт',     minPower: 0.20, spread: 25, slop: 12 },
    { name: 'ступень 1', minPower: 0.32, spread: 20, slop: 9 },
    { name: 'ступень 2', minPower: 0.44, spread: 15, slop: 6 },
    { name: 'ступень 3', minPower: 0.56, spread: 10, slop: 4 }
];

function u(a, b) { return a + Math.random() * (b - a); }

function run(t) {
    let hits = 0;
    for (let i = 0; i < SHOTS; i++) {
        if (u(t.minPower, 1) < REACH) continue;               // не долетела
        if (Math.abs(u(-t.spread, t.spread) + u(-t.slop, t.slop)) <= MOUTH) hits++;
    }
    return hits;
}

// Осколки: каждая заполненная секция — осколок, полная шкала — жетон целиком
// (три осколка). Механизм размена уже есть в конфиге, ECONOMY.exchange.
function shards(hits) {
    return Math.min(SECTIONS, Math.floor(hits / PER_SECTION));
}

console.log(`финал ${SHOTS} толчков, секция = ${PER_SECTION} попадания, ` +
    `шкала ${SECTIONS} секции\n`);
console.log(['ступень', 'сила от', 'разброс', 'хвост', 'попаданий', 'осколков', 'пусто', 'жетон']
    .map(h => String(h).padStart(11)).join(''));

for (const t of TIERS) {
    let hits = 0, sh = 0, zero = 0, full = 0;
    for (let i = 0; i < RUNS; i++) {
        const h = run(t);
        const s = shards(h);
        hits += h; sh += s;
        if (s === 0) zero++;
        if (s === SECTIONS) full++;
    }
    console.log([t.name, t.minPower.toFixed(2), `±${t.spread}°`, `±${t.slop}°`,
        (hits / RUNS).toFixed(1), (sh / RUNS).toFixed(2),
        (zero / RUNS * 100).toFixed(1) + '%', (full / RUNS * 100).toFixed(1) + '%']
        .map(h => String(h).padStart(11)).join(''));
}

console.log('\nосколков за сутки (похоть пустеет за 12 ч → два захода):');
for (const t of TIERS) {
    let sh = 0;
    for (let i = 0; i < RUNS; i++) sh += shards(run(t));
    console.log(`  ${t.name.padEnd(10)} ${(sh / RUNS * 2).toFixed(2)} осколка ` +
        `= ${(sh / RUNS * 2 / 3).toFixed(2)} жетона`);
}
