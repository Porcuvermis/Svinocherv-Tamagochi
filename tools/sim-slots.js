// ================= АВТОМАТ АЛЧНОСТИ: ИСТОЧНИК ИЛИ СТОК =================
// Крутка стоит монету, заполняет шкалу алчности на 10% и иногда платит.
// Вопрос ровно один: сколько золота автомат в итоге ОТДАЁТ игроку.
//
// Возврат выше 100% ломает экономику мгновенно: круток никто не ограничивает,
// и лучшей стратегией в игре становится «сидеть и крутить вечно». Рабочий
// коридор — 60–80% (docs/plan/15-progression.md, раздел 10).
//
// Числа ставки, выплаты и гарантии — вверху файла: меняются там.
//
// Запуск из корня:  node tools/sim-slots.js
const SPIN = 1, PAY = 3, PITY = 6, SPINS_PER_FILL = 10;

console.log('доля возврата (RTP) при разной частоте выигрышей:\n');
console.log('выигрышей на 6 круток   возврат   на 10 круток (одна шкала)');
for (let wins = 1; wins <= 3; wins += 0.5) {
    const rtp = (wins * PAY) / (PITY * SPIN);
    const perFill = SPINS_PER_FILL * SPIN - SPINS_PER_FILL * (wins / PITY) * PAY;
    console.log(
        ('  ' + wins.toFixed(1)).padEnd(24) +
        (rtp * 100).toFixed(0).padStart(4) + '%    ' +
        (perFill > 0 ? ('игрок теряет ' + perFill.toFixed(1))
                     : ('игрок зарабатывает ' + (-perFill).toFixed(1))) +
        (Math.abs(perFill) < 0.6 ? '   ← почти в ноль' : '') +
        (perFill < -0.6 ? '   ← печатный станок' : ''));
}

console.log('\nпри гарантии «раз в 6 круток» и выплате 3 нижняя граница возврата — '
    + ((PAY / PITY) * 100).toFixed(0) + '%.');
console.log('всё, что сверху, добавляют случайные выигрыши: они и есть ручка настройки.');
